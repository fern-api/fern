<?php

namespace Seed\Types;

use Seed\Core\Json\JsonSerializableType;
use Seed\Core\Json\JsonProperty;
use Seed\Core\Types\ArrayType;

/**
 * RFC 9457 Problem Details returned for every error response.
 */
class ServiceErrorResponse extends JsonSerializableType
{
    /**
     * @var string $type A URI reference that identifies the problem type.
     */
    #[JsonProperty('type')]
    public string $type;

    /**
     * @var string $title A short, human-readable summary of the problem type.
     */
    #[JsonProperty('title')]
    public string $title;

    /**
     * @var int $status The HTTP status code generated by the origin server for this occurrence of the problem.
     */
    #[JsonProperty('status')]
    public int $status;

    /**
     * @var ?string $detail A human-readable explanation specific to this occurrence of the problem.
     */
    #[JsonProperty('detail')]
    public ?string $detail;

    /**
     * @var ?string $instance A URI reference that identifies the specific occurrence of the problem.
     */
    #[JsonProperty('instance')]
    public ?string $instance;

    /**
     * @var ?int $code Service-specific error code.
     */
    #[JsonProperty('code')]
    public ?int $code;

    /**
     * @var ?array<ServiceErrorResponseErrorsItem> $errors Field-level validation failures.
     */
    #[JsonProperty('errors'), ArrayType([ServiceErrorResponseErrorsItem::class])]
    public ?array $errors;

    /**
     * @param array{
     *   type: string,
     *   title: string,
     *   status: int,
     *   detail?: ?string,
     *   instance?: ?string,
     *   code?: ?int,
     *   errors?: ?array<ServiceErrorResponseErrorsItem>,
     * } $values
     */
    public function __construct(
        array $values,
    ) {
        $this->type = $values['type'];
        $this->title = $values['title'];
        $this->status = $values['status'];
        $this->detail = $values['detail'] ?? null;
        $this->instance = $values['instance'] ?? null;
        $this->code = $values['code'] ?? null;
        $this->errors = $values['errors'] ?? null;
    }

    /**
     * @return string
     */
    public function __toString(): string
    {
        return $this->toJson();
    }
}
