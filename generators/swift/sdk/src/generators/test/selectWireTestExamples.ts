import { FernIr } from "@fern-fern/ir-sdk";

/** The parts of an IR example endpoint call that example selection depends on. */
export interface WireTestExampleCall {
    id?: string;
    response: { type: "ok" } | { type: "error"; error: { errorId: string } };
}

export interface SelectedWireTestExample<T extends WireTestExampleCall> {
    example: T;
    /** ID of the matching example in the dynamic IR, used to generate the call snippet. */
    dynamicExampleId: string;
}

/**
 * Selects the examples to generate wire tests for, mirroring the other generators: all user-specified
 * examples (or the first autogenerated success example when there are none), plus the autogenerated
 * error examples (one per error) when no user-specified example covers an error.
 */
export function selectWireTestExamples<T extends WireTestExampleCall>(
    endpoint: {
        id: string;
        userSpecifiedExamples: readonly { example?: T }[];
        autogeneratedExamples: readonly { example: T }[];
    },
    { includeAutogeneratedErrorExamples }: { includeAutogeneratedErrorExamples: boolean }
): SelectedWireTestExample<T>[] {
    // Fallback IDs match the ones the dynamic IR converter assigns to examples without an ID.
    const userExamples = endpoint.userSpecifiedExamples.flatMap((example, index) =>
        example.example != null
            ? [{ example: example.example, dynamicExampleId: example.example.id ?? `${endpoint.id}-user-${index}` }]
            : []
    );
    const autogeneratedExamples = endpoint.autogeneratedExamples.map((example, index) => ({
        example: example.example,
        dynamicExampleId: example.example.id ?? `${endpoint.id}-auto-${index}`
    }));
    const isError = ({ example }: SelectedWireTestExample<T>) => example.response.type === "error";

    const selected = [...userExamples];
    if (userExamples.length === 0) {
        const firstSuccessExample = autogeneratedExamples.find((example) => !isError(example));
        if (firstSuccessExample != null) {
            selected.push(firstSuccessExample);
        }
    }
    if (includeAutogeneratedErrorExamples && !userExamples.some(isError)) {
        const seenErrorIds = new Set<string>();
        for (const autogeneratedExample of autogeneratedExamples) {
            const response = autogeneratedExample.example.response;
            if (response.type !== "error" || seenErrorIds.has(response.error.errorId)) {
                continue;
            }
            seenErrorIds.add(response.error.errorId);
            selected.push(autogeneratedExample);
        }
    }
    return selected;
}

/**
 * The endpoint's declared success status code. Falls back to 200 for undeclared or non-2xx codes,
 * and for bodiless status codes (204/205) on endpoints that return a body.
 */
export function getWireTestSuccessStatusCode(endpoint: Pick<FernIr.HttpEndpoint, "response">): number {
    const statusCode = endpoint.response?.statusCode;
    if (statusCode == null || statusCode < 200 || statusCode >= 300) {
        return 200;
    }
    if ((statusCode === 204 || statusCode === 205) && endpoint.response?.body != null) {
        return 200;
    }
    return statusCode;
}

export interface ExpectedHTTPErrorResponseBody {
    code: number;
    type: string | undefined;
    message: string | undefined;
}

/**
 * The `HTTPError.ResponseBody` the generated SDK parses from an error response body, mirroring
 * `HTTPError.ResponseBody.decode`: a typed `{ code, type?, message? }` payload first, then a JSON
 * object with a string `message`, then the raw body as plain text. Returns `undefined` for an empty body.
 */
export function getExpectedHTTPErrorResponseBody({
    statusCode,
    json,
    rawBody
}: {
    statusCode: number;
    json: unknown;
    rawBody: string;
}): ExpectedHTTPErrorResponseBody | undefined {
    if (isJsonObject(json)) {
        const { code, type, message } = json;
        if (typeof code === "number" && isSwiftInt(code) && isOptionalString(type) && isOptionalString(message)) {
            return { code, type: type ?? undefined, message: message ?? undefined };
        }
        if (typeof message === "string") {
            return { code: statusCode, type: undefined, message };
        }
    }
    if (rawBody.length > 0) {
        return { code: statusCode, type: undefined, message: rawBody };
    }
    return undefined;
}

function isJsonObject(value: unknown): value is Record<string, unknown> {
    return value != null && typeof value === "object" && !Array.isArray(value);
}

function isOptionalString(value: unknown): value is string | null | undefined {
    return value == null || typeof value === "string";
}

/** `HTTPError.ResponseBody.code` is a 64-bit Swift `Int`. */
function isSwiftInt(value: number): boolean {
    return Number.isInteger(value) && Math.abs(value) < 2 ** 63;
}
