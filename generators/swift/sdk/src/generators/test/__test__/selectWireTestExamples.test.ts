import { describe, expect, it } from "vitest";

import {
    getExpectedHTTPErrorResponseBody,
    getWireTestSuccessStatusCode,
    selectWireTestExamples,
    WireTestExampleCall
} from "../selectWireTestExamples.js";

const ok = (id?: string): WireTestExampleCall => ({ id, response: { type: "ok" } });
const error = (errorId: string, id?: string): WireTestExampleCall => ({
    id,
    response: { type: "error", error: { errorId } }
});

function select(
    userExamples: WireTestExampleCall[],
    autogeneratedExamples: WireTestExampleCall[],
    includeAutogeneratedErrorExamples = true
): string[] {
    return selectWireTestExamples(
        {
            id: "endpoint",
            userSpecifiedExamples: userExamples.map((example) => ({ example })),
            autogeneratedExamples: autogeneratedExamples.map((example) => ({ example }))
        },
        { includeAutogeneratedErrorExamples }
    ).map(({ dynamicExampleId }) => dynamicExampleId);
}

describe("selectWireTestExamples", () => {
    it("keeps every user example and adds autogenerated errors once per error", () => {
        expect(
            select([ok("u1"), ok()], [ok("a1"), error("NotFound", "a2"), error("NotFound", "a3"), error("BadRequest")])
        ).toEqual(["u1", "endpoint-user-1", "a2", "endpoint-auto-3"]);
    });

    it("falls back to the first autogenerated success example", () => {
        expect(select([], [error("NotFound", "a1"), ok("a2"), ok("a3")])).toEqual(["a2", "a1"]);
    });

    it("skips autogenerated errors when a user example is an error", () => {
        expect(select([ok("u1"), error("NotFound", "u2")], [error("BadRequest", "a1")])).toEqual(["u1", "u2"]);
    });

    it("skips autogenerated errors when the fallback is disabled", () => {
        expect(select([ok("u1")], [error("NotFound", "a1")], false)).toEqual(["u1"]);
    });
});

describe("getWireTestSuccessStatusCode", () => {
    it("uses the declared 2xx status code", () => {
        expect(
            getWireTestSuccessStatusCode({
                response: { statusCode: 201, isWildcardStatusCode: undefined, body: undefined, docs: undefined }
            })
        ).toBe(201);
        expect(
            getWireTestSuccessStatusCode({
                response: { statusCode: 204, isWildcardStatusCode: undefined, body: undefined, docs: undefined }
            })
        ).toBe(204);
    });

    it("falls back to 200", () => {
        expect(getWireTestSuccessStatusCode({ response: undefined })).toBe(200);
        expect(
            getWireTestSuccessStatusCode({
                response: { statusCode: 302, isWildcardStatusCode: undefined, body: undefined, docs: undefined }
            })
        ).toBe(200);
    });
});

describe("getExpectedHTTPErrorResponseBody", () => {
    const parse = (json: unknown) =>
        getExpectedHTTPErrorResponseBody({
            statusCode: 404,
            json,
            rawBody: json === undefined ? "" : JSON.stringify(json, null, 2)
        });

    it("decodes a typed error payload", () => {
        expect(parse({ code: 7, type: "missing", message: "gone", extra: true })).toEqual({
            code: 7,
            type: "missing",
            message: "gone"
        });
    });

    it("falls back to the message field with the status code", () => {
        expect(parse({ message: "gone", code: "E1" })).toEqual({ code: 404, type: undefined, message: "gone" });
    });

    it("falls back to the raw body as plain text", () => {
        expect(parse({ code: 1.5 })).toEqual({ code: 404, type: undefined, message: '{\n  "code": 1.5\n}' });
        expect(parse("gone")).toEqual({ code: 404, type: undefined, message: '"gone"' });
    });

    it("returns undefined for an empty body", () => {
        expect(parse(undefined)).toBeUndefined();
    });
});
