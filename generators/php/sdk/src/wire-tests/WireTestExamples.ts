import { FernIr } from "@fern-fern/ir-sdk";
import { SdkGeneratorContext } from "../SdkGeneratorContext.js";

export interface WireTestExpectedError {
    statusCode: number;
    /** PascalCase name of the error declaration, used to name the test. */
    errorName: string;
    /** The example's error body, asserted against the exception body when present. */
    body: unknown;
}

export interface WireTestExample {
    example: FernIr.ExampleEndpointCall;
    /** ID of the matching example in the dynamic IR, used to generate the call snippet. */
    dynamicExampleId: string;
    /** Sent as the `X-Test-Id` header and matched by the example's WireMock stub. */
    testId: string;
    /** PascalCase name of the example, if it has one. */
    exampleName?: string;
    /** Set for error examples: the error the generated client is expected to throw. */
    expectedError?: WireTestExpectedError;
}

/**
 * Selects the examples to generate wire tests for, mirroring the other generators: all user-specified
 * examples, plus the autogenerated error examples (one per error) when no user example covers an error.
 * Endpoints without user examples use the first autogenerated success example.
 */
export class WireTestExamples {
    private readonly cache = new Map<string, WireTestExample[]>();

    constructor(private readonly context: SdkGeneratorContext) {}

    public get(service: FernIr.HttpService, endpoint: FernIr.HttpEndpoint): WireTestExample[] {
        const cached = this.cache.get(endpoint.id);
        if (cached != null) {
            return cached;
        }
        const examples = this.select(service, endpoint);
        this.cache.set(endpoint.id, examples);
        return examples;
    }

    public getTestId(
        service: FernIr.HttpService,
        endpoint: FernIr.HttpEndpoint,
        example: FernIr.ExampleEndpointCall
    ): string | undefined {
        return this.get(service, endpoint).find(
            (testExample) =>
                testExample.example === example || (example.id != null && testExample.example.id === example.id)
        )?.testId;
    }

    private select(service: FernIr.HttpService, endpoint: FernIr.HttpEndpoint): WireTestExample[] {
        const userExamples = endpoint.userSpecifiedExamples.flatMap((example, index) =>
            example.example != null
                ? [{ example: example.example, dynamicExampleId: example.example.id ?? `${endpoint.id}-user-${index}` }]
                : []
        );
        const autogeneratedExamples = endpoint.autogeneratedExamples.flatMap((example, index) =>
            example.example != null
                ? [{ example: example.example, dynamicExampleId: example.example.id ?? `${endpoint.id}-auto-${index}` }]
                : []
        );
        const isError = ({ example }: { example: FernIr.ExampleEndpointCall }) => example.response.type === "error";

        const selected = [...userExamples];
        if (userExamples.length === 0) {
            const firstSuccessExample = autogeneratedExamples.find((example) => !isError(example));
            if (firstSuccessExample != null) {
                selected.push(firstSuccessExample);
            }
        }
        if (this.context.customConfig.wireTestsFallbackToAutogeneratedErrorExamples && !userExamples.some(isError)) {
            const seenErrorIds = new Set<string>();
            for (const autogeneratedExample of autogeneratedExamples) {
                const response = autogeneratedExample.example.response;
                if (response.type !== "error" || seenErrorIds.has(response.error.errorId)) {
                    continue;
                }
                seenErrorIds.add(response.error.errorId);
                selected.push(autogeneratedExample);
            }
        }

        const testExamples: WireTestExample[] = [];
        for (const { example, dynamicExampleId } of selected) {
            let expectedError: WireTestExpectedError | undefined;
            if (example.response.type === "error") {
                expectedError = this.getExpectedError(example.response);
                if (expectedError == null) {
                    continue;
                }
            }
            testExamples.push({
                example,
                dynamicExampleId,
                testId: this.buildTestId(service, endpoint, testExamples.length),
                exampleName:
                    example.name != null
                        ? this.context.case.pascalSafe(example.name).replace(/[^A-Za-z0-9_]/g, "")
                        : undefined,
                expectedError
            });
        }
        return testExamples;
    }

    /**
     * The generated client throws the base API exception for every non-2XX/3XX response, with the
     * response status code and raw body. WireMock serves error examples with the status code declared
     * on the error, so errors declared with a non-error status code can't be asserted and are skipped.
     */
    private getExpectedError(response: FernIr.ExampleEndpointErrorResponse): WireTestExpectedError | undefined {
        const errorDeclaration = this.context.ir.errors[response.error.errorId];
        if (errorDeclaration == null || errorDeclaration.statusCode < 400) {
            return undefined;
        }
        return {
            statusCode: errorDeclaration.statusCode,
            errorName: this.context.case.pascalSafe(errorDeclaration.name.name).replace(/[^A-Za-z0-9_]/g, ""),
            body: response.body?.jsonExample
        };
    }

    private buildTestId(service: FernIr.HttpService, endpoint: FernIr.HttpEndpoint, index: number): string {
        const servicePathParts = service.name.fernFilepath.allParts.map((part) => this.context.case.snakeSafe(part));
        const segments: string[] = [];
        if (servicePathParts.length > 0) {
            segments.push(servicePathParts.join("."));
        }
        segments.push(this.context.case.snakeSafe(endpoint.name));
        segments.push(String(index));
        return segments.join(".");
    }
}
