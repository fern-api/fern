import { CaseConverter } from "@fern-api/base-generator";
import { FernIr } from "@fern-fern/ir-sdk";
import { PackageId } from "@fern-typescript/commons";
import { PackageResolver } from "@fern-typescript/resolvers";

const FILE_HEADER = `// This file was auto-generated by Fern from our API Definition.\n\n`;

export declare namespace ReactQueryGenerator {
    interface Args {
        intermediateRepresentation: FernIr.IntermediateRepresentation;
        packageResolver: PackageResolver;
        namespaceExport: string;
        clientClassName: string;
        caseConverter: CaseConverter;
        npmPackageName: string | undefined;
        relativePackagePath: string;
    }
}

interface EndpointHookInfo {
    serviceAccessPath: string[];
    endpointCamelName: string;
    method: string;
    hasArgs: boolean;
    docs: string | undefined;
}

interface NamespaceNode {
    endpoints: EndpointHookInfo[];
    children: Map<string, NamespaceNode>;
}

export class ReactQueryGenerator {
    private readonly ir: FernIr.IntermediateRepresentation;
    private readonly packageResolver: PackageResolver;
    private readonly namespaceExport: string;
    private readonly clientClassName: string;
    private readonly case: CaseConverter;
    private readonly npmPackageName: string | undefined;
    private readonly relativePackagePath: string;

    constructor(args: ReactQueryGenerator.Args) {
        this.ir = args.intermediateRepresentation;
        this.packageResolver = args.packageResolver;
        this.namespaceExport = args.namespaceExport;
        this.clientClassName = args.clientClassName;
        this.case = args.caseConverter;
        this.npmPackageName = args.npmPackageName;
        this.relativePackagePath = args.relativePackagePath;
    }

    public generateFiles(): { files: Record<string, string>; serviceExportPaths: string[] } {
        const files: Record<string, string> = {};
        const serviceExportPaths: string[] = [];
        const srcPrefix = this.relativePackagePath;

        const endpoints = this.collectEndpoints();
        const hasHooks = endpoints.length > 0;

        files[`${srcPrefix}/react-query/index.ts`] = this.generateIndexFile(hasHooks);
        files[`${srcPrefix}/react-query/context.ts`] = this.generateContextFile();
        files[`${srcPrefix}/react-query/types.ts`] = this.generateTypesFile();

        if (hasHooks) {
            const tree = this.buildEndpointTree(endpoints);

            // Generate per-service files for each top-level service
            for (const [serviceName, serviceNode] of tree.children) {
                files[`${srcPrefix}/react-query/${serviceName}/index.ts`] = this.generateServiceFile(
                    serviceName,
                    serviceNode,
                    [serviceName]
                );
                serviceExportPaths.push(`react-query/${serviceName}`);
            }

            // Generate main hooks file that imports from per-service files
            files[`${srcPrefix}/react-query/hooks.ts`] = this.generateMainHooksFile(tree);
        }

        return { files, serviceExportPaths };
    }

    private getNamespaceName(): string {
        const name = this.clientClassName;
        // SeedApiClient -> seedApi, AcmeClient -> acme, MyApiClient -> myApi
        const withoutClient = name.endsWith("Client") ? name.slice(0, -"Client".length) : name;
        return withoutClient.charAt(0).toLowerCase() + withoutClient.slice(1);
    }

    private getQueryKeyPrefix(): string {
        return this.npmPackageName ?? this.namespaceExport;
    }

    private generateIndexFile(hasHooks: boolean): string {
        const clientName = this.clientClassName;
        let content =
            FILE_HEADER +
            `export { ${clientName}Provider, use${clientName}Context } from "./context.js";\n` +
            `export type { ${clientName}ProviderProps } from "./context.js";\n` +
            `export { type QueryKey } from "@tanstack/react-query";\n` +
            `export type { QueryHookOptions, SuspenseQueryHookOptions, InfiniteQueryHookOptions, SuspenseInfiniteQueryHookOptions, MutationHookOptions } from "./types.js";\n`;
        if (hasHooks) {
            content += `export { ${this.getNamespaceName()} } from "./hooks.js";\n`;
        }
        return content;
    }

    private generateContextFile(): string {
        const clientName = this.clientClassName;

        return (
            FILE_HEADER +
            `import { createContext, useContext, createElement } from "react";\n` +
            `import type { ReactNode, ReactElement } from "react";\n` +
            `import type { ${clientName} } from "../index.js";\n` +
            `\n` +
            `const ${clientName}Context = createContext<${clientName} | null>(null);\n` +
            `\n` +
            `export interface ${clientName}ProviderProps {\n` +
            `    client: ${clientName};\n` +
            `    children: ReactNode;\n` +
            `}\n` +
            `\n` +
            `export function ${clientName}Provider(props: ${clientName}ProviderProps): ReactElement {\n` +
            `    return createElement(${clientName}Context.Provider, { value: props.client }, props.children);\n` +
            `}\n` +
            `\n` +
            `export function use${clientName}Context(): ${clientName} {\n` +
            `    const value = useContext(${clientName}Context);\n` +
            `    if (value === null) {\n` +
            `        throw new Error(\n` +
            `            "${clientName} not initialized. Create an instance of ${clientName} and pass it to <${clientName}Provider />."\n` +
            `        );\n` +
            `    }\n` +
            `    return value;\n` +
            `}\n`
        );
    }

    private generateTypesFile(): string {
        return (
            FILE_HEADER +
            `import type {\n` +
            `    UseQueryOptions,\n` +
            `    UseMutationOptions,\n` +
            `    UseSuspenseQueryOptions,\n` +
            `    UseInfiniteQueryOptions,\n` +
            `    UseSuspenseInfiniteQueryOptions,\n` +
            `    InfiniteData,\n` +
            `} from "@tanstack/react-query";\n` +
            `\n` +
            `export type QueryHookOptions<TData, TError = Error> = Omit<\n` +
            `    UseQueryOptions<TData, TError>,\n` +
            `    "queryKey" | "queryFn"\n` +
            `>;\n` +
            `\n` +
            `export type SuspenseQueryHookOptions<TData, TError = Error> = Omit<\n` +
            `    UseSuspenseQueryOptions<TData, TError>,\n` +
            `    "queryKey" | "queryFn"\n` +
            `>;\n` +
            `\n` +
            `export type InfiniteQueryHookOptions<TData, TError = Error, TPageParam = unknown> = Omit<\n` +
            `    UseInfiniteQueryOptions<TData, TError, InfiniteData<TData>, readonly unknown[], TPageParam>,\n` +
            `    "queryKey" | "queryFn" | "initialPageParam" | "getNextPageParam"\n` +
            `>;\n` +
            `\n` +
            `export type SuspenseInfiniteQueryHookOptions<TData, TError = Error, TPageParam = unknown> = Omit<\n` +
            `    UseSuspenseInfiniteQueryOptions<TData, TError, InfiniteData<TData>, readonly unknown[], TPageParam>,\n` +
            `    "queryKey" | "queryFn" | "initialPageParam" | "getNextPageParam"\n` +
            `>;\n` +
            `\n` +
            `export type MutationHookOptions<TData, TError = Error, TVariables = void> = Omit<\n` +
            `    UseMutationOptions<TData, TError, TVariables>,\n` +
            `    "mutationKey" | "mutationFn"\n` +
            `>;\n`
        );
    }

    private generateHookImports(
        queryEndpoints: EndpointHookInfo[],
        mutationEndpoints: EndpointHookInfo[],
        clientName: string,
        isServiceFile: boolean
    ): string {
        let content = "";
        const reactQueryImports: string[] = [];

        if (queryEndpoints.length > 0) {
            reactQueryImports.push(
                "useQuery",
                "useSuspenseQuery",
                "useInfiniteQuery",
                "useSuspenseInfiniteQuery",
                "type UseQueryResult",
                "type UseSuspenseQueryResult",
                "type UseInfiniteQueryResult",
                "type UseSuspenseInfiniteQueryResult",
                "type InfiniteData",
                "type QueryKey",
                "type QueryClient"
            );
        }
        if (mutationEndpoints.length > 0) {
            reactQueryImports.push("useMutation", "type UseMutationResult");
            if (queryEndpoints.length === 0) {
                reactQueryImports.push("type QueryClient");
            }
        }
        content += `import { ${reactQueryImports.join(", ")} } from "@tanstack/react-query";\n`;

        const clientImportPath = isServiceFile ? "../../index.js" : "../index.js";
        const contextImportPath = isServiceFile ? "../context.js" : "./context.js";
        const typesImportPath = isServiceFile ? "../types.js" : "./types.js";

        content += `import type { ${clientName} } from "${clientImportPath}";\n`;
        content += `import { use${clientName}Context } from "${contextImportPath}";\n`;

        const typeImports: string[] = [];
        if (queryEndpoints.length > 0) {
            typeImports.push(
                "QueryHookOptions",
                "SuspenseQueryHookOptions",
                "InfiniteQueryHookOptions",
                "SuspenseInfiniteQueryHookOptions"
            );
        }
        if (mutationEndpoints.length > 0) {
            typeImports.push("MutationHookOptions");
        }
        content += `import type { ${typeImports.join(", ")} } from "${typesImportPath}";\n`;

        return content;
    }

    private generateServiceFile(serviceName: string, node: NamespaceNode, path: string[]): string {
        const clientName = this.clientClassName;
        const queryKeyPrefix = this.getQueryKeyPrefix();

        const allEndpoints = this.collectEndpointsFromNode(node);
        const queryEndpoints = allEndpoints.filter((e) => this.isQueryMethod(e.method));
        const mutationEndpoints = allEndpoints.filter((e) => !this.isQueryMethod(e.method));

        let content = FILE_HEADER;
        content += this.generateHookImports(queryEndpoints, mutationEndpoints, clientName, true);
        content += `\n`;
        content += `export const ${serviceName} = `;
        content += this.generateNamespaceObject(node, queryKeyPrefix, clientName, path, 0);
        content += `;\n`;

        return content;
    }

    private generateMainHooksFile(tree: NamespaceNode): string {
        const clientName = this.clientClassName;
        const queryKeyPrefix = this.getQueryKeyPrefix();
        const namespaceName = this.getNamespaceName();

        const serviceNames = [...tree.children.keys()];
        const rootEndpoints = tree.endpoints;
        const rootQueryEndpoints = rootEndpoints.filter((e) => this.isQueryMethod(e.method));
        const rootMutationEndpoints = rootEndpoints.filter((e) => !this.isQueryMethod(e.method));
        const hasRootEndpoints = rootEndpoints.length > 0;

        let content = FILE_HEADER;

        // Import per-service namespaces
        for (const serviceName of serviceNames) {
            content += `import { ${serviceName} } from "./${serviceName}/index.js";\n`;
        }

        if (hasRootEndpoints) {
            content += this.generateHookImports(rootQueryEndpoints, rootMutationEndpoints, clientName, false);
        } else {
            content += `import { type QueryClient } from "@tanstack/react-query";\n`;
        }

        content += `\n`;

        // Build explicit type annotation for --isolatedDeclarations compatibility
        content += `export const ${namespaceName}: {\n`;
        for (const endpoint of rootEndpoints) {
            if (endpoint.docs) {
                content += `    /** ${endpoint.docs} */\n`;
            }
            const returnType = `Awaited<ReturnType<${clientName}["${endpoint.endpointCamelName}"]>>`;
            if (this.isQueryMethod(endpoint.method)) {
                content += `    ${endpoint.endpointCamelName}: Record<string, unknown>;\n`;
            } else {
                content += `    ${endpoint.endpointCamelName}: Record<string, unknown>;\n`;
            }
        }
        for (const serviceName of serviceNames) {
            content += `    ${serviceName}: typeof import("./${serviceName}/index.js").${serviceName};\n`;
        }
        content += `    invalidate(queryClient: QueryClient): Promise<void>;\n`;
        content += `} = {\n`;

        // Root-level endpoints (generated inline)
        for (const endpoint of rootEndpoints) {
            if (endpoint.docs) {
                content += `    /** ${endpoint.docs} */\n`;
            }
            content += `    ${endpoint.endpointCamelName}: `;
            content += this.generateEndpointNode(endpoint, queryKeyPrefix, clientName, [], 1);
            content += `,\n`;
        }

        // Service namespaces
        for (const serviceName of serviceNames) {
            content += `    ${serviceName}: ${serviceName},\n`;
        }

        // Root-level invalidate
        content += `    invalidate(queryClient: QueryClient): Promise<void> {\n`;
        content += `        return queryClient.invalidateQueries({ queryKey: ["${queryKeyPrefix}"] });\n`;
        content += `    },\n`;

        content += `};\n`;

        return content;
    }

    private buildEndpointTree(endpoints: EndpointHookInfo[]): NamespaceNode {
        const root: NamespaceNode = { endpoints: [], children: new Map() };

        for (const endpoint of endpoints) {
            let current = root;
            for (const segment of endpoint.serviceAccessPath) {
                let child = current.children.get(segment);
                if (child == null) {
                    child = { endpoints: [], children: new Map() };
                    current.children.set(segment, child);
                }
                current = child;
            }
            current.endpoints.push(endpoint);
        }

        return root;
    }

    private collectEndpointsFromNode(node: NamespaceNode): EndpointHookInfo[] {
        const endpoints = [...node.endpoints];
        for (const child of node.children.values()) {
            endpoints.push(...this.collectEndpointsFromNode(child));
        }
        return endpoints;
    }

    private generateNamespaceObject(
        node: NamespaceNode,
        queryKeyPrefix: string,
        clientName: string,
        path: string[],
        depth: number
    ): string {
        const indent = "    ".repeat(depth);
        const innerIndent = "    ".repeat(depth + 1);

        let content = "{\n";

        // Generate endpoint entries
        for (const endpoint of node.endpoints) {
            if (endpoint.docs) {
                content += `${innerIndent}/** ${endpoint.docs} */\n`;
            }
            content += `${innerIndent}${endpoint.endpointCamelName}: `;
            content += this.generateEndpointNode(endpoint, queryKeyPrefix, clientName, path, depth + 1);
            content += `,\n`;
        }

        // Generate child service namespaces
        for (const [name, child] of node.children) {
            content += `${innerIndent}${name}: `;
            content += this.generateNamespaceObject(child, queryKeyPrefix, clientName, [...path, name], depth + 1);
            content += `,\n`;
        }

        // Generate invalidate method at this level
        const queryKeyParts = [queryKeyPrefix, ...path].map((p) => `"${p}"`).join(", ");
        content += `${innerIndent}invalidate(queryClient: QueryClient): Promise<void> {\n`;
        content += `${innerIndent}    return queryClient.invalidateQueries({ queryKey: [${queryKeyParts}] });\n`;
        content += `${innerIndent}},\n`;

        content += `${indent}}`;
        return content;
    }

    private generateEndpointNode(
        endpoint: EndpointHookInfo,
        queryKeyPrefix: string,
        clientName: string,
        servicePath: string[],
        depth: number
    ): string {
        if (this.isQueryMethod(endpoint.method)) {
            return this.generateQueryEndpointNode(endpoint, queryKeyPrefix, clientName, servicePath, depth);
        }
        return this.generateMutationEndpointNode(endpoint, queryKeyPrefix, clientName, servicePath, depth);
    }

    private generateQueryEndpointNode(
        endpoint: EndpointHookInfo,
        queryKeyPrefix: string,
        clientName: string,
        servicePath: string[],
        depth: number
    ): string {
        const { endpointCamelName, hasArgs } = endpoint;
        const indent = "    ".repeat(depth);
        const innerIndent = "    ".repeat(depth + 1);

        const clientAccessor = this.buildClientAccessor(servicePath);
        const methodType = `${clientName}${servicePath.map((s) => `["${s}"]`).join("")}["${endpointCamelName}"]`;
        const dataType = `Awaited<ReturnType<${methodType}>>`;
        const queryKeyParts = [queryKeyPrefix, ...servicePath, endpointCamelName].map((p) => `"${p}"`).join(", ");

        let content = "{\n";

        // useQuery
        if (hasArgs) {
            content += `${innerIndent}useQuery(\n`;
            content += `${innerIndent}    args: Parameters<${methodType}>,\n`;
            content += `${innerIndent}    options?: QueryHookOptions<${dataType}>,\n`;
            content += `${innerIndent}): UseQueryResult<${dataType}> {\n`;
            content += `${innerIndent}    const client = use${clientName}Context();\n`;
            content += `${innerIndent}    return useQuery({\n`;
            content += `${innerIndent}        queryKey: [${queryKeyParts}, ...args] as const,\n`;
            content += `${innerIndent}        queryFn: () => client${clientAccessor}.${endpointCamelName}(...args),\n`;
            content += `${innerIndent}        ...options,\n`;
            content += `${innerIndent}    });\n`;
            content += `${innerIndent}},\n`;
        } else {
            content += `${innerIndent}useQuery(\n`;
            content += `${innerIndent}    options?: QueryHookOptions<${dataType}>,\n`;
            content += `${innerIndent}): UseQueryResult<${dataType}> {\n`;
            content += `${innerIndent}    const client = use${clientName}Context();\n`;
            content += `${innerIndent}    return useQuery({\n`;
            content += `${innerIndent}        queryKey: [${queryKeyParts}] as const,\n`;
            content += `${innerIndent}        queryFn: () => client${clientAccessor}.${endpointCamelName}(),\n`;
            content += `${innerIndent}        ...options,\n`;
            content += `${innerIndent}    });\n`;
            content += `${innerIndent}},\n`;
        }

        // useSuspenseQuery
        if (hasArgs) {
            content += `${innerIndent}useSuspenseQuery(\n`;
            content += `${innerIndent}    args: Parameters<${methodType}>,\n`;
            content += `${innerIndent}    options?: SuspenseQueryHookOptions<${dataType}>,\n`;
            content += `${innerIndent}): UseSuspenseQueryResult<${dataType}> {\n`;
            content += `${innerIndent}    const client = use${clientName}Context();\n`;
            content += `${innerIndent}    return useSuspenseQuery({\n`;
            content += `${innerIndent}        queryKey: [${queryKeyParts}, ...args] as const,\n`;
            content += `${innerIndent}        queryFn: () => client${clientAccessor}.${endpointCamelName}(...args),\n`;
            content += `${innerIndent}        ...options,\n`;
            content += `${innerIndent}    });\n`;
            content += `${innerIndent}},\n`;
        } else {
            content += `${innerIndent}useSuspenseQuery(\n`;
            content += `${innerIndent}    options?: SuspenseQueryHookOptions<${dataType}>,\n`;
            content += `${innerIndent}): UseSuspenseQueryResult<${dataType}> {\n`;
            content += `${innerIndent}    const client = use${clientName}Context();\n`;
            content += `${innerIndent}    return useSuspenseQuery({\n`;
            content += `${innerIndent}        queryKey: [${queryKeyParts}] as const,\n`;
            content += `${innerIndent}        queryFn: () => client${clientAccessor}.${endpointCamelName}(),\n`;
            content += `${innerIndent}        ...options,\n`;
            content += `${innerIndent}    });\n`;
            content += `${innerIndent}},\n`;
        }

        // useInfiniteQuery
        if (hasArgs) {
            content += `${innerIndent}useInfiniteQuery<TPageParam = unknown>(\n`;
            content += `${innerIndent}    args: Parameters<${methodType}>,\n`;
            content += `${innerIndent}    options: InfiniteQueryHookOptions<${dataType}, Error, TPageParam> & { initialPageParam: TPageParam; getNextPageParam: (lastPage: ${dataType}, allPages: ${dataType}[]) => TPageParam | undefined },\n`;
            content += `${innerIndent}): UseInfiniteQueryResult<InfiniteData<${dataType}>> {\n`;
            content += `${innerIndent}    const client = use${clientName}Context();\n`;
            content += `${innerIndent}    const { initialPageParam, getNextPageParam, ...rest } = options;\n`;
            content += `${innerIndent}    return useInfiniteQuery({\n`;
            content += `${innerIndent}        queryKey: [${queryKeyParts}, ...args] as const,\n`;
            content += `${innerIndent}        queryFn: () => client${clientAccessor}.${endpointCamelName}(...args),\n`;
            content += `${innerIndent}        initialPageParam,\n`;
            content += `${innerIndent}        getNextPageParam,\n`;
            content += `${innerIndent}        ...rest,\n`;
            content += `${innerIndent}    });\n`;
            content += `${innerIndent}},\n`;
        } else {
            content += `${innerIndent}useInfiniteQuery<TPageParam = unknown>(\n`;
            content += `${innerIndent}    options: InfiniteQueryHookOptions<${dataType}, Error, TPageParam> & { initialPageParam: TPageParam; getNextPageParam: (lastPage: ${dataType}, allPages: ${dataType}[]) => TPageParam | undefined },\n`;
            content += `${innerIndent}): UseInfiniteQueryResult<InfiniteData<${dataType}>> {\n`;
            content += `${innerIndent}    const client = use${clientName}Context();\n`;
            content += `${innerIndent}    const { initialPageParam, getNextPageParam, ...rest } = options;\n`;
            content += `${innerIndent}    return useInfiniteQuery({\n`;
            content += `${innerIndent}        queryKey: [${queryKeyParts}] as const,\n`;
            content += `${innerIndent}        queryFn: () => client${clientAccessor}.${endpointCamelName}(),\n`;
            content += `${innerIndent}        initialPageParam,\n`;
            content += `${innerIndent}        getNextPageParam,\n`;
            content += `${innerIndent}        ...rest,\n`;
            content += `${innerIndent}    });\n`;
            content += `${innerIndent}},\n`;
        }

        // useSuspenseInfiniteQuery
        if (hasArgs) {
            content += `${innerIndent}useSuspenseInfiniteQuery<TPageParam = unknown>(\n`;
            content += `${innerIndent}    args: Parameters<${methodType}>,\n`;
            content += `${innerIndent}    options: SuspenseInfiniteQueryHookOptions<${dataType}, Error, TPageParam> & { initialPageParam: TPageParam; getNextPageParam: (lastPage: ${dataType}, allPages: ${dataType}[]) => TPageParam | undefined },\n`;
            content += `${innerIndent}): UseSuspenseInfiniteQueryResult<InfiniteData<${dataType}>> {\n`;
            content += `${innerIndent}    const client = use${clientName}Context();\n`;
            content += `${innerIndent}    const { initialPageParam, getNextPageParam, ...rest } = options;\n`;
            content += `${innerIndent}    return useSuspenseInfiniteQuery({\n`;
            content += `${innerIndent}        queryKey: [${queryKeyParts}, ...args] as const,\n`;
            content += `${innerIndent}        queryFn: () => client${clientAccessor}.${endpointCamelName}(...args),\n`;
            content += `${innerIndent}        initialPageParam,\n`;
            content += `${innerIndent}        getNextPageParam,\n`;
            content += `${innerIndent}        ...rest,\n`;
            content += `${innerIndent}    });\n`;
            content += `${innerIndent}},\n`;
        } else {
            content += `${innerIndent}useSuspenseInfiniteQuery<TPageParam = unknown>(\n`;
            content += `${innerIndent}    options: SuspenseInfiniteQueryHookOptions<${dataType}, Error, TPageParam> & { initialPageParam: TPageParam; getNextPageParam: (lastPage: ${dataType}, allPages: ${dataType}[]) => TPageParam | undefined },\n`;
            content += `${innerIndent}): UseSuspenseInfiniteQueryResult<InfiniteData<${dataType}>> {\n`;
            content += `${innerIndent}    const client = use${clientName}Context();\n`;
            content += `${innerIndent}    const { initialPageParam, getNextPageParam, ...rest } = options;\n`;
            content += `${innerIndent}    return useSuspenseInfiniteQuery({\n`;
            content += `${innerIndent}        queryKey: [${queryKeyParts}] as const,\n`;
            content += `${innerIndent}        queryFn: () => client${clientAccessor}.${endpointCamelName}(),\n`;
            content += `${innerIndent}        initialPageParam,\n`;
            content += `${innerIndent}        getNextPageParam,\n`;
            content += `${innerIndent}        ...rest,\n`;
            content += `${innerIndent}    });\n`;
            content += `${innerIndent}},\n`;
        }

        // getQueryKey
        if (hasArgs) {
            content += `${innerIndent}getQueryKey(...args: Parameters<${methodType}>): QueryKey {\n`;
            content += `${innerIndent}    return [${queryKeyParts}, ...args] as const;\n`;
            content += `${innerIndent}},\n`;
        } else {
            content += `${innerIndent}getQueryKey(): QueryKey {\n`;
            content += `${innerIndent}    return [${queryKeyParts}] as const;\n`;
            content += `${innerIndent}},\n`;
        }

        // getQueryOptions (framework-agnostic, for SSR/RSC/prefetch)
        if (hasArgs) {
            content += `${innerIndent}getQueryOptions(\n`;
            content += `${innerIndent}    client: ${clientName},\n`;
            content += `${innerIndent}    args: Parameters<${methodType}>,\n`;
            content += `${innerIndent}): { queryKey: readonly unknown[]; queryFn: () => Promise<${dataType}> } {\n`;
            content += `${innerIndent}    return {\n`;
            content += `${innerIndent}        queryKey: [${queryKeyParts}, ...args] as const,\n`;
            content += `${innerIndent}        queryFn: () => client${clientAccessor}.${endpointCamelName}(...args),\n`;
            content += `${innerIndent}    };\n`;
            content += `${innerIndent}},\n`;
        } else {
            content += `${innerIndent}getQueryOptions(\n`;
            content += `${innerIndent}    client: ${clientName},\n`;
            content += `${innerIndent}): { queryKey: readonly unknown[]; queryFn: () => Promise<${dataType}> } {\n`;
            content += `${innerIndent}    return {\n`;
            content += `${innerIndent}        queryKey: [${queryKeyParts}] as const,\n`;
            content += `${innerIndent}        queryFn: () => client${clientAccessor}.${endpointCamelName}(),\n`;
            content += `${innerIndent}    };\n`;
            content += `${innerIndent}},\n`;
        }

        // invalidate (uses prefix matching — works with or without args)
        content += `${innerIndent}invalidate(queryClient: QueryClient, ...args: unknown[]): Promise<void> {\n`;
        content += `${innerIndent}    return queryClient.invalidateQueries({ queryKey: [${queryKeyParts}, ...args] });\n`;
        content += `${innerIndent}},\n`;

        content += `${indent}}`;
        return content;
    }

    private generateMutationEndpointNode(
        endpoint: EndpointHookInfo,
        queryKeyPrefix: string,
        clientName: string,
        servicePath: string[],
        depth: number
    ): string {
        const { endpointCamelName, hasArgs } = endpoint;
        const indent = "    ".repeat(depth);
        const innerIndent = "    ".repeat(depth + 1);

        const clientAccessor = this.buildClientAccessor(servicePath);
        const methodType = `${clientName}${servicePath.map((s) => `["${s}"]`).join("")}["${endpointCamelName}"]`;
        const dataType = `Awaited<ReturnType<${methodType}>>`;
        const variablesType = hasArgs ? `Parameters<${methodType}>` : "void";
        const queryKeyParts = [queryKeyPrefix, ...servicePath, endpointCamelName].map((p) => `"${p}"`).join(", ");

        let content = "{\n";

        // useMutation
        content += `${innerIndent}useMutation(\n`;
        content += `${innerIndent}    options?: MutationHookOptions<${dataType}, Error, ${variablesType}>,\n`;
        content += `${innerIndent}): UseMutationResult<${dataType}, Error, ${variablesType}> {\n`;
        content += `${innerIndent}    const client = use${clientName}Context();\n`;
        content += `${innerIndent}    return useMutation({\n`;
        content += `${innerIndent}        mutationKey: [${queryKeyParts}] as const,\n`;

        if (hasArgs) {
            content += `${innerIndent}        mutationFn: (args) => client${clientAccessor}.${endpointCamelName}(...args),\n`;
        } else {
            content += `${innerIndent}        mutationFn: () => client${clientAccessor}.${endpointCamelName}(),\n`;
        }

        content += `${innerIndent}        ...options,\n`;
        content += `${innerIndent}    });\n`;
        content += `${innerIndent}},\n`;

        content += `${indent}}`;
        return content;
    }

    private collectEndpoints(): EndpointHookInfo[] {
        const endpoints: EndpointHookInfo[] = [];

        for (const packageId of this.getAllPackageIds()) {
            const service = this.packageResolver.getServiceDeclaration(packageId);
            if (service == null) {
                continue;
            }

            const accessPath = this.getServiceAccessPath(packageId);

            for (const endpoint of service.endpoints) {
                const endpointCamelName = this.case.camelUnsafe(endpoint.name);

                const hasArgs =
                    endpoint.sdkRequest != null ||
                    endpoint.pathParameters.length > 0 ||
                    endpoint.allPathParameters.length > 0;

                endpoints.push({
                    serviceAccessPath: accessPath,
                    endpointCamelName,
                    method: endpoint.method,
                    hasArgs,
                    docs: endpoint.docs ?? undefined
                });
            }
        }

        return endpoints;
    }

    private isQueryMethod(method: string): boolean {
        return method === "GET" || method === "HEAD";
    }

    private getServiceAccessPath(packageId: PackageId): string[] {
        if (packageId.isRoot) {
            return [];
        }
        const subpackage = this.ir.subpackages[packageId.subpackageId];
        if (subpackage == null) {
            return [];
        }
        return subpackage.fernFilepath.allParts.map((part) => this.case.camelUnsafe(part));
    }

    private buildClientAccessor(accessPath: string[]): string {
        if (accessPath.length === 0) {
            return "";
        }
        return "." + accessPath.join(".");
    }

    private getAllPackageIds(): PackageId[] {
        return [
            { isRoot: true },
            ...Object.keys(this.ir.subpackages).map((subpackageId): PackageId => ({ isRoot: false, subpackageId }))
        ];
    }
}
