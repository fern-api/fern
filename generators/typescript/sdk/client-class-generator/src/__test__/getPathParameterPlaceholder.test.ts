import { FernIr } from "@fern-fern/ir-sdk";
import { getTextOfTsNode } from "@fern-typescript/commons";
import {
    createDeclaredTypeName,
    createNameAndWireValue,
    createNamedTypeReference,
    createPathParameter
} from "@fern-typescript/test-utils";
import assert from "assert";
import { describe, expect, it } from "vitest";

import {
    getPathParameterPlaceholder,
    PathParameterPlaceholderContext
} from "../endpoints/utils/getPathParameterPlaceholder.js";

function createPrimitivePathParameter(name: string, v1: FernIr.PrimitiveTypeV1): FernIr.PathParameter {
    return createPathParameter(name, "ENDPOINT", FernIr.TypeReference.primitive({ v1, v2: undefined }));
}

function createEnumTypeDeclaration(name: string, values: string[]): FernIr.TypeDeclaration {
    return {
        name: createDeclaredTypeName(name),
        shape: FernIr.Type.enum({
            default: undefined,
            forwardCompatible: undefined,
            values: values.map((value) => ({
                name: createNameAndWireValue(value),
                docs: undefined,
                availability: undefined
            }))
        }),
        autogeneratedExamples: [],
        userProvidedExamples: [],
        v2Examples: undefined,
        referencedTypes: new Set<FernIr.TypeId>(),
        encoding: undefined,
        source: undefined,
        inline: undefined,
        docs: undefined,
        availability: undefined
    };
}

function createContext({
    resolvedTypeReference,
    typeDeclaration
}: {
    resolvedTypeReference: (typeReference: FernIr.TypeReference) => FernIr.ResolvedTypeReference;
    typeDeclaration?: FernIr.TypeDeclaration;
}): PathParameterPlaceholderContext {
    return {
        type: {
            resolveTypeReference: resolvedTypeReference,
            getTypeDeclaration: () => {
                if (typeDeclaration == null) {
                    throw new Error("No type declaration was registered for this test");
                }
                return typeDeclaration;
            }
        }
    };
}

const PRIMITIVE_CONTEXT = createContext({
    resolvedTypeReference: (typeReference) => {
        if (typeReference.type !== "primitive") {
            throw new Error(`Expected a primitive type reference, got ${typeReference.type}`);
        }
        return FernIr.ResolvedTypeReference.primitive(typeReference.primitive);
    }
});

describe("getPathParameterPlaceholder", () => {
    it("uses the path parameter name for strings", () => {
        const placeholder = getPathParameterPlaceholder({
            pathParameter: createPrimitivePathParameter("objectPath", "STRING"),
            context: PRIMITIVE_CONTEXT
        });
        assert(placeholder != null, "expected a placeholder");
        expect(getTextOfTsNode(placeholder)).toBe('"objectPath"');
    });

    it("renders values of the declared primitive type", () => {
        const cases: [FernIr.PrimitiveTypeV1, string][] = [
            ["INTEGER", "1"],
            ["DOUBLE", "1.1"],
            ["BOOLEAN", "true"],
            ["UUID", '"d5e9c84f-c2b2-4bf4-b4b0-7ffd7a9ffc32"'],
            ["DATE", '"2023-01-15"']
        ];
        for (const [v1, expected] of cases) {
            const placeholder = getPathParameterPlaceholder({
                pathParameter: createPrimitivePathParameter("param", v1),
                context: PRIMITIVE_CONTEXT
            });
            assert(placeholder != null, `expected a placeholder for ${v1}`);
            expect(getTextOfTsNode(placeholder)).toBe(expected);
        }
    });

    it("uses the first value of an enum", () => {
        const context = createContext({
            resolvedTypeReference: () =>
                FernIr.ResolvedTypeReference.named({
                    name: createDeclaredTypeName("Color"),
                    shape: FernIr.ShapeType.Enum
                }),
            typeDeclaration: createEnumTypeDeclaration("Color", ["red", "blue"])
        });
        const placeholder = getPathParameterPlaceholder({
            pathParameter: createPathParameter("color", "ENDPOINT", createNamedTypeReference("Color")),
            context
        });
        assert(placeholder != null, "expected a placeholder");
        expect(getTextOfTsNode(placeholder)).toBe('"red"');
    });

    it("returns undefined for object types, which have no single-value placeholder", () => {
        const context = createContext({
            resolvedTypeReference: () =>
                FernIr.ResolvedTypeReference.named({
                    name: createDeclaredTypeName("Object"),
                    shape: FernIr.ShapeType.Object
                }),
            typeDeclaration: {
                ...createEnumTypeDeclaration("Object", []),
                shape: FernIr.Type.object({
                    properties: [],
                    extends: [],
                    extraProperties: false,
                    extendedProperties: undefined,
                    deferredUnionBaseProperties: undefined
                })
            }
        });
        const placeholder = getPathParameterPlaceholder({
            pathParameter: createPathParameter("object", "ENDPOINT", createNamedTypeReference("Object")),
            context
        });
        expect(placeholder).toBeUndefined();
    });

    it("returns undefined for unknown types", () => {
        const context = createContext({
            resolvedTypeReference: () => FernIr.ResolvedTypeReference.unknown()
        });
        const placeholder = getPathParameterPlaceholder({
            pathParameter: createPathParameter("anything", "ENDPOINT", FernIr.TypeReference.unknown()),
            context
        });
        expect(placeholder).toBeUndefined();
    });
});
