import { FernIr } from "@fern-fern/ir-sdk";

/**
 * Whether the caller may leave the request body out of the generated call entirely.
 */
export function mayOmitRequestBody({
    endpoint,
    respectOptionalRequestBody
}: {
    endpoint: FernIr.HttpEndpoint;
    respectOptionalRequestBody: boolean;
}): boolean {
    return (
        respectOptionalRequestBody &&
        endpoint.requestBody?.type === "reference" &&
        endpoint.requestBody.required === false
    );
}

/**
 * Whether the example calls the endpoint without the request body it declares.
 *
 * Unless the caller may omit the body, the generated client asks for it, so rendering such an
 * example produces a call that is missing a required argument.
 */
export function exampleOmitsRequestBody({
    endpoint,
    example,
    respectOptionalRequestBody
}: {
    endpoint: FernIr.HttpEndpoint;
    example: FernIr.ExampleEndpointCall;
    respectOptionalRequestBody: boolean;
}): boolean {
    return (
        endpoint.requestBody != null &&
        example.request == null &&
        !mayOmitRequestBody({ endpoint, respectOptionalRequestBody })
    );
}

function withoutExamplesOmittingRequestBody({
    endpoint,
    examples,
    respectOptionalRequestBody
}: {
    endpoint: FernIr.HttpEndpoint;
    examples: FernIr.ExampleEndpointCall[];
    respectOptionalRequestBody: boolean;
}): FernIr.ExampleEndpointCall[] {
    return examples.filter((example) => !exampleOmitsRequestBody({ endpoint, example, respectOptionalRequestBody }));
}

export function getExampleEndpointCallsForTests({
    endpoint,
    fallbackToAutoGeneratedErrorExamples = true,
    respectOptionalRequestBody
}: {
    endpoint: FernIr.HttpEndpoint;
    fallbackToAutoGeneratedErrorExamples?: boolean;
    respectOptionalRequestBody: boolean;
}): FernIr.ExampleEndpointCall[] {
    const examples: FernIr.ExampleEndpointCall[] = [];
    // If any of the examples are user provided, we should only include those.
    const hasUserExamples = endpoint.userSpecifiedExamples.length > 0;
    const userExamplesHasErrorExample = endpoint.userSpecifiedExamples.some(
        (e) => e.example?.response.type === "error"
    );
    if (hasUserExamples) {
        examples.push(...endpoint.userSpecifiedExamples.map((e) => e.example).filter((e) => e != null));
        // if no user examples, add auto generated error examples
        if (!userExamplesHasErrorExample && fallbackToAutoGeneratedErrorExamples) {
            examples.push(
                ...endpoint.autogeneratedExamples
                    .map((e) => e.example)
                    .filter((e) => e != null)
                    .filter((e) => e.response.type === "error")
            );
        }

        return withoutExamplesOmittingRequestBody({ endpoint, examples, respectOptionalRequestBody });
    }

    // Otherwise we should only include a single one of the generated examples.
    examples.push(...endpoint.autogeneratedExamples.map((e) => e.example).filter((e) => e != null));
    return withoutExamplesOmittingRequestBody({ endpoint, examples, respectOptionalRequestBody });
}

export function getExampleEndpointCalls(
    endpoint: FernIr.HttpEndpoint,
    respectOptionalRequestBody: boolean
): FernIr.ExampleEndpointCall[] {
    // If any of the examples are user provided, we should only include those.
    if (endpoint.userSpecifiedExamples.length > 0) {
        const examples: FernIr.ExampleEndpointCall[] = [];
        for (const userDefinedExample of endpoint.userSpecifiedExamples) {
            if (userDefinedExample.example != null) {
                examples.push(userDefinedExample.example);
            }
        }
        return withoutExamplesOmittingRequestBody({ endpoint, examples, respectOptionalRequestBody });
    }
    // Otherwise we should only include a single one of the generated examples.
    for (const autogenerated of endpoint.autogeneratedExamples) {
        if (
            autogenerated.example != null &&
            !exampleOmitsRequestBody({ endpoint, example: autogenerated.example, respectOptionalRequestBody })
        ) {
            return [autogenerated.example];
        }
    }
    return [];
}
