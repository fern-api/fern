import { FernIr } from "@fern-fern/ir-sdk";

import { SdkGeneratorContext } from "../SdkGeneratorContext.js";

export interface WireTestExpectedError {
    statusCode: number;
    /** The typed error the SDK returns, or undefined when it returns the base *core.APIError. */
    errorDeclaration: FernIr.ErrorDeclaration | undefined;
    body: unknown;
}

export interface WireTestExample {
    example: FernIr.ExampleEndpointCall;
    dynamicExample: FernIr.dynamic.EndpointExample;
    expectedError: WireTestExpectedError | undefined;
}

interface TaggedExample {
    example: FernIr.ExampleEndpointCall;
    dynamicExampleId: string;
    isUserSpecified: boolean;
}

/**
 * Selects the examples to generate wire tests for and resolves the error each error example is
 * expected to produce, mirroring the generated SDK's error decoder.
 */
export class WireTestExampleSelector {
    private readonly context: SdkGeneratorContext;
    private readonly errorIdsByStatusCodeKeyByNamespace = new Map<string, Map<string, string>>();
    private readonly serviceByEndpointId = new Map<string, FernIr.HttpService>();

    constructor(context: SdkGeneratorContext) {
        this.context = context;
        for (const service of Object.values(context.ir.services)) {
            for (const endpoint of service.endpoints) {
                this.serviceByEndpointId.set(endpoint.id, service);
            }
        }
    }

    /**
     * Every user-specified example (or the first autogenerated success example when there are none),
     * plus one autogenerated example per error when no user-specified example covers an error.
     */
    public getTestExamples(endpoint: FernIr.HttpEndpoint): WireTestExample[] {
        const userExamples = this.tagExamples(endpoint, endpoint.userSpecifiedExamples, true);
        const autogeneratedExamples = this.tagExamples(endpoint, endpoint.autogeneratedExamples, false);
        const isError = ({ example }: TaggedExample) => example.response.type === "error";

        const selected = [...userExamples];
        if (userExamples.length === 0) {
            const firstSuccessExample = autogeneratedExamples.find((example) => !isError(example));
            if (firstSuccessExample != null) {
                selected.push(firstSuccessExample);
            }
        }
        if (
            this.context.customConfig.wireTestsFallbackToAutogeneratedErrorExamples !== false &&
            !userExamples.some(isError)
        ) {
            const seenErrorIds = new Set<string>();
            for (const autogeneratedExample of autogeneratedExamples) {
                const response = autogeneratedExample.example.response;
                if (response.type !== "error" || seenErrorIds.has(response.error.errorId)) {
                    continue;
                }
                seenErrorIds.add(response.error.errorId);
                selected.push(autogeneratedExample);
            }
        }

        const dynamicExamples = this.context.ir.dynamic?.endpoints[endpoint.id]?.examples ?? [];
        const testExamples: WireTestExample[] = [];
        for (const tagged of selected) {
            const dynamicExample = this.findDynamicExample(dynamicExamples, tagged);
            if (dynamicExample == null) {
                this.context.logger.warn(
                    `Skipping wire test for an example of endpoint ${endpoint.id}: no matching dynamic example ${tagged.dynamicExampleId}`
                );
                continue;
            }
            const response = tagged.example.response;
            if (response.type !== "error") {
                testExamples.push({ example: tagged.example, dynamicExample, expectedError: undefined });
                continue;
            }
            const expectedError = this.getExpectedError(endpoint, response);
            if (expectedError == null) {
                continue;
            }
            testExamples.push({ example: tagged.example, dynamicExample, expectedError });
        }
        return testExamples;
    }

    public getTestNameSuffix({ example, expectedError }: WireTestExample): string {
        if (example.response.type === "error") {
            const errorDeclaration =
                expectedError?.errorDeclaration ?? this.context.ir.errors[example.response.error.errorId];
            const errorName =
                errorDeclaration != null ? this.context.getClassName(errorDeclaration.name.name) : "Error";
            return `Throws${sanitizeIdentifier(errorName)}`;
        }
        const exampleName =
            example.name != null ? sanitizeIdentifier(this.context.caseConverter.pascalUnsafe(example.name)) : "";
        return exampleName.length > 0 ? exampleName : "Example";
    }

    private tagExamples(
        endpoint: FernIr.HttpEndpoint,
        examples: (FernIr.UserSpecifiedEndpointExample | FernIr.AutogeneratedEndpointExample)[],
        isUserSpecified: boolean
    ): TaggedExample[] {
        const tagged: TaggedExample[] = [];
        examples.forEach(({ example }, index) => {
            if (example == null) {
                return;
            }
            // Mirrors the IDs the dynamic IR assigns to examples so the two can be paired up.
            const dynamicExampleId = example.id ?? `${endpoint.id}-${isUserSpecified ? "user" : "auto"}-${index}`;
            tagged.push({ example, dynamicExampleId, isUserSpecified });
        });
        return tagged;
    }

    private findDynamicExample(
        dynamicExamples: FernIr.dynamic.EndpointExample[],
        { dynamicExampleId, isUserSpecified }: TaggedExample
    ): FernIr.dynamic.EndpointExample | undefined {
        const candidates = dynamicExamples.filter((example) => example.id === dynamicExampleId);
        // Matching IDs identify the same example; isUserSpecified only breaks ties between colliding IDs.
        return candidates.find((example) => (example.isUserSpecified ?? false) === isUserSpecified) ?? candidates[0];
    }

    /**
     * Returns undefined when the example can't be asserted: a non-error status, or an error that the
     * decoder never returns because another error claims the same status code.
     */
    private getExpectedError(
        endpoint: FernIr.HttpEndpoint,
        response: FernIr.ExampleEndpointErrorResponse
    ): WireTestExpectedError | undefined {
        const errorId = response.error.errorId;
        const errorDeclaration = this.context.ir.errors[errorId];
        if (errorDeclaration == null || errorDeclaration.statusCode < 400) {
            return undefined;
        }
        const statusCode = errorDeclaration.statusCode;
        const body = response.body?.jsonExample;
        const base: WireTestExpectedError = { statusCode, errorDeclaration: undefined, body };

        if (this.context.ir.errorDiscriminationStrategy.type !== "statusCode") {
            return base;
        }
        // Without a body the decoder can't unmarshal the declared body type and returns the base error.
        if (response.body == null && errorDeclaration.type != null) {
            return base;
        }
        const dispatchedErrorId = this.getDispatchedErrorId(endpoint, statusCode);
        if (dispatchedErrorId == null) {
            return base;
        }
        if (dispatchedErrorId !== errorId) {
            return undefined;
        }
        return { statusCode, errorDeclaration, body };
    }

    /** Mirrors internal.ErrorCodes lookup: a concrete status code wins over its 4XX/5XX wildcard. */
    private getDispatchedErrorId(endpoint: FernIr.HttpEndpoint, statusCode: number): string | undefined {
        const errorIdsByStatusCodeKey = this.getErrorIdsByStatusCodeKey(endpoint);
        const concrete = errorIdsByStatusCodeKey.get(statusCode.toString());
        if (concrete != null || statusCode < 400 || statusCode > 599) {
            return concrete;
        }
        return errorIdsByStatusCodeKey.get(`${Math.floor(statusCode / 100)}XX`);
    }

    /**
     * Per-endpoint error codes are built from the endpoint's own errors; otherwise every endpoint in a
     * namespace shares one ErrorCodes map where the first error referenced for a status code wins
     * (see InternalFilesGenerator).
     */
    private getErrorIdsByStatusCodeKey(endpoint: FernIr.HttpEndpoint): Map<string, string> {
        if (this.context.isPerEndpointErrorCodes()) {
            return this.buildErrorIdsByStatusCodeKey([endpoint]);
        }
        const service = this.serviceByEndpointId.get(endpoint.id);
        if (service == null) {
            return this.buildErrorIdsByStatusCodeKey([endpoint]);
        }
        const namespace = this.context.getPackageLocation(service.name.fernFilepath).importPath;
        let errorIdsByStatusCodeKey = this.errorIdsByStatusCodeKeyByNamespace.get(namespace);
        if (errorIdsByStatusCodeKey == null) {
            const namespaceEndpoints = Object.values(this.context.ir.services)
                .filter(
                    (namespaceService) =>
                        this.context.getPackageLocation(namespaceService.name.fernFilepath).importPath === namespace
                )
                .flatMap((namespaceService) => namespaceService.endpoints);
            errorIdsByStatusCodeKey = this.buildErrorIdsByStatusCodeKey(
                namespaceEndpoints.length > 0 ? namespaceEndpoints : [endpoint]
            );
            this.errorIdsByStatusCodeKeyByNamespace.set(namespace, errorIdsByStatusCodeKey);
        }
        return errorIdsByStatusCodeKey;
    }

    private buildErrorIdsByStatusCodeKey(endpoints: FernIr.HttpEndpoint[]): Map<string, string> {
        const errorIdsByStatusCodeKey = new Map<string, string>();
        for (const endpoint of endpoints) {
            for (const responseError of endpoint.errors) {
                const errorDeclaration = this.context.ir.errors[responseError.error.errorId];
                if (errorDeclaration == null) {
                    continue;
                }
                const key =
                    errorDeclaration.isWildcardStatusCode === true
                        ? `${Math.floor(errorDeclaration.statusCode / 100)}XX`
                        : errorDeclaration.statusCode.toString();
                if (!errorIdsByStatusCodeKey.has(key)) {
                    errorIdsByStatusCodeKey.set(key, errorDeclaration.name.errorId);
                }
            }
        }
        return errorIdsByStatusCodeKey;
    }
}

function sanitizeIdentifier(value: string): string {
    return value.replace(/[^A-Za-z0-9]/g, "");
}
