import { CaseConverter } from "@fern-api/base-generator";
import { FernIr } from "@fern-fern/ir-sdk";
import { describe, expect, it } from "vitest";
import { ClientConfigGenerator } from "../generators/ClientConfigGenerator.js";
import { SubClientGenerator } from "../generators/SubClientGenerator.js";
import { SdkGeneratorContext } from "../SdkGeneratorContext.js";
import { createMultipleBaseUrlsEnvironmentsConfig } from "./util/createEnvironmentsConfig.js";
import { createSampleGeneratorContext } from "./util/createSampleGeneratorContext.js";

const caseConverter = new CaseConverter({
    generationLanguage: "rust",
    keywords: undefined,
    smartCasing: true
});

const ENVIRONMENTS = {
    baseUrls: ["api", "auth"],
    environments: {
        Production: {
            api: "https://api.example.com",
            auth: "https://auth.example.com"
        },
        Staging: {
            api: "https://staging-api.example.com",
            auth: "https://staging-auth.example.com"
        }
    }
};

function createSubClientContext(environments: FernIr.EnvironmentsConfig): SdkGeneratorContext {
    const ir = {
        apiName: {
            originalName: "TestAPI",
            camelCase: { unsafeName: "testApi", safeName: "testApi" },
            snakeCase: { unsafeName: "test_api", safeName: "test_api" },
            screamingSnakeCase: { unsafeName: "TEST_API", safeName: "TEST_API" },
            pascalCase: { unsafeName: "TestAPI", safeName: "TestAPI" }
        },
        apiVersion: "1.0.0",
        errors: {},
        types: {},
        services: {},
        subpackages: {},
        environments
    } as unknown as FernIr.IntermediateRepresentation;

    return {
        ir,
        case: caseConverter,
        getClientName: () => "TestClient",
        customConfig: { generateExamples: false },
        getHttpServiceOrThrow: () => ({ endpoints: [] }) as unknown as FernIr.HttpService,
        getSubpackageOrThrow: () => undefined,
        getSubpackagesOrThrow: () => [],
        getUniqueFilenameForSubpackage: () => "test_subpackage.rs",
        getUniqueClientNameForSubpackage: () => "TestSubpackageClient",
        getDirectoryForFernFilepath: () => "",
        getQueryRequestTypeName: (endpoint: FernIr.HttpEndpoint) =>
            `${caseConverter.pascalSafe(endpoint.name)}QueryRequest`,
        getModuleNameForQueryRequest: (queryRequestTypeName: string) => queryRequestTypeName.toLowerCase(),
        hasEnvironments: () => true,
        hasMultipleBaseUrls: () => true,
        getEnvironmentEnumName: () => "Environment",
        isEndpointSecurity: () => false,
        getEndpointSnippet: () => undefined,
        escapeRustKeyword: (name: string) => name
    } as unknown as SdkGeneratorContext;
}

function createSubpackage(): FernIr.Subpackage {
    return {
        name: {
            originalName: "TestSubpackage",
            camelCase: { unsafeName: "testSubpackage", safeName: "testSubpackage" },
            snakeCase: { unsafeName: "test_subpackage", safeName: "test_subpackage" },
            screamingSnakeCase: {
                unsafeName: "TEST_SUBPACKAGE",
                safeName: "TEST_SUBPACKAGE"
            },
            pascalCase: { unsafeName: "TestSubpackage", safeName: "TestSubpackage" }
        },
        fernFilepath: {
            allParts: [],
            packagePath: [],
            file: { contents: [], extension: "fern" }
        },
        service: undefined,
        types: [],
        errors: [],
        subpackages: [],
        hasEndpointsInTree: false
    } as unknown as FernIr.Subpackage;
}

function createEndpoint(name: string, baseUrl: string | undefined): FernIr.HttpEndpoint {
    return {
        id: name,
        name: {
            originalName: name,
            camelCase: { unsafeName: name, safeName: name },
            snakeCase: {
                unsafeName: name.toLowerCase(),
                safeName: name.toLowerCase()
            },
            screamingSnakeCase: {
                unsafeName: name.toUpperCase(),
                safeName: name.toUpperCase()
            },
            pascalCase: { unsafeName: name, safeName: name }
        },
        method: "GET",
        baseUrl,
        path: { head: "/token", parts: [] },
        fullPath: { head: "/token", parts: [] },
        pathParameters: [],
        allPathParameters: [],
        queryParameters: [],
        headers: [],
        errors: [],
        auth: false,
        idempotent: false,
        userSpecifiedExamples: [],
        autogeneratedExamples: []
    } as unknown as FernIr.HttpEndpoint;
}

function generateEndpointBody(context: SdkGeneratorContext, endpoint: FernIr.HttpEndpoint): string {
    const generator = new SubClientGenerator(context, createSubpackage());
    return (
        generator as unknown as {
            generateHttpMethod: (endpoint: FernIr.HttpEndpoint) => { body: string };
        }
    ).generateHttpMethod(endpoint).body;
}

describe("multi-URL environments", () => {
    describe("ClientConfig", () => {
        it("resolves a service URL with an explicit base_url winning over the environment", async () => {
            const context = createSampleGeneratorContext({
                environments: createMultipleBaseUrlsEnvironmentsConfig({
                    ...ENVIRONMENTS,
                    defaultEnvironment: "Production"
                })
            });
            const contents = new ClientConfigGenerator(context).generate().fileContents;

            expect(contents).toContain(
                "pub fn service_url<'a>(&'a self, url_for: impl FnOnce(&'a Environment) -> &'a str) -> &'a str"
            );
            expect(contents).toContain("environment.api_url(),");
            expect(contents).toContain("environment.auth_url(),");
            expect(contents).toContain(`"https://api.example.com",`);
            expect(contents).not.toContain("Environment::default().url(),");
            expect(contents).toContain("environment: Some(Environment::default())");
            await expect(contents).toMatchFileSnapshot("snapshots/client-config-multi-url.rs");
        });

        it("compares base_url against the environment's URLs only when no default environment exists", async () => {
            const context = createSampleGeneratorContext({
                environments: createMultipleBaseUrlsEnvironmentsConfig(ENVIRONMENTS)
            });
            const contents = new ClientConfigGenerator(context).generate().fileContents;

            expect(contents).toContain("pub fn service_url<'a>");
            expect(contents).not.toContain("default_environment");
            expect(contents).toContain("environment: None");
            await expect(contents).toMatchFileSnapshot("snapshots/client-config-multi-url-no-default.rs");
        });
    });

    describe("endpoints", () => {
        const context = createSubClientContext(
            createMultipleBaseUrlsEnvironmentsConfig({
                ...ENVIRONMENTS,
                defaultEnvironment: "Production"
            })
        );

        it("resolves an endpoint's URL through ClientConfig::service_url", () => {
            const body = generateEndpointBody(context, createEndpoint("getToken", "auth"));

            expect(body).toContain(
                "let base_url = self.http_client.config().service_url(|environment| environment.auth_url());"
            );
            expect(body).toContain("execute_request_with_base_url");
            expect(body).not.toContain("environment.as_ref()");
        });

        it("leaves an endpoint without a base URL on the client's URL", () => {
            const body = generateEndpointBody(context, createEndpoint("getToken", undefined));

            expect(body).not.toContain("service_url");
            expect(body).toContain("execute_request(");
        });
    });
});
