import { CaseConverter } from "@fern-api/base-generator";
import { FernIr } from "@fern-fern/ir-sdk";
import { describe, expect, it } from "vitest";
import { SubClientGenerator } from "../generators/SubClientGenerator.js";
import { SdkGeneratorContext } from "../SdkGeneratorContext.js";

const caseConverter = new CaseConverter({ generationLanguage: "rust", keywords: undefined, smartCasing: true });

function createName(name: string): FernIr.Name {
    return {
        originalName: name,
        camelCase: { unsafeName: name, safeName: name },
        snakeCase: { unsafeName: name.toLowerCase(), safeName: name.toLowerCase() },
        screamingSnakeCase: { unsafeName: name.toUpperCase(), safeName: name.toUpperCase() },
        pascalCase: { unsafeName: name, safeName: name }
    } as FernIr.Name;
}

function createHttpEndpoint(retries: FernIr.RetriesConfiguration | undefined): FernIr.HttpEndpoint {
    return {
        id: "getUsers",
        name: createName("getUsers"),
        method: "GET",
        path: { head: "/users", parts: [] },
        fullPath: { head: "/users", parts: [] },
        pathParameters: [],
        allPathParameters: [],
        queryParameters: [],
        headers: [],
        errors: [],
        auth: false,
        idempotent: false,
        userSpecifiedExamples: [],
        autogeneratedExamples: [],
        retries
    } as unknown as FernIr.HttpEndpoint;
}

function createMockContext(): SdkGeneratorContext {
    return {
        ir: { headers: [], types: {}, services: {} },
        case: caseConverter,
        customConfig: {},
        getClientName: () => "TestClient",
        getUniqueClientNameForSubpackage: () => "TestSubpackageClient",
        getSubpackagesOrThrow: () => [],
        getHttpServiceOrThrow: () => ({ endpoints: [] }) as unknown as FernIr.HttpService,
        hasMultipleBaseUrls: () => false,
        isEndpointSecurity: () => false,
        getEndpointSnippet: () => undefined
    } as unknown as SdkGeneratorContext;
}

function createMockSubpackage(): FernIr.Subpackage {
    return {
        name: createName("TestSubpackage"),
        fernFilepath: { allParts: [], packagePath: [], file: undefined },
        service: undefined,
        types: [],
        errors: [],
        subpackages: [],
        hasEndpointsInTree: false
    } as unknown as FernIr.Subpackage;
}

function generateMethodBody(retries: FernIr.RetriesConfiguration | undefined): string {
    const generator = new SubClientGenerator(createMockContext(), createMockSubpackage());
    return (
        generator as unknown as {
            generateHttpMethod: (endpoint: FernIr.HttpEndpoint) => { body: string };
        }
    ).generateHttpMethod(createHttpEndpoint(retries)).body;
}

describe("retries configuration", () => {
    it("pins max_retries to zero when the endpoint disables retries", () => {
        const body = generateMethodBody({ disabled: true });
        expect(body).toContain("let mut o = options.unwrap_or_default();");
        expect(body).toContain("o.max_retries = Some(0);");
    });

    it("leaves options untouched when the endpoint does not configure retries", () => {
        const body = generateMethodBody(undefined);
        expect(body).not.toContain("max_retries");
        expect(body).not.toContain("options.unwrap_or_default()");
    });

    it("leaves options untouched when retries are explicitly enabled", () => {
        const body = generateMethodBody({ disabled: false });
        expect(body).not.toContain("max_retries");
    });
});
