import { FernIr } from "@fern-fern/ir-sdk";
import { describe, expect, it } from "vitest";
import { SubClientGenerator } from "../generators/SubClientGenerator.js";
import { createSampleGeneratorContext } from "./util/createSampleGeneratorContext.js";

const SERVICE_ID = "service_users";

function createName(name: string): FernIr.Name {
    return {
        originalName: name,
        camelCase: { unsafeName: name, safeName: name },
        snakeCase: { unsafeName: name.toLowerCase(), safeName: name.toLowerCase() },
        screamingSnakeCase: { unsafeName: name.toUpperCase(), safeName: name.toUpperCase() },
        pascalCase: { unsafeName: name, safeName: name }
    };
}

function createEndpoint(retries: FernIr.RetriesConfiguration | undefined): FernIr.HttpEndpoint {
    return {
        docs: undefined,
        availability: undefined,
        id: "getUsers",
        name: createName("getUsers"),
        displayName: undefined,
        method: "GET",
        headers: [],
        responseHeaders: undefined,
        baseUrl: undefined,
        v2BaseUrls: undefined,
        basePath: undefined,
        path: { head: "/users", parts: [] },
        fullPath: { head: "/users", parts: [] },
        pathParameters: [],
        allPathParameters: [],
        queryParameters: [],
        requestBody: undefined,
        v2RequestBodies: undefined,
        sdkRequest: undefined,
        response: undefined,
        v2Responses: undefined,
        errors: [],
        auth: false,
        security: undefined,
        idempotent: false,
        pagination: undefined,
        userSpecifiedExamples: [],
        autogeneratedExamples: [],
        v2Examples: undefined,
        transport: undefined,
        source: undefined,
        audiences: undefined,
        retries,
        apiPlayground: undefined
    };
}

function createService(retries: FernIr.RetriesConfiguration | undefined): FernIr.HttpService {
    const fernFilepath: FernIr.FernFilepath = { allParts: [], packagePath: [], file: undefined };
    return {
        availability: undefined,
        name: { fernFilepath },
        displayName: undefined,
        basePath: { head: "/users", parts: [] },
        endpoints: [createEndpoint(retries)],
        headers: [],
        pathParameters: [],
        encoding: undefined,
        transport: undefined,
        audiences: undefined
    };
}

function createSubpackage(): FernIr.Subpackage {
    return {
        docs: undefined,
        name: createName("users"),
        displayName: undefined,
        fernFilepath: { allParts: [], packagePath: [], file: undefined },
        service: SERVICE_ID,
        types: [],
        errors: [],
        webhooks: undefined,
        websocket: undefined,
        subpackages: [],
        hasEndpointsInTree: true,
        navigationConfig: undefined
    };
}

function generateClient(retries: FernIr.RetriesConfiguration | undefined): string {
    const service = createService(retries);
    const context = createSampleGeneratorContext();
    context.ir.headers = [];
    context.getHttpServiceOrThrow = () => service;
    context.getSubpackagesOrThrow = () => [];
    context.getUniqueClientNameForSubpackage = () => "UsersClient";
    context.getEndpointSnippet = () => undefined;

    const generator = new SubClientGenerator(context, createSubpackage());
    return generator.generateRawClientContent().rawDeclarations.join("\n");
}

describe("retries configuration", () => {
    it("pins max_retries to zero when the endpoint disables retries", () => {
        const client = generateClient({ disabled: true });
        expect(client).toContain("let mut o = options.unwrap_or_default();");
        expect(client).toContain("o.max_retries = Some(0);");
    });

    it("leaves options untouched when the endpoint does not configure retries", () => {
        const client = generateClient(undefined);
        expect(client).not.toContain("max_retries");
        expect(client).not.toContain("options.unwrap_or_default()");
    });

    it("leaves options untouched when retries are explicitly enabled", () => {
        const client = generateClient({ disabled: false });
        expect(client).not.toContain("max_retries");
    });
});
