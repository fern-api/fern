import { CaseConverter } from "@fern-api/base-generator";
import { FernIr } from "@fern-fern/ir-sdk";
import { describe, expect, it } from "vitest";
import { SubClientGenerator } from "../generators/SubClientGenerator.js";
import { SdkGeneratorContext } from "../SdkGeneratorContext.js";

const caseConverter = new CaseConverter({ generationLanguage: "rust", keywords: undefined, smartCasing: true });

function name(value: string) {
    return {
        originalName: value,
        camelCase: { unsafeName: value, safeName: value },
        snakeCase: { unsafeName: value, safeName: value },
        screamingSnakeCase: { unsafeName: value.toUpperCase(), safeName: value.toUpperCase() },
        pascalCase: { unsafeName: value, safeName: value }
    };
}

function createMockIR(): FernIr.IntermediateRepresentation {
    return {
        apiName: name("TestAPI"),
        apiVersion: "1.0.0",
        errors: {},
        types: {},
        services: {}
    } as unknown as FernIr.IntermediateRepresentation;
}

function createMockContext(ir: FernIr.IntermediateRepresentation): SdkGeneratorContext {
    return {
        ir,
        case: caseConverter,
        customConfig: { generateExamples: false },
        getClientName: () => "TestClient",
        getHttpServiceOrThrow: () => ({ endpoints: [] }) as unknown as FernIr.HttpService,
        getSubpackagesOrThrow: () => [],
        hasMultipleBaseUrls: () => false,
        isEndpointSecurity: () => false,
        getEndpointSnippet: () => undefined,
        escapeRustKeyword: (value: string) => value
    } as unknown as SdkGeneratorContext;
}

/** A path parameter whose value is the given type reference, in a path of `/things/{ids}`. */
function endpointWithPathParameter(valueType: FernIr.TypeReference): FernIr.HttpEndpoint {
    const pathParameter = {
        name: name("ids"),
        valueType,
        location: "ENDPOINT",
        variable: undefined,
        docs: undefined
    } as unknown as FernIr.PathParameter;

    return {
        id: "getThings",
        name: name("getThings"),
        method: "GET",
        path: { head: "/things/", parts: [{ pathParameter: "ids", tail: "" }] },
        fullPath: { head: "/things/", parts: [{ pathParameter: "ids", tail: "" }] },
        pathParameters: [pathParameter],
        allPathParameters: [pathParameter],
        queryParameters: [],
        headers: [],
        errors: [],
        auth: false,
        idempotent: false,
        userSpecifiedExamples: [],
        autogeneratedExamples: []
    } as unknown as FernIr.HttpEndpoint;
}

function pathExpressionFor(valueType: FernIr.TypeReference): string {
    const generator = new SubClientGenerator(createMockContext(createMockIR()), {
        name: name("things"),
        fernFilepath: { allParts: [], packagePath: [], file: { contents: [], extension: "fern" } },
        service: undefined,
        types: [],
        errors: [],
        subpackages: [],
        hasEndpointsInTree: false
    } as unknown as FernIr.Subpackage);

    return (
        generator as unknown as { getPathExpression: (endpoint: FernIr.HttpEndpoint) => string }
    ).getPathExpression(endpointWithPathParameter(valueType));
}

const stringType = FernIr.TypeReference.primitive({
    v1: "STRING",
    v2: undefined
} as unknown as FernIr.PrimitiveType);

describe("path parameters", () => {
    it("interpolates a scalar path parameter directly", () => {
        expect(pathExpressionFor(stringType)).toBe('&format!("/things/{}", ids)');
    });

    // A `Vec<T>` has no `Display`, so interpolating one directly does not compile — the generated
    // crate fails with E0277 and every endpoint in it becomes unusable, not just this one. Regression
    // test rather than a snapshot: the shape of the expression matters less than the fact that it
    // cannot be a bare interpolation again.
    it("joins a list path parameter instead of interpolating the Vec", () => {
        const listOfStrings = FernIr.TypeReference.container(FernIr.ContainerType.list(stringType));
        const expression = pathExpressionFor(listOfStrings);

        expect(expression).not.toBe('&format!("/things/{}", ids)');
        expect(expression).toContain('.join(",")');
        expect(expression).toContain("to_string()");
    });

    it("joins a set path parameter the same way", () => {
        const setOfStrings = FernIr.TypeReference.container(FernIr.ContainerType.set(stringType));
        expect(pathExpressionFor(setOfStrings)).toContain('.join(",")');
    });
});
