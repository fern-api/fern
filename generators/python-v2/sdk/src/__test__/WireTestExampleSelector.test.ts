import { CaseConverter } from "@fern-api/base-generator";
import { FernIr } from "@fern-fern/ir-sdk";
import { describe, expect, it } from "vitest";
import { SdkGeneratorContext } from "../SdkGeneratorContext.js";
import { WireTestExampleSelector } from "../wire-tests/WireTestExampleSelector.js";

const caseConverter = new CaseConverter({ generationLanguage: "python", keywords: undefined, smartCasing: true });

const ROOT_FILEPATH = { allParts: [], packagePath: [], file: undefined };

function createErrorDeclaration(
    errorId: string,
    statusCode: number,
    isWildcardStatusCode = false
): FernIr.ErrorDeclaration {
    return {
        name: { errorId, name: errorId, fernFilepath: ROOT_FILEPATH },
        statusCode,
        isWildcardStatusCode,
        type: { type: "unknown" }
    } as unknown as FernIr.ErrorDeclaration;
}

function createErrorExample(errorId: string): FernIr.ExampleEndpointCall {
    return {
        response: { type: "error", error: { errorId }, body: { jsonExample: { message: errorId } } }
    } as unknown as FernIr.ExampleEndpointCall;
}

function createSelector(errors: FernIr.ErrorDeclaration[]): WireTestExampleSelector {
    const context = {
        ir: {
            errors: Object.fromEntries(errors.map((error) => [error.name.errorId, error])),
            errorDiscriminationStrategy: { type: "statusCode" },
            auth: undefined
        },
        customConfig: {},
        caseConverter,
        getModulePath: () => "seed"
    } as unknown as SdkGeneratorContext;
    return new WireTestExampleSelector(context);
}

function getExpectedErrors(
    errors: FernIr.ErrorDeclaration[],
    endpointErrorIds: string[],
    exampleErrorIds: string[]
): { errorName: string; statusCode: number; typed: boolean }[] {
    const service = { name: { fernFilepath: ROOT_FILEPATH } } as unknown as FernIr.HttpService;
    const endpoint = {
        id: "endpoint_get",
        name: "get",
        errors: endpointErrorIds.map((errorId) => ({ error: { errorId } })),
        userSpecifiedExamples: [],
        autogeneratedExamples: exampleErrorIds.map((errorId) => ({ example: createErrorExample(errorId) }))
    } as unknown as FernIr.HttpEndpoint;
    return createSelector(errors)
        .getExamples(service, endpoint)
        .map(({ expectedError }) => ({
            errorName: expectedError?.errorName ?? "",
            statusCode: expectedError?.statusCode ?? 0,
            typed: expectedError?.errorClass != null
        }));
}

// The generated client checks `_response.status_code == <statusCode>` for each endpoint error in
// declaration order and has no 4XX/5XX range checks; a wildcard error's statusCode is its base value.
describe("WireTestExampleSelector status-code dispatch", () => {
    const clientError = createErrorDeclaration("ClientError", 400, true);
    const badRequest = createErrorDeclaration("BadRequestError", 400);
    const notFound = createErrorDeclaration("NotFoundError", 404);

    it("expects a 4XX wildcard declared before a concrete 400 and skips the shadowed concrete error", () => {
        expect(
            getExpectedErrors(
                [clientError, badRequest],
                ["ClientError", "BadRequestError"],
                ["ClientError", "BadRequestError"]
            )
        ).toEqual([{ errorName: "ClientError", statusCode: 400, typed: true }]);
    });

    it("expects a concrete 400 declared before a 4XX wildcard and skips the shadowed wildcard error", () => {
        expect(
            getExpectedErrors(
                [clientError, badRequest],
                ["BadRequestError", "ClientError"],
                ["ClientError", "BadRequestError"]
            )
        ).toEqual([{ errorName: "BadRequestError", statusCode: 400, typed: true }]);
    });

    it("expects the base ApiError for a status only covered by a 4XX wildcard range", () => {
        expect(getExpectedErrors([clientError, notFound], ["ClientError"], ["NotFoundError"])).toEqual([
            { errorName: "NotFoundError", statusCode: 404, typed: false }
        ]);
    });
});
