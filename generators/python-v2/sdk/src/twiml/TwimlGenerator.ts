import { File } from "@fern-api/base-generator";
import { RelativeFilePath } from "@fern-api/fs-utils";
import { python } from "@fern-api/python-ast";
import { WriteablePythonFile } from "@fern-api/python-base";
import { FernIr } from "@fern-fern/ir-sdk";

import { type OutputDirectory } from "../SdkCustomConfig.js";
import { SdkGeneratorContext } from "../SdkGeneratorContext.js";
import { pythonString, TwimlBuilderGenerator } from "./TwimlBuilderGenerator.js";
import { TWIML_PACKAGE, TwimlNames } from "./TwimlNames.js";
import { TWIML_RUNTIME_SOURCE } from "./TwimlRuntime.js";
import { TwimlSnippetGenerator } from "./TwimlSnippetGenerator.js";

const GENERATED_HEADER = "This file was auto-generated by Fern from our API Definition.";
const EXAMPLES_TEST_FILENAME = "test_twiml_examples";
const EXAMPLES_TEST_DIRECTORY = "tests/twiml";
const SOURCE_ROOT: OutputDirectory = "source-root";

/**
 * Emits the `<package>/twiml/` subpackage: the XML runtime (`__init__.py`), one builder module
 * per namespace, and — unless the SDK is embedded at the source root, where no `tests/` tree is
 * generated — a pytest module that runs each docs example snippet and asserts its XML matches.
 */
export class TwimlGenerator {
    private readonly context: SdkGeneratorContext;
    private readonly twiml: FernIr.TwimlDefinition;
    private readonly packagePath: string[];
    private readonly namesByNamespace: Map<FernIr.TwimlNamespace, TwimlNames>;
    private readonly namesByTag: Map<FernIr.TwimlTagId, TwimlNames>;

    constructor({ context, twiml }: { context: SdkGeneratorContext; twiml: FernIr.TwimlDefinition }) {
        this.context = context;
        this.twiml = twiml;
        this.packagePath = [...context.getModulePath().split("."), TWIML_PACKAGE];
        this.namesByNamespace = new Map(
            twiml.namespaces.map((namespace) => [namespace, new TwimlNames(context.caseConverter, namespace)])
        );
        this.namesByTag = new Map(
            [...this.namesByNamespace].flatMap(([namespace, names]) =>
                Object.keys(namespace.tags).map((tagId): [FernIr.TwimlTagId, TwimlNames] => [tagId, names])
            )
        );
    }

    public generate(): void {
        const sourceDirectory = this.getSourceDirectory();
        this.context.project.addRawFiles(new File("__init__.py", sourceDirectory, TWIML_RUNTIME_SOURCE));

        for (const [namespace, names] of this.namesByNamespace) {
            const builders = new TwimlBuilderGenerator({ namespace, names, packagePath: this.packagePath });
            this.context.project.addSourceFiles(
                new WriteablePythonFile({
                    filename: names.getModuleName(),
                    directory: sourceDirectory,
                    contents: builders.generate()
                })
            );
        }

        if (!this.isSourceRoot() && this.twiml.examples.length > 0) {
            this.context.project.addSourceFiles(
                new WriteablePythonFile({
                    filename: EXAMPLES_TEST_FILENAME,
                    directory: RelativeFilePath.of(EXAMPLES_TEST_DIRECTORY),
                    contents: this.generateExamplesTest()
                })
            );
        }
    }

    /** Mirrors `buildReference.ts`: `src/<package>/twiml` unless the SDK is written at the source root. */
    private getSourceDirectory(): RelativeFilePath {
        const packageDirectory = this.packagePath.join("/");
        return RelativeFilePath.of(this.isSourceRoot() ? packageDirectory : `src/${packageDirectory}`);
    }

    private isSourceRoot(): boolean {
        return this.context.customConfig.output_directory === SOURCE_ROOT;
    }

    private generateExamplesTest(): python.PythonFile {
        const file = python.file({
            path: [...EXAMPLES_TEST_DIRECTORY.split("/"), EXAMPLES_TEST_FILENAME],
            comments: [python.comment({ docs: GENERATED_HEADER })]
        });
        file.addStatement(python.codeBlock("import xml.etree.ElementTree as ET"));
        file.addStatement(
            python.codeBlock(
                ["def canonical(xml: str) -> str:", "    return ET.canonicalize(xml, strip_text=True)"].join("\n")
            )
        );

        for (const example of this.twiml.examples) {
            file.addStatement(this.generateExampleTest(example));
        }
        return file;
    }

    private generateExampleTest(example: FernIr.TwimlExample): python.AstNode {
        const names = this.getNamesForTag(example.root.tag);
        const snippet = new TwimlSnippetGenerator({ names }).generate(example);
        const testName = `test_${this.context.caseConverter.snakeSafe(example.id)}`;
        const test = python.codeBlock(
            [
                `def ${testName}() -> None:`,
                ...snippet.statements.map((statement) => `    ${statement}`),
                "",
                `    assert canonical(str(${snippet.rootVariable})) == canonical(${pythonString(example.xml)})`
            ].join("\n")
        );
        const modulePath = [...this.packagePath, names.getModuleName()];
        for (const className of snippet.imports) {
            test.addReference(python.reference({ name: className, modulePath }));
        }
        return test;
    }

    private getNamesForTag(tagId: FernIr.TwimlTagId): TwimlNames {
        const names = this.namesByTag.get(tagId);
        if (names == null) {
            throw new Error(`TwiML example references tag '${tagId}' that belongs to no namespace`);
        }
        return names;
    }
}
