import { python } from "@fern-api/python-ast";
import { FernIr } from "@fern-fern/ir-sdk";

import { TWIML_BASE_CLASS, TwimlNames } from "./TwimlNames.js";

export declare namespace TwimlBuilderGenerator {
    interface Args {
        namespace: FernIr.TwimlNamespace;
        names: TwimlNames;
        /** Module path of the generated `twiml` package, e.g. `["acme", "twiml"]`. */
        packagePath: string[];
    }
}

const RUNTIME_FORMAT_VALUE = "format_value";

/**
 * Generates one Python module per TwiML namespace containing a builder class per tag
 * (`class Say(TwiML)`) with a fluent method per allowed child (`response.say(...)`).
 */
export class TwimlBuilderGenerator {
    private readonly namespace: FernIr.TwimlNamespace;
    private readonly names: TwimlNames;
    private readonly packagePath: string[];

    constructor({ namespace, names, packagePath }: TwimlBuilderGenerator.Args) {
        this.namespace = namespace;
        this.names = names;
        this.packagePath = packagePath;
    }

    public generate(): python.PythonFile {
        const file = python.file({
            path: [...this.packagePath, this.names.getModuleName()],
            comments: [python.comment({ docs: "This file was auto-generated by Fern from our API Definition." })]
        });
        for (const tag of this.getTagsInOrder()) {
            file.addStatement(this.generateTagClass(tag));
        }
        return file;
    }

    /** Root first, then every other tag by class name, so the module reads top-down like the docs. */
    private getTagsInOrder(): FernIr.TwimlTag[] {
        const root = this.names.getRootTag();
        const rest = Object.values(this.namespace.tags)
            .filter((tag) => tag.id !== root.id)
            .sort((a, b) => this.names.getClassName(a).localeCompare(this.names.getClassName(b), "en"));
        return [root, ...rest];
    }

    private generateTagClass(tag: FernIr.TwimlTag): python.Class {
        const class_ = python.class_({
            name: this.names.getClassName(tag),
            docs: describe(tag.docs, `<${tag.xmlName}> TwiML element.`),
            extends_: [python.reference({ name: TWIML_BASE_CLASS, modulePath: this.packagePath })]
        });

        class_.add(python.codeBlock(`name = ${pythonString(tag.xmlName)}`));
        const overrides = Object.entries(this.names.getAttributeNameOverrides(tag));
        if (overrides.length > 0) {
            const field = python.codeBlock(
                `ATTRIBUTE_NAMES: ClassVar[Dict[str, str]] = {${overrides
                    .map(([pythonName, xmlName]) => `${pythonString(pythonName)}: ${pythonString(xmlName)}`)
                    .join(", ")}}`
            );
            field.addReference(python.reference({ name: "ClassVar", modulePath: ["typing"] }));
            field.addReference(python.reference({ name: "Dict", modulePath: ["typing"] }));
            class_.add(field);
        }

        class_.add(this.generateConstructor(tag));
        for (const childId of tag.children) {
            class_.add(this.generateChildMethod(this.names.getTagOrThrow(childId)));
        }
        return class_;
    }

    private generateConstructor(tag: FernIr.TwimlTag): python.Method {
        const method = python.method({
            name: "__init__",
            type: python.ClassMethodType.INSTANCE,
            parameters: this.generateParameters(tag),
            return_: python.Type.none(),
            docstring: this.getDocstring({ tag, intro: `Create a new <${tag.xmlName}> element.` })
        });
        const attributeNames = tag.attributes.map((attribute) => this.names.getAttributeName(attribute));
        method.addStatement(
            python.codeBlock(
                `super().__init__(${[...attributeNames.map((name) => `${name}=${name}`), "**kwargs"].join(", ")})`
            )
        );
        if (tag.body != null) {
            const bodyName = this.names.getBodyName(tag.body);
            const assignment = python.codeBlock(
                this.isBodyRequired(tag)
                    ? `self.value = ${RUNTIME_FORMAT_VALUE}(${bodyName})`
                    : `if ${bodyName} is not None:\n    self.value = ${RUNTIME_FORMAT_VALUE}(${bodyName})`
            );
            assignment.addReference(python.reference({ name: RUNTIME_FORMAT_VALUE, modulePath: this.packagePath }));
            method.addStatement(assignment);
        }
        return method;
    }

    private generateChildMethod(child: FernIr.TwimlTag): python.Method {
        const childClassName = this.names.getClassName(child);
        const forwarded: string[] = [];
        if (child.body != null) {
            forwarded.push(this.names.getBodyName(child.body));
        }
        for (const attribute of child.attributes) {
            const name = this.names.getAttributeName(attribute);
            forwarded.push(`${name}=${name}`);
        }
        forwarded.push("**kwargs");

        const method = python.method({
            name: this.names.getChildMethodName(child),
            type: python.ClassMethodType.INSTANCE,
            parameters: this.generateParameters(child),
            // Quoted: the child class may be defined further down the module.
            return_: python.Type.reference(python.reference({ name: `"${childClassName}"` })),
            docstring: this.getDocstring({
                tag: child,
                intro: `Create a <${child.xmlName}> element and append it as a child.`,
                returns: `the newly created <${child.xmlName}> element`
            })
        });
        method.addStatement(python.codeBlock(`return self.nest(${childClassName}(${forwarded.join(", ")}))`));
        return method;
    }

    /** `(body, *, attr_a=None, attr_b=None, **kwargs)` — attributes are keyword-only like twilio-python. */
    private generateParameters(tag: FernIr.TwimlTag): python.Parameter[] {
        const parameters: python.Parameter[] = [];
        if (tag.body != null) {
            const type = this.names.getPythonType(tag.body.type);
            const required = this.isBodyRequired(tag);
            parameters.push(
                python.parameter({
                    name: this.names.getBodyName(tag.body),
                    type: required ? type : python.Type.optional(type),
                    initializer: required ? undefined : python.codeBlock("None")
                })
            );
        }
        if (tag.attributes.length > 0) {
            parameters.push(python.parameter({ name: "*", type: undefined }));
        }
        for (const attribute of tag.attributes) {
            parameters.push(
                python.parameter({
                    name: this.names.getAttributeName(attribute),
                    type: python.Type.optional(this.names.getPythonType(attribute.type)),
                    initializer: python.codeBlock("None")
                })
            );
        }
        parameters.push(python.parameter({ name: "**kwargs", type: python.Type.any() }));
        return parameters;
    }

    /**
     * A tag with children may legitimately be built with no body text (`<Say><emphasis>..`), so the
     * body is only mandatory when the definition requires it and there is nothing else to nest.
     */
    private isBodyRequired(tag: FernIr.TwimlTag): boolean {
        return tag.body != null && tag.body.required && tag.children.length === 0;
    }

    private getDocstring({ tag, intro, returns }: { tag: FernIr.TwimlTag; intro: string; returns?: string }): string {
        const lines = [intro, ""];
        if (tag.body != null) {
            lines.push(`:param ${this.names.getBodyName(tag.body)}: ${describe(tag.body.docs, "element body")}`);
        }
        for (const attribute of tag.attributes) {
            lines.push(
                `:param ${this.names.getAttributeName(attribute)}: ${describe(attribute.docs, `\`${attribute.xmlName}\` attribute`)}`
            );
        }
        lines.push(":param kwargs: additional attributes");
        if (returns != null) {
            lines.push("", `:returns: ${returns}`);
        }
        return lines.join("\n");
    }
}

function describe(docs: string | undefined, fallback: string): string {
    const collapsed = docs?.replace(/\s+/g, " ").trim();
    return collapsed != null && collapsed.length > 0 ? collapsed : fallback;
}

/** Double-quoted Python string literal. */
export function pythonString(value: string): string {
    return `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n")}"`;
}
