import { getOriginalName } from "@fern-api/base-generator";
import { python } from "@fern-api/python-ast";
import { FernIr } from "@fern-fern/ir-sdk";
import { SdkGeneratorContext } from "../SdkGeneratorContext.js";

/**
 * The exception a generated client raises for an error example. `errorClass` is undefined when
 * the client raises the base `ApiError`.
 */
export interface WireTestExpectedError {
    statusCode: number;
    errorName: string;
    errorClass: python.Reference | undefined;
    /** The JSON error body to assert on, or undefined when the body should not be asserted. */
    body: unknown;
}

export interface WireTestExampleCase {
    example: FernIr.ExampleEndpointCall;
    index: number;
    testId: string;
    expectedError: WireTestExpectedError | undefined;
}

/**
 * Selects the examples to generate wire tests for, mirroring the TypeScript and Java generators:
 * all user-specified examples, or the first autogenerated success example when there are none,
 * plus the autogenerated error examples (deduped by error) when no user example covers an error.
 *
 * Both the generated tests and the per-example WireMock stubs are derived from this selection,
 * so each test's `X-Test-Id` header matches exactly one stub.
 */
export class WireTestExampleSelector {
    private readonly cache = new Map<string, WireTestExampleCase[]>();

    constructor(private readonly context: SdkGeneratorContext) {}

    public getExamples(service: FernIr.HttpService, endpoint: FernIr.HttpEndpoint): WireTestExampleCase[] {
        const cached = this.cache.get(endpoint.id);
        if (cached != null) {
            return cached;
        }
        const cases: WireTestExampleCase[] = [];
        for (const example of this.selectExamples(endpoint)) {
            let expectedError: WireTestExpectedError | undefined;
            if (example.response.type === "error") {
                if (this.isAuthTokenEndpoint(endpoint)) {
                    // The test client fetches a token from this endpoint before the call under test,
                    // so an error stub for it would fail the token fetch rather than the call.
                    continue;
                }
                expectedError = this.getExpectedError(endpoint, example.response);
                if (expectedError == null) {
                    continue;
                }
            }
            const index = cases.length;
            cases.push({
                example,
                index,
                testId: this.buildTestId(service, endpoint, index),
                expectedError
            });
        }
        this.cache.set(endpoint.id, cases);
        return cases;
    }

    /** Returns the test ID for an example, or undefined when no wire test is generated for it. */
    public getTestId(
        service: FernIr.HttpService,
        endpoint: FernIr.HttpEndpoint,
        example: FernIr.ExampleEndpointCall
    ): string | undefined {
        return this.getExamples(service, endpoint).find((testCase) => testCase.example === example)?.testId;
    }

    private selectExamples(endpoint: FernIr.HttpEndpoint): FernIr.ExampleEndpointCall[] {
        const userExamples = endpoint.userSpecifiedExamples.flatMap((example) =>
            example.example != null ? [example.example] : []
        );
        const autogeneratedExamples = endpoint.autogeneratedExamples.flatMap((example) =>
            example.example != null ? [example.example] : []
        );
        const isError = (example: FernIr.ExampleEndpointCall) => example.response.type === "error";

        const selected = [...userExamples];
        if (userExamples.length === 0) {
            const firstSuccessExample = autogeneratedExamples.find((example) => !isError(example));
            if (firstSuccessExample != null) {
                selected.push(firstSuccessExample);
            }
        }
        const includeAutogeneratedErrors =
            this.context.customConfig.wire_tests?.fallback_to_autogenerated_error_examples !== false;
        if (includeAutogeneratedErrors && !userExamples.some(isError)) {
            const seenErrorIds = new Set<string>();
            for (const example of autogeneratedExamples) {
                const response = example.response;
                if (response.type !== "error" || seenErrorIds.has(response.error.errorId)) {
                    continue;
                }
                seenErrorIds.add(response.error.errorId);
                selected.push(example);
            }
        }
        return selected;
    }

    /**
     * Resolves the exception the generated client raises for an error example. With status-code
     * discrimination the client checks the endpoint's errors in declaration order and raises the
     * first one whose status code matches, so examples for errors shadowed by an earlier error with
     * the same status code are skipped; undeclared status codes raise the base `ApiError`. Other
     * discrimination strategies, and error examples without a body for an error that declares a
     * body type, are expected to raise (at least) the base `ApiError`.
     */
    private getExpectedError(
        endpoint: FernIr.HttpEndpoint,
        response: FernIr.ExampleEndpointErrorResponse
    ): WireTestExpectedError | undefined {
        const errorId = response.error.errorId;
        const errorDeclaration = this.context.ir.errors[errorId];
        if (errorDeclaration == null || errorDeclaration.statusCode < 400) {
            return undefined;
        }
        const statusCode = errorDeclaration.statusCode;
        const errorName = getOriginalName(errorDeclaration.name.name);
        const body = response.body?.jsonExample;
        const hasBody = body != null;
        const base: WireTestExpectedError = { statusCode, errorName, errorClass: undefined, body: undefined };

        if (this.context.ir.errorDiscriminationStrategy.type !== "statusCode") {
            return base;
        }
        if (!hasBody && errorDeclaration.type != null) {
            return base;
        }

        const dispatchedErrorId = endpoint.errors
            .map((responseError) => this.context.ir.errors[responseError.error.errorId])
            .find((declaration) => declaration?.statusCode === statusCode)?.name.errorId;
        if (dispatchedErrorId == null) {
            return { ...base, body };
        }
        if (dispatchedErrorId !== errorId) {
            return undefined;
        }
        return {
            statusCode,
            errorName,
            errorClass: this.getErrorClassReference(errorDeclaration),
            body: errorDeclaration.type != null ? body : undefined
        };
    }

    private getErrorClassReference(errorDeclaration: FernIr.ErrorDeclaration): python.Reference {
        return python.reference({
            name: this.context.caseConverter.pascalSafe(errorDeclaration.name.name),
            modulePath: [
                this.context.getModulePath(),
                ...errorDeclaration.name.fernFilepath.allParts.map((part) => this.getModuleName(part))
            ]
        });
    }

    private getModuleName(name: FernIr.NameOrString): string {
        const originalName = getOriginalName(name);
        const leading = originalName.match(/^(_+)/)?.[1] ?? "";
        const core = originalName.slice(leading.length);
        const trailing = core.match(/(_+)$/)?.[1] ?? "";
        return `${leading}${this.context.caseConverter.snakeSafe(name)}${trailing}`;
    }

    private isAuthTokenEndpoint(endpoint: FernIr.HttpEndpoint): boolean {
        return (this.context.ir.auth?.schemes ?? []).some((scheme) => {
            if (scheme.type === "inferred") {
                return scheme.tokenEndpoint.endpoint.endpointId === endpoint.id;
            }
            if (scheme.type === "oauth" && scheme.configuration?.type === "clientCredentials") {
                return scheme.configuration.tokenEndpoint.endpointReference.endpointId === endpoint.id;
            }
            return false;
        });
    }

    /**
     * Builds a deterministic test ID based on the fully qualified service path.
     * Format: service.sub_service.endpoint_name.example_index
     * Example: "endpoints.primitive.get_and_return_string.0"
     */
    private buildTestId(service: FernIr.HttpService, endpoint: FernIr.HttpEndpoint, exampleIndex: number): string {
        const servicePathParts = service.name.fernFilepath.allParts.map((part) =>
            this.context.caseConverter.snakeSafe(part)
        );
        const segments: string[] = [];
        if (servicePathParts.length > 0) {
            segments.push(servicePathParts.join("."));
        }
        segments.push(this.context.caseConverter.snakeSafe(endpoint.name));
        segments.push(String(exampleIndex));
        return segments.join(".");
    }
}
