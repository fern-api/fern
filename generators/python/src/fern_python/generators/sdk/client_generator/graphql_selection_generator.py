import typing

import fern.ir.resources as ir_types
from fern_python.codegen import AST, Filepath, Project
from fern_python.generators.sdk.context.sdk_generator_context import SdkGeneratorContext
from fern_python.utils.name_resolver import get_name_from_wire_value, get_wire_value, resolve_name


class GraphqlSelectionGenerator:
    """
    Generates one fluent selection-builder class per selectable GraphQL type (PRD §11.3, Strategy A).

    Each ``<Type>Selection`` subclasses the ``GraphqlSelection`` runtime base and exposes a method
    per field — scalar fields record themselves; object fields take a nested selection lambda. The
    builders are emitted into a single root-level ``graphql_selections.py`` module (the M0 spike
    confirmed this scales to ~500 classes with sub-second type-checking).
    """

    MODULE_NAME = "graphql_selections"

    def __init__(self, context: SdkGeneratorContext):
        self._context = context

    # ---- public references used by the endpoint generator ----

    def get_reference_to_builder_for_type_reference(
        self, type_reference: ir_types.TypeReference
    ) -> typing.Optional[AST.ClassReference]:
        type_id = self._unwrap_to_type_id(type_reference)
        if type_id is None:
            return None
        decl = self._context.ir.types.get(type_id)
        if decl is None or not self._is_selectable(decl):
            return None
        return AST.ClassReference(
            qualified_name_excluding_import=(),
            import_=AST.ReferenceImport(
                # Module.local resolves relative to the package root, so pass only the module name
                # (the package prefix is added by the import system).
                module=AST.Module.local(self.MODULE_NAME),
                named_import=self._class_name(decl),
            ),
        )

    # ---- generation ----

    def generate(self, project: Project) -> None:
        selectable = [decl for decl in self._context.ir.types.values() if self._is_selectable(decl)]
        if len(selectable) == 0:
            return
        core_module = ".".join(self._context.core_utilities._module_path)
        chunks: typing.List[str] = [
            "# This file was auto-generated by Fern.\n",
            "import typing\n",
            f"from .{core_module}.graphql import GraphqlSelection\n",
            "\n\n",
        ]
        exports: typing.Set[str] = set()
        for decl in selectable:
            class_name = self._class_name(decl)
            exports.add(class_name)
            chunks.append(self._render_class(decl, class_name))
            chunks.append("\n\n")
        filepath = Filepath(directories=(), file=Filepath.FilepathPart(module_name=self.MODULE_NAME))
        nested_filepath = project.get_source_file_filepath(filepath, include_src_root=True)
        project.add_file(nested_filepath, "".join(chunks))
        project.register_export_in_project(filepath_in_project=filepath, exports=exports)

    # ---- helpers ----

    def _class_name(self, decl: ir_types.TypeDeclaration) -> str:
        return f"{resolve_name(decl.name.name).pascal_case.safe_name}Selection"

    def _is_selectable(self, decl: ir_types.TypeDeclaration) -> bool:
        return decl.shape.visit(
            alias=lambda _a: False,
            enum=lambda _e: False,
            object=lambda _o: True,
            union=lambda _u: False,
            undiscriminated_union=lambda _u: True,
        )

    def _unwrap_to_type_id(self, type_reference: ir_types.TypeReference) -> typing.Optional[str]:
        return type_reference.visit(
            container=lambda container: self._unwrap_container(container),
            named=lambda named: named.type_id,
            primitive=lambda _p: None,
            unknown=lambda: None,
        )

    def _unwrap_container(self, container: ir_types.ContainerType) -> typing.Optional[str]:
        return container.visit(
            list_=lambda inner: self._unwrap_to_type_id(inner),
            optional=lambda inner: self._unwrap_to_type_id(inner),
            nullable=lambda inner: self._unwrap_to_type_id(inner),
            set_=lambda inner: self._unwrap_to_type_id(inner),
            map_=lambda _m: None,
            literal=lambda _l: None,
        )

    def _render_class(self, decl: ir_types.TypeDeclaration, class_name: str) -> str:
        return decl.shape.visit(
            alias=lambda _a: "",
            enum=lambda _e: "",
            union=lambda _u: "",
            object=lambda obj: self._render_object_class(obj, class_name),
            undiscriminated_union=lambda union: self._render_union_class(union, class_name),
        )

    def _render_object_class(self, obj: ir_types.ObjectTypeDeclaration, class_name: str) -> str:
        properties = list(obj.properties) + list(obj.extended_properties or [])
        leaf_wires: typing.List[str] = []
        methods: typing.List[str] = []
        seen: typing.Set[str] = set()
        for prop in properties:
            wire = get_wire_value(prop.name)
            method = resolve_name(get_name_from_wire_value(prop.name)).snake_case.safe_name
            if method in seen or method == "all_":
                continue
            seen.add(method)
            child = self._builder_name_for_type_reference(prop.value_type)
            if child is not None:
                methods.append(
                    f'    def {method}(self, selection: typing.Callable[["{child}"], typing.Any], '
                    f"*, args: typing.Optional[typing.Dict[str, typing.Any]] = None) -> "
                    f'"{class_name}":\n'
                    f"        _child = {child}()\n"
                    f"        selection(_child)\n"
                    f'        self._selection["{wire}"] = (_child, args)\n'
                    f"        return self\n\n"
                )
            else:
                leaf_wires.append(wire)
                methods.append(
                    f'    def {method}(self) -> "{class_name}":\n'
                    f'        self._selection["{wire}"] = True\n'
                    f"        return self\n\n"
                )
        all_method = [f'    def all_(self) -> "{class_name}":\n']
        all_method.append('        self._selection["__typename"] = True\n')
        for wire in leaf_wires:
            all_method.append(f'        self._selection["{wire}"] = True\n')
        all_method.append("        return self\n\n")
        return f"class {class_name}(GraphqlSelection):\n" + "".join(all_method) + "".join(methods)

    def _render_union_class(self, union: ir_types.UndiscriminatedUnionTypeDeclaration, class_name: str) -> str:
        methods: typing.List[str] = []
        for member in union.members:
            member_id = self._unwrap_to_type_id(member.type)
            member_decl = self._context.ir.types.get(member_id) if member_id is not None else None
            if member_decl is None or not self._is_selectable(member_decl):
                continue
            graphql_type = resolve_name(member_decl.name.name).original_name
            method = resolve_name(member_decl.name.name).snake_case.safe_name
            child = self._class_name(member_decl)
            methods.append(
                f'    def on_{method}(self, selection: typing.Callable[["{child}"], typing.Any]) -> '
                f'"{class_name}":\n'
                f"        _child = {child}()\n"
                f"        selection(_child)\n"
                f'        self._selection["__on_{graphql_type}"] = _child\n'
                f"        return self\n\n"
            )
        body = "".join(methods) if methods else "    pass\n"
        return f"class {class_name}(GraphqlSelection):\n" + body

    def _builder_name_for_type_reference(self, type_reference: ir_types.TypeReference) -> typing.Optional[str]:
        type_id = self._unwrap_to_type_id(type_reference)
        if type_id is None:
            return None
        decl = self._context.ir.types.get(type_id)
        if decl is None or not self._is_selectable(decl):
            return None
        return self._class_name(decl)
