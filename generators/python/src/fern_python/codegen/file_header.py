from typing import Optional

FERN_HEADER = "# This file was auto-generated by Fern from our API Definition."
WHITELABEL_HEADER = "# This file was auto-generated from our API Definition."


def get_file_header(*, license_header: Optional[str] = None, whitelabel: bool = False) -> str:
    """Build the comment block prepended to every generated Python file.

    A user-supplied `license_header` is emitted above the auto-generated notice.
    Lines that are not already comments are prefixed with `#`, so the header may
    be configured as plain prose or as pre-commented text.
    """
    header = WHITELABEL_HEADER if whitelabel else FERN_HEADER
    if license_header is None:
        return f"{header}\n\n"
    return f"{_as_comment(license_header)}\n\n{header}\n\n"


def _as_comment(text: str) -> str:
    return "\n".join(
        line if line.startswith("#") else (f"# {line}" if line.strip() else "#")
        for line in text.rstrip("\n").split("\n")
    )
