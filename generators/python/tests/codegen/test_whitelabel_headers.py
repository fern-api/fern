from pathlib import Path

import pytest

from fern_python.codegen.filepath import ExportStrategy, Filepath
from fern_python.codegen.project import Project

FERN_NOTICE = "auto-generated by Fern"
WHITELABEL_NOTICE = "# This file was auto-generated from our API Definition."


def _generate(tmp_path: Path, *, whitelabel: bool) -> Path:
    core_file_on_disk = tmp_path / "core_on_disk.py"
    core_file_on_disk.write_text("# This file was auto-generated by Fern from our API Definition.\n\nX = 1\n")
    output = tmp_path / "output"
    with Project(
        filepath=str(output),
        relative_path_to_project="acme",
        whitelabel=whitelabel,
        pypi_metadata=None,
        github_output_mode=None,
        license_=None,
    ) as project:
        project.add_source_file_from_disk(
            path_on_disk=str(core_file_on_disk),
            filepath_in_project=Filepath(
                directories=(
                    Filepath.DirectoryFilepathPart(
                        module_name="core", export_strategy=ExportStrategy(export_all=True)
                    ),
                ),
                file=Filepath.FilepathPart(module_name="utils"),
            ),
            exports={"X"},
        )
        project.add_file(
            project.get_source_file_filepath(
                Filepath(directories=(), file=Filepath.FilepathPart(module_name="handwritten")), include_src_root=True
            ),
            f"{project.auto_generated_notice}\n\nY = 2\n",
        )
    return output


@pytest.mark.parametrize("relative_path", ["__init__.py", "core/__init__.py", "core/utils.py", "handwritten.py"])
def test_whitelabel_removes_fern_from_every_header(tmp_path: Path, relative_path: str) -> None:
    contents = (_generate(tmp_path, whitelabel=True) / relative_path).read_text()
    assert contents.startswith(WHITELABEL_NOTICE)
    assert FERN_NOTICE not in contents


@pytest.mark.parametrize("relative_path", ["__init__.py", "core/__init__.py", "core/utils.py", "handwritten.py"])
def test_default_header_mentions_fern(tmp_path: Path, relative_path: str) -> None:
    contents = (_generate(tmp_path, whitelabel=False) / relative_path).read_text()
    assert contents.startswith(f"# This file was {FERN_NOTICE} from our API Definition.")
    assert contents.count(FERN_NOTICE) == 1
