from fern_python.codegen.file_header import get_file_header


def test_default_header() -> None:
    assert get_file_header() == "# This file was auto-generated by Fern from our API Definition.\n\n"


def test_whitelabel_header() -> None:
    assert get_file_header(whitelabel=True) == "# This file was auto-generated from our API Definition.\n\n"


def test_license_header_is_commented() -> None:
    assert get_file_header(license_header="Copyright 2024 Acme, Inc.\n\nAll rights reserved.\n") == (
        "# Copyright 2024 Acme, Inc.\n"
        "#\n"
        "# All rights reserved.\n"
        "\n"
        "# This file was auto-generated by Fern from our API Definition.\n"
        "\n"
    )


def test_license_header_preserves_existing_comments() -> None:
    assert get_file_header(license_header="# Copyright 2024 Acme, Inc.", whitelabel=True) == (
        "# Copyright 2024 Acme, Inc.\n\n# This file was auto-generated from our API Definition.\n\n"
    )
