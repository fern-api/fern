import { ast } from "@fern-api/csharp-codegen";
import { FernIr } from "@fern-fern/ir-sdk";

import { SdkGeneratorContext } from "../../SdkGeneratorContext.js";
import { exampleOmitsRequestBody } from "../../utils/exampleUtils.js";

/** The exception the generated client is expected to throw for an error example. */
export interface ExpectedMockServerError {
    statusCode: number;
    /** The class the test asserts is thrown: the typed error class, or the base API exception. */
    exceptionClassReference: ast.ClassReference;
    /** Whether the expected exception is the base API exception, whose body is the raw response string. */
    isBaseApiException: boolean;
    /** The C# class name of the declared error, used to name the test. */
    errorClassName: string;
}

export interface MockServerTestExample {
    example: FernIr.ExampleEndpointCall;
    /** Set for error examples. */
    expectedError?: ExpectedMockServerError;
}

/**
 * Returns the examples to generate mock server tests for, mirroring the TypeScript and Java generators:
 * every user-specified example, or the first autogenerated success example when the endpoint has none,
 * plus the endpoint's autogenerated error examples (one per error) when no user example is an error.
 */
export function getMockServerTestExamples({
    context,
    endpoint
}: {
    context: SdkGeneratorContext;
    endpoint: FernIr.HttpEndpoint;
}): MockServerTestExample[] {
    const userExamples = endpoint.userSpecifiedExamples.flatMap((example) =>
        example.example != null && isUsableExample({ context, endpoint, example: example.example })
            ? [example.example]
            : []
    );
    const autogeneratedExamples = endpoint.autogeneratedExamples.flatMap((example) =>
        example.example != null && isUsableExample({ context, endpoint, example: example.example })
            ? [example.example]
            : []
    );

    const selected = [...userExamples];
    if (userExamples.length === 0) {
        const firstSuccessExample = autogeneratedExamples.find((example) => example.response.type === "ok");
        if (firstSuccessExample != null) {
            selected.push(firstSuccessExample);
        }
    }
    if (
        context.settings.wireTestsFallbackToAutogeneratedErrorExamples &&
        !userExamples.some((example) => example.response.type === "error")
    ) {
        const seenErrorIds = new Set<string>();
        for (const example of autogeneratedExamples) {
            if (example.response.type !== "error" || seenErrorIds.has(example.response.error.errorId)) {
                continue;
            }
            seenErrorIds.add(example.response.error.errorId);
            selected.push(example);
        }
    }

    const testExamples: MockServerTestExample[] = [];
    for (const example of selected) {
        if (example.response.type === "error") {
            const expectedError = getExpectedError({
                context,
                endpoint,
                errorId: example.response.error.errorId,
                hasBody: example.response.body?.jsonExample != null
            });
            if (expectedError == null) {
                continue;
            }
            testExamples.push({ example, expectedError });
        } else {
            testExamples.push({ example });
        }
    }
    return testExamples;
}

/**
 * The status code the mock server responds with for an example: the declared error status code for
 * error examples, otherwise the endpoint's declared success status code. Falls back to 200 for
 * undeclared or non-2xx codes, and for bodiless status codes (204/205) on endpoints that return a body.
 */
export function getMockResponseStatusCode({
    context,
    endpoint,
    example
}: {
    context: SdkGeneratorContext;
    endpoint: FernIr.HttpEndpoint;
    example: FernIr.ExampleEndpointCall;
}): number {
    if (example.response.type === "error") {
        return context.ir.errors[example.response.error.errorId]?.statusCode ?? 500;
    }
    const statusCode = endpoint.response?.statusCode;
    if (statusCode == null || statusCode < 200 || statusCode >= 300) {
        return 200;
    }
    if (isBodilessStatusCode(statusCode) && endpoint.response?.body != null) {
        return 200;
    }
    return statusCode;
}

export function isBodilessStatusCode(statusCode: number): boolean {
    return statusCode === 204 || statusCode === 205;
}

function isUsableExample({
    context,
    endpoint,
    example
}: {
    context: SdkGeneratorContext;
    endpoint: FernIr.HttpEndpoint;
    example: FernIr.ExampleEndpointCall;
}): boolean {
    // TODO: support other response body types
    if (example.response.type === "ok" && example.response.value.type !== "body") {
        return false;
    }
    // Skip examples with empty string path parameters. An empty path parameter
    // causes a URL mismatch: the mock server registers a collapsed path (e.g.
    // /v0/tools/version/1) while the SDK client sends a double-slash path (e.g.
    // /v0/tools//version/1), resulting in a 404 from WireMock.
    if (hasEmptyPathParameter(example)) {
        return false;
    }
    if (exampleOmitsRequestBody({ context, endpoint, example })) {
        return false;
    }
    return true;
}

function hasEmptyPathParameter(example: FernIr.ExampleEndpointCall): boolean {
    const allPathParams = [
        ...example.rootPathParameters,
        ...example.servicePathParameters,
        ...example.endpointPathParameters
    ];
    return allPathParams.some((param) => param.value.jsonExample === "");
}

/**
 * Resolves the exception the generated client throws for an error example. With status-code
 * discrimination the client maps each status code to the first declared error with that status code
 * and throws the base API exception for undeclared ones; examples for errors shadowed by another
 * error with the same status code are skipped. With property discrimination (or when error types are
 * not generated) the client always throws the base API exception. The mock server responds with an
 * empty body to error examples without a body, which can't be parsed into an error that declares a
 * body type, so the client throws the base API exception for those too.
 */
function getExpectedError({
    context,
    endpoint,
    errorId,
    hasBody
}: {
    context: SdkGeneratorContext;
    endpoint: FernIr.HttpEndpoint;
    errorId: string;
    hasBody: boolean;
}): ExpectedMockServerError | undefined {
    const errorDeclaration = context.ir.errors[errorId];
    if (errorDeclaration == null || errorDeclaration.statusCode < 400) {
        return undefined;
    }
    const statusCode = errorDeclaration.statusCode;
    const errorClassName = context.getExceptionClassReference(errorDeclaration.name).name;
    const base: ExpectedMockServerError = {
        statusCode,
        exceptionClassReference: context.Types.BaseApiException,
        isBaseApiException: true,
        errorClassName
    };

    if (context.ir.errorDiscriminationStrategy.type !== "statusCode" || !context.settings.generateErrorTypes) {
        return base;
    }
    if (!hasBody && errorDeclaration.type != null) {
        return base;
    }
    const dispatchedErrorId = endpoint.errors.find(
        (responseError) => context.ir.errors[responseError.error.errorId]?.statusCode === statusCode
    )?.error.errorId;
    if (dispatchedErrorId == null) {
        return base;
    }
    if (dispatchedErrorId !== errorId) {
        return undefined;
    }
    return {
        statusCode,
        exceptionClassReference: context.getExceptionClassReference(errorDeclaration.name),
        isBaseApiException: false,
        errorClassName
    };
}
