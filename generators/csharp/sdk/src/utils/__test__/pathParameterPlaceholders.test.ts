import { FernIr } from "@fern-fern/ir-sdk";

import { getPathParameterPlaceholder } from "../pathParameterPlaceholders.js";

function name(originalName: string): FernIr.Name {
    return {
        originalName,
        camelCase: { safeName: originalName, unsafeName: originalName },
        pascalCase: { safeName: originalName, unsafeName: originalName },
        snakeCase: { safeName: originalName, unsafeName: originalName },
        screamingSnakeCase: { safeName: originalName, unsafeName: originalName }
    };
}

function pathParameter(originalName: string, valueType: FernIr.TypeReference): FernIr.PathParameter {
    return {
        name: name(originalName),
        valueType,
        location: "ENDPOINT",
        variable: undefined,
        v2Examples: undefined,
        docs: undefined,
        explode: undefined,
        clientDefault: undefined
    };
}

function primitive(v1: FernIr.PrimitiveTypeV1): FernIr.TypeReference {
    return FernIr.TypeReference.primitive({ v1, v2: undefined });
}

function named(typeId: string): FernIr.TypeReference {
    return FernIr.TypeReference.named({
        typeId,
        fernFilepath: { allParts: [], packagePath: [], file: undefined },
        name: name(typeId),
        displayName: undefined,
        default: undefined,
        inline: undefined
    });
}

function typeDeclaration(typeId: string, shape: FernIr.Type): FernIr.TypeDeclaration {
    return {
        name: {
            typeId,
            fernFilepath: { allParts: [], packagePath: [], file: undefined },
            name: name(typeId),
            displayName: undefined
        },
        shape,
        autogeneratedExamples: [],
        userProvidedExamples: [],
        v2Examples: undefined,
        referencedTypes: new Set<FernIr.TypeId>(),
        encoding: undefined,
        source: undefined,
        inline: undefined,
        docs: undefined,
        availability: undefined
    };
}

function aliasOf(typeId: string, aliasOfType: FernIr.TypeReference): FernIr.TypeDeclaration {
    return typeDeclaration(
        typeId,
        FernIr.Type.alias({
            aliasOf: aliasOfType,
            resolvedType: FernIr.ResolvedTypeReference.primitive({ v1: "STRING", v2: undefined })
        })
    );
}

function getPrimitive(example: FernIr.ExampleTypeReference | undefined): FernIr.ExamplePrimitive | undefined {
    return example?.shape.type === "primitive" ? example.shape.primitive : undefined;
}

describe("getPathParameterPlaceholder", () => {
    it("uses the path parameter name for strings", () => {
        const placeholder = getPathParameterPlaceholder({
            pathParameter: pathParameter("objectPath", primitive("STRING")),
            types: {}
        });
        expect(placeholder?.jsonExample).toBe("objectPath");
        expect(getPrimitive(placeholder)).toMatchObject({ type: "string", string: { original: "objectPath" } });
    });

    it("uses a value of the declared primitive type", () => {
        const placeholder = getPathParameterPlaceholder({
            pathParameter: pathParameter("count", primitive("INTEGER")),
            types: {}
        });
        expect(placeholder?.jsonExample).toBe(1);
        expect(getPrimitive(placeholder)).toMatchObject({ type: "integer", integer: 1 });
    });

    it("resolves aliases to their underlying primitive", () => {
        const placeholder = getPathParameterPlaceholder({
            pathParameter: pathParameter("objectPath", named("ObjectPath")),
            types: { ObjectPath: aliasOf("ObjectPath", primitive("STRING")) }
        });
        expect(placeholder?.jsonExample).toBe("objectPath");
        expect(getPrimitive(placeholder)).toMatchObject({ type: "string", string: { original: "objectPath" } });
    });

    it("returns undefined for types with no single-value placeholder", () => {
        expect(
            getPathParameterPlaceholder({
                pathParameter: pathParameter("filter", named("Filter")),
                types: {
                    Filter: typeDeclaration(
                        "Filter",
                        FernIr.Type.object({
                            properties: [],
                            extends: [],
                            extraProperties: false,
                            extendedProperties: undefined,
                            deferredUnionBaseProperties: undefined
                        })
                    )
                }
            })
        ).toBeUndefined();
        expect(
            getPathParameterPlaceholder({
                pathParameter: pathParameter("anything", FernIr.TypeReference.unknown()),
                types: {}
            })
        ).toBeUndefined();
    });
});
