import { FernIr } from "@fern-fern/ir-sdk";
import { describe, expect, it } from "vitest";
import { buildWebhookManifest, defaultWebhookSecretEnv } from "../webhooks.js";

const string = FernIr.TypeReference.primitive({ v1: "STRING", v2: undefined });
const integer = FernIr.TypeReference.primitive({ v1: "INTEGER", v2: undefined });

function webhook(args: {
    name: string;
    method?: FernIr.WebhookHttpMethod;
    properties?: Record<string, FernIr.TypeReference>;
    example?: Record<string, unknown>;
    signature?: FernIr.WebhookSignatureVerification;
}): FernIr.Webhook {
    return {
        id: args.name,
        name: args.name,
        displayName: undefined,
        method: args.method ?? "POST",
        headers: [],
        payload: FernIr.WebhookPayload.inlinedPayload({
            name: `${args.name}Payload`,
            extends: [],
            properties: Object.entries(args.properties ?? {}).map(([wireValue, valueType]) => ({
                name: wireValue,
                valueType,
                docs: undefined,
                availability: undefined
            }))
        }),
        signatureVerification: args.signature,
        fileUploadPayload: undefined,
        responses: undefined,
        examples: undefined,
        v2Examples:
            args.example != null
                ? {
                      userSpecifiedExamples: {
                          default: { name: undefined, payload: args.example }
                      },
                      autogeneratedExamples: {}
                  }
                : undefined,
        docs: undefined,
        availability: undefined
    };
}

const twilioHmac = FernIr.WebhookSignatureVerification.hmac({
    signatureHeaderName: "X-Twilio-Signature",
    algorithm: "SHA1",
    encoding: "BASE64",
    signaturePrefix: undefined,
    payloadFormat: { components: ["NOTIFICATION_URL", "BODY"], delimiter: "", bodySort: "ALPHABETICAL" },
    timestamp: undefined,
    bodyHashBinding: {
        algorithm: "SHA256",
        encoding: "HEX",
        location: FernIr.WebhookBodyHashLocation.queryParameter({ name: "bodySHA256" })
    },
    notificationUrlNormalization: undefined
});

describe("defaultWebhookSecretEnv", () => {
    it("uppercases the binary name and swaps dashes for underscores", () => {
        expect(defaultWebhookSecretEnv("twilio-cli")).toBe("TWILIO_CLI_WEBHOOK_SECRET");
    });
});

describe("buildWebhookManifest", () => {
    it("returns undefined when the IR declares no webhooks", () => {
        expect(buildWebhookManifest({ webhookGroups: {}, types: {}, secretEnv: "X" })).toBeUndefined();
    });

    it("lowers a Twilio-shaped HMAC scheme and prefers the example payload", () => {
        const manifest = buildWebhookManifest({
            webhookGroups: {
                webhooks: [
                    webhook({
                        name: "messageReceived",
                        properties: { MessageSid: string, Body: string },
                        example: { MessageSid: "SM123", Body: "hi" },
                        signature: twilioHmac
                    })
                ]
            },
            types: {},
            secretEnv: "TWILIO_AUTH_TOKEN"
        });
        expect(manifest).toEqual({
            secretEnv: "TWILIO_AUTH_TOKEN",
            webhooks: [
                {
                    name: "message-received",
                    displayName: undefined,
                    docs: undefined,
                    method: "POST",
                    contentType: "form",
                    examplePayload: { MessageSid: "SM123", Body: "hi" },
                    headers: [],
                    signature: {
                        header: "X-Twilio-Signature",
                        algorithm: "SHA1",
                        encoding: "BASE64",
                        prefix: undefined,
                        components: ["NOTIFICATION_URL", "BODY"],
                        delimiter: "",
                        bodySort: "ALPHABETICAL",
                        timestamp: undefined,
                        bodyHash: { algorithm: "SHA256", encoding: "HEX", queryParameter: "bodySHA256" }
                    }
                }
            ]
        });
    });

    it("synthesizes a placeholder payload when there is no example, and defaults to JSON", () => {
        const manifest = buildWebhookManifest({
            webhookGroups: {
                webhooks: [
                    webhook({ name: "callStatus", method: "GET", properties: { CallSid: string, Attempt: integer } })
                ]
            },
            types: {},
            secretEnv: "X"
        });
        const [only] = manifest?.webhooks ?? [];
        expect(only?.method).toBe("GET");
        expect(only?.contentType).toBe("json");
        expect(only?.examplePayload).toEqual({ CallSid: "string", Attempt: 0 });
        expect(only?.signature).toBeUndefined();
    });

    it("prefixes names with the group when there is more than one group", () => {
        const manifest = buildWebhookManifest({
            webhookGroups: {
                messaging: [webhook({ name: "received" })],
                voice: [webhook({ name: "received" })]
            },
            types: {},
            secretEnv: "X"
        });
        expect(manifest?.webhooks.map((w) => w.name)).toEqual(["messaging-received", "voice-received"]);
    });

    it("drops asymmetric schemes (no private key to sign with)", () => {
        const manifest = buildWebhookManifest({
            webhookGroups: {
                webhooks: [
                    webhook({
                        name: "payment",
                        signature: FernIr.WebhookSignatureVerification.asymmetric({
                            signatureHeaderName: "X-Sig",
                            algorithm: "RSA_SHA256",
                            encoding: "BASE64",
                            signaturePrefix: undefined,
                            payloadFormat: { components: ["BODY"], delimiter: "", bodySort: undefined },
                            timestamp: undefined,
                            keySource: FernIr.AsymmetricKeySource.jwks({
                                url: "https://example.com/jwks.json",
                                keyIdHeader: undefined
                            })
                        })
                    })
                ]
            },
            types: {},
            secretEnv: "X"
        });
        expect(manifest?.webhooks[0]?.signature).toBeUndefined();
    });
});
