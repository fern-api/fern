import { FernIr } from "@fern-fern/ir-sdk";
import { mkdir, mkdtemp, rm } from "fs/promises";
import os from "os";
import path from "path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { generateWireTests } from "../wireTests/generateWireTests.js";
import { renderWireTestHarness } from "../wireTests/harness.js";
import type { WireTestCase } from "../wireTests/manifest.js";
import { buildWireTestManifest } from "../wireTests/manifest.js";

/**
 * A deliberately minimal IR fixture: one GET endpoint with a single query
 * parameter and a JSON response body. It carries only the fields
 * `mock-utils` + the manifest builder actually read. The one suppression is
 * the price of not hand-writing every field of the (large) IR type in a test
 * mock — the shape below is what the code under test touches.
 */
function makeSingleEndpointIr(): FernIr.IntermediateRepresentation {
    const example = {
        rootPathParameters: [],
        servicePathParameters: [],
        endpointPathParameters: [],
        serviceHeaders: [],
        endpointHeaders: [],
        queryParameters: [
            {
                name: { wireValue: "limit" },
                value: { jsonExample: 5 }
            }
        ],
        request: undefined,
        response: {
            type: "ok",
            value: { type: "body", value: { jsonExample: { results: ["alice"] } } }
        }
    };
    const endpoint = {
        id: "endpoint_users.search",
        name: { originalName: "search" },
        displayName: "Search",
        method: "GET",
        path: { head: "/users", parts: [] },
        fullPath: { head: "/users", parts: [] },
        auth: false,
        requestBody: undefined,
        response: { statusCode: 200, body: { type: "json" } },
        userSpecifiedExamples: [{ example }],
        autogeneratedExamples: []
    };
    const ir = {
        services: { service_users: { name: { originalName: "users" }, endpoints: [endpoint] } },
        auth: { schemes: [] }
    };
    // @ts-expect-error minimal test fixture — only the fields the manifest
    // builder + mock-utils read are populated; the rest of the IR is elided.
    return ir;
}

describe("buildWireTestManifest", () => {
    it("turns an endpoint example into a naming-independent case", () => {
        const manifest = buildWireTestManifest(makeSingleEndpointIr(), {
            binaryName: "acme-cli",
            rootGroup: null,
            specs: [{ file: "cli/acme-cli/openapi0.json", namespace: null }],
            authEnvVars: []
        });

        expect(manifest.binaryName).toBe("acme-cli");
        expect(manifest.cases).toHaveLength(1);

        const testCase = manifest.cases[0];
        expect(testCase?.method).toBe("GET");
        expect(testCase?.path).toBe("/users");
        expect(testCase?.params).toEqual({ limit: 5 });
        expect(testCase?.body).toBeNull();
        expect(testCase?.response.status).toBe(200);
        expect(JSON.parse(testCase?.response.body ?? "")).toEqual({ results: ["alice"] });
        // The scalar query param is carried as a matcher so the mock enforces it.
        expect(testCase?.queryMatchers).toEqual([{ name: "limit", value: "5" }]);
        expect(testCase?.headerMatchers).toEqual([]);
    });

    it("emits an auth-header matcher for an authenticated bearer endpoint", () => {
        const example = {
            rootPathParameters: [],
            servicePathParameters: [],
            endpointPathParameters: [],
            serviceHeaders: [],
            endpointHeaders: [],
            queryParameters: [],
            request: undefined,
            response: { type: "ok", value: { type: "body", value: { jsonExample: {} } } }
        };
        const endpoint = {
            id: "endpoint_users.me",
            name: { originalName: "me" },
            method: "GET",
            path: { head: "/me", parts: [] },
            fullPath: { head: "/me", parts: [] },
            auth: true,
            requestBody: undefined,
            response: { statusCode: 200, body: { type: "json" } },
            userSpecifiedExamples: [{ example }],
            autogeneratedExamples: []
        };
        const ir = {
            services: { service_users: { name: { originalName: "users" }, endpoints: [endpoint] } },
            auth: { schemes: [{ type: "bearer", key: "token" }] }
        };
        // @ts-expect-error minimal fixture — only fields the builder + mock-utils read.
        const manifest = buildWireTestManifest(ir, {
            binaryName: "acme-cli",
            rootGroup: null,
            specs: [],
            authEnvVars: ["ACME_TOKEN"]
        });
        // mock-utils emits a presence-only Authorization matcher for bearer auth.
        expect(manifest.cases[0]?.headerMatchers).toEqual([{ name: "Authorization", matches: "Bearer .+" }]);
    });

    it("gives each case a unique, rust-identifier-safe id", () => {
        const manifest = buildWireTestManifest(makeSingleEndpointIr(), {
            binaryName: "acme-cli",
            rootGroup: null,
            specs: [],
            authEnvVars: []
        });
        for (const testCase of manifest.cases) {
            expect(testCase.id).toMatch(/^[a-z][a-z0-9_]*$/);
        }
    });

    it("emits no authMock for a non-OAuth CLI", () => {
        const manifest = buildWireTestManifest(makeSingleEndpointIr(), {
            binaryName: "acme-cli",
            rootGroup: null,
            specs: [],
            authEnvVars: []
        });
        expect(manifest.authMock).toBeNull();
    });

    it("synthesizes an OAuth token-endpoint mock at the configured response paths", () => {
        const manifest = buildWireTestManifest(makeSingleEndpointIr(), {
            binaryName: "acme-cli",
            rootGroup: null,
            specs: [],
            authEnvVars: ["ACME_CLIENT_ID", "ACME_CLIENT_SECRET"],
            oauthTokenEndpoint: {
                method: "POST",
                path: "/v1/oauth/token",
                accessTokenPath: ["access_token"],
                expiresInPath: ["expires_in"]
            }
        });
        expect(manifest.authMock).not.toBeNull();
        expect(manifest.authMock?.method).toBe("POST");
        expect(manifest.authMock?.path).toBe("/v1/oauth/token");
        const body = JSON.parse(manifest.authMock?.responseBody ?? "");
        // The token the CLI reads at access_token_path must be present + truthy.
        expect(typeof body.access_token).toBe("string");
        expect(body.access_token.length).toBeGreaterThan(0);
        expect(body.expires_in).toBe(3600);
    });

    it("nests the synthesized token under a dotted access_token path", () => {
        const manifest = buildWireTestManifest(makeSingleEndpointIr(), {
            binaryName: "acme-cli",
            rootGroup: null,
            specs: [],
            authEnvVars: [],
            oauthTokenEndpoint: {
                method: "POST",
                path: "/token",
                accessTokenPath: ["data", "token"],
                expiresInPath: null
            }
        });
        const body = JSON.parse(manifest.authMock?.responseBody ?? "");
        expect(typeof body.data.token).toBe("string");
        expect(body.expires_in).toBeUndefined();
    });
});

describe("renderWireTestHarness", () => {
    const searchCase: WireTestCase = {
        id: "search",
        method: "GET",
        path: "/users",
        params: { limit: 5 },
        body: null,
        queryMatchers: [{ name: "limit", value: "5" }],
        headerMatchers: [],
        response: { status: 200, body: '{"results":[]}' }
    };

    it("references the compiled binary via CARGO_BIN_EXE and emits one test fn per case", () => {
        const rust = renderWireTestHarness({ binaryName: "acme-cli", cases: [searchCase] });
        expect(rust).toContain('env!("CARGO_BIN_EXE_acme-cli")');
        expect(rust).toContain("async fn wire_search()");
        expect(rust).toContain('run_case("search").await;');
        expect(rust).toContain('include_str!("../wiremock/wire-test-cases.json")');
        // Drives the binary generically — never hard-codes a command chain.
        expect(rust).toContain("resolve_command(&manifest");
        // Matches on query params + auth headers, not just method+path.
        expect(rust).toContain("match_query_param(q.name.as_str()");
        expect(rust).toContain("match_header(h.name.as_str()");
        expect(rust).toContain("match_header_regex(h.name.as_str()");
    });

    it("rejects a case id that is not a safe Rust identifier", () => {
        const badCase: WireTestCase = { ...searchCase, id: "bad-id" };
        expect(() => renderWireTestHarness({ binaryName: "acme-cli", cases: [badCase] })).toThrow(/Rust identifier/);
    });
});

describe("generateWireTests", () => {
    let tmpDir: string;

    beforeEach(async () => {
        tmpDir = await mkdtemp(path.join(os.tmpdir(), "wireTests-"));
    });

    afterEach(async () => {
        await rm(tmpDir, { recursive: true, force: true });
    });

    it("skips cleanly when no OpenAPI specs are mounted", async () => {
        const specsDir = path.join(tmpDir, "specs");
        await mkdir(specsDir, { recursive: true });
        // No specs-manifest.json → readSpecsManifest returns null. The skip
        // fires before the IR is read, so a missing IR file is fine here.
        const result = await generateWireTests({
            outputDir: path.join(tmpDir, "out"),
            binaryName: "acme-cli",
            irFilepath: path.join(tmpDir, "ir.json"),
            specsDir,
            authBindings: []
        });
        expect(result.status).toBe("skipped");
        expect(result.caseCount).toBe(0);
    });
});
