import { FernIr } from "@fern-fern/ir-sdk";
import { describe, expect, it } from "vitest";
import {
    CORE_PARTITION_KEY,
    type PartitionService,
    planTypeCratePartitions,
    type TypePartitionInput
} from "../planTypeCratePartitions.js";

/**
 * Partitioning exists so that no single generated crate holds every type: one
 * `rustc` process peaks well past a standard CI runner's memory when it has to
 * type-check and expand serde derives for thousands of types at once.
 *
 * The invariant the emitter depends on is that the only cross-crate edges are
 * leaf -> core. Cargo forbids dependency cycles, so a leaf -> leaf edge would
 * make the generated workspace unbuildable.
 */
function declaredTypeName(typeId: string, subpackage: string): FernIr.DeclaredTypeName {
    return {
        typeId,
        fernFilepath: fernFilepath(subpackage),
        name: typeId,
        displayName: undefined
    };
}

function fernFilepath(subpackage: string): FernIr.FernFilepath {
    const allParts = subpackage.length > 0 ? [subpackage] : [];
    return { allParts, packagePath: allParts, file: undefined };
}

function property(name: string, typeId: string, subpackage: string): FernIr.ObjectProperty {
    return {
        name,
        valueType: FernIr.TypeReference.named({
            ...declaredTypeName(typeId, subpackage),
            default: undefined,
            inline: undefined
        }),
        propertyAccess: undefined,
        defaultValue: undefined,
        v2Examples: undefined,
        availability: undefined,
        docs: undefined
    };
}

function objectType({
    typeId,
    subpackage,
    references = []
}: {
    typeId: string;
    subpackage: string;
    references?: string[];
}): FernIr.TypeDeclaration {
    return {
        name: declaredTypeName(typeId, subpackage),
        shape: FernIr.Type.object({
            extends: [],
            properties: references.map((reference, index) => property(`property${index}`, reference, subpackage)),
            extendedProperties: undefined,
            extraProperties: false,
            deferredUnionBaseProperties: undefined
        }),
        autogeneratedExamples: [],
        userProvidedExamples: [],
        referencedTypes: new Set(references),
        v2Examples: undefined,
        encoding: undefined,
        source: undefined,
        inline: undefined,
        availability: undefined,
        docs: undefined
    };
}

/**
 * An endpoint under `subpackage` whose response body references `responseTypeId`,
 * which is how a service pulls a type into its partition.
 */
function endpointReturning({
    endpointId,
    subpackage,
    responseTypeId
}: {
    endpointId: string;
    subpackage: string;
    responseTypeId: string;
}): PartitionService {
    return {
        name: { fernFilepath: fernFilepath(subpackage) },
        endpoints: [
            {
                id: endpointId,
                requestBody: undefined,
                response: {
                    body: FernIr.HttpResponseBody.json(
                        FernIr.JsonResponse.response({
                            responseBodyType: FernIr.TypeReference.named({
                                ...declaredTypeName(responseTypeId, subpackage),
                                default: undefined,
                                inline: undefined
                            }),
                            docs: undefined,
                            v2Examples: undefined
                        })
                    ),
                    statusCode: undefined,
                    isWildcardStatusCode: undefined,
                    docs: undefined
                },
                errors: [],
                pathParameters: [],
                queryParameters: [],
                headers: []
            }
        ]
    };
}

function ir(types: FernIr.TypeDeclaration[], services: PartitionService[] = []): TypePartitionInput {
    const typesById: Record<string, FernIr.TypeDeclaration> = {};
    for (const type of types) {
        typesById[type.name.typeId] = type;
    }
    const servicesById: Record<string, PartitionService> = {};
    services.forEach((service, index) => {
        servicesById[`service_${index}`] = service;
    });
    return { types: typesById, services: servicesById, errors: {} };
}

function keyOf(plan: ReturnType<typeof planTypeCratePartitions>, typeId: string): string {
    if (plan.core.typeIds.includes(typeId)) {
        return CORE_PARTITION_KEY;
    }
    const leaf = plan.leaves.find((partition) => partition.typeIds.includes(typeId));
    if (leaf == null) {
        throw new Error(`${typeId} was not assigned to any partition`);
    }
    return leaf.key;
}

describe("planTypeCratePartitions", () => {
    it("keeps types only their own subpackage reaches in that subpackage's crate", () => {
        const plan = planTypeCratePartitions(
            ir([
                objectType({ typeId: "Message", subpackage: "messaging", references: ["MessageBody"] }),
                objectType({ typeId: "MessageBody", subpackage: "messaging" }),
                objectType({ typeId: "Call", subpackage: "voice" })
            ])
        );

        expect(plan.leaves.map((partition) => partition.key)).toEqual(["messaging", "voice"]);
        expect(keyOf(plan, "Message")).toBe("messaging");
        expect(keyOf(plan, "MessageBody")).toBe("messaging");
        expect(keyOf(plan, "Call")).toBe("voice");
        expect(plan.core.typeIds).toEqual([]);
    });

    it("hoists a type two subpackages reach into core", () => {
        const plan = planTypeCratePartitions(
            ir([
                objectType({ typeId: "Message", subpackage: "messaging", references: ["ApiError"] }),
                objectType({ typeId: "Call", subpackage: "voice", references: ["ApiError"] }),
                objectType({ typeId: "ApiError", subpackage: "commons" })
            ])
        );

        expect(keyOf(plan, "ApiError")).toBe(CORE_PARTITION_KEY);
        expect(keyOf(plan, "Message")).toBe("messaging");
        expect(keyOf(plan, "Call")).toBe("voice");
    });

    it("hoists everything a shared type references, so core never depends on a leaf", () => {
        const plan = planTypeCratePartitions(
            ir([
                objectType({ typeId: "Message", subpackage: "messaging", references: ["ApiError"] }),
                objectType({ typeId: "Call", subpackage: "voice", references: ["ApiError"] }),
                // Declared under `commons` but only reachable *through* the shared type.
                objectType({ typeId: "ApiError", subpackage: "commons", references: ["ErrorDetail"] }),
                objectType({ typeId: "ErrorDetail", subpackage: "commons" })
            ])
        );

        expect(keyOf(plan, "ApiError")).toBe(CORE_PARTITION_KEY);
        expect(keyOf(plan, "ErrorDetail")).toBe(CORE_PARTITION_KEY);
    });

    it("keeps mutually-referencing types in one crate rather than emitting a cargo cycle", () => {
        const plan = planTypeCratePartitions(
            ir([
                objectType({ typeId: "Node", subpackage: "messaging", references: ["Edge"] }),
                objectType({ typeId: "Edge", subpackage: "messaging", references: ["Node"] })
            ])
        );

        expect(keyOf(plan, "Node")).toBe("messaging");
        expect(keyOf(plan, "Edge")).toBe("messaging");
    });

    it("hoists a reference cycle that spans two subpackages into core", () => {
        const plan = planTypeCratePartitions(
            ir([
                objectType({ typeId: "Node", subpackage: "messaging", references: ["Edge"] }),
                objectType({ typeId: "Edge", subpackage: "voice", references: ["Node"] })
            ])
        );

        expect(keyOf(plan, "Node")).toBe(CORE_PARTITION_KEY);
        expect(keyOf(plan, "Edge")).toBe(CORE_PARTITION_KEY);
        expect(plan.leaves).toEqual([]);
    });

    it("assigns root-level types to core, since they have no subpackage of their own", () => {
        const plan = planTypeCratePartitions(
            ir([
                objectType({ typeId: "RootType", subpackage: "" }),
                objectType({ typeId: "Message", subpackage: "messaging" })
            ])
        );

        expect(keyOf(plan, "RootType")).toBe(CORE_PARTITION_KEY);
        expect(keyOf(plan, "Message")).toBe("messaging");
    });

    it("assigns each endpoint's request structs to its own service's crate", () => {
        const plan = planTypeCratePartitions(
            ir(
                [
                    objectType({ typeId: "Message", subpackage: "messaging" }),
                    objectType({ typeId: "Call", subpackage: "voice" })
                ],
                [
                    endpointReturning({ endpointId: "send", subpackage: "messaging", responseTypeId: "Message" }),
                    endpointReturning({ endpointId: "dial", subpackage: "voice", responseTypeId: "Call" })
                ]
            )
        );

        expect(plan.leaves.map((partition) => ({ key: partition.key, endpointIds: partition.endpointIds }))).toEqual([
            { key: "messaging", endpointIds: ["send"] },
            { key: "voice", endpointIds: ["dial"] }
        ]);
        // Request structs reference their own service's types, so core owning an
        // endpoint would point core at a leaf.
        expect(plan.core.endpointIds).toEqual([]);
    });

    it("hoists a type reached only through two services' endpoints into core", () => {
        // The declaration sits in `messaging`, but `voice`'s endpoint also returns
        // it. Assigning it to `messaging` would leave the `voice` crate referencing
        // across to a leaf, so it has to move to core.
        const plan = planTypeCratePartitions(
            ir(
                [objectType({ typeId: "Message", subpackage: "messaging" })],
                [
                    endpointReturning({ endpointId: "send", subpackage: "messaging", responseTypeId: "Message" }),
                    endpointReturning({ endpointId: "dial", subpackage: "voice", responseTypeId: "Message" })
                ]
            )
        );

        expect(keyOf(plan, "Message")).toBe(CORE_PARTITION_KEY);
        expect(plan.leaves.map((partition) => partition.key)).toEqual(["messaging", "voice"]);
    });

    it("keeps a partition whose types all moved to core, because it still owns endpoints", () => {
        const plan = planTypeCratePartitions(
            ir(
                [objectType({ typeId: "Message", subpackage: "messaging" })],
                [
                    endpointReturning({ endpointId: "send", subpackage: "messaging", responseTypeId: "Message" }),
                    endpointReturning({ endpointId: "dial", subpackage: "voice", responseTypeId: "Message" })
                ]
            )
        );

        const messaging = plan.leaves.find((partition) => partition.key === "messaging");
        expect(messaging?.typeIds).toEqual([]);
        expect(messaging?.endpointIds).toEqual(["send"]);
    });

    it("assigns every type in the IR to exactly one partition", () => {
        const plan = planTypeCratePartitions(
            ir([
                objectType({ typeId: "Message", subpackage: "messaging", references: ["ApiError"] }),
                objectType({ typeId: "Call", subpackage: "voice", references: ["ApiError"] }),
                objectType({ typeId: "ApiError", subpackage: "commons" }),
                objectType({ typeId: "RootType", subpackage: "" })
            ])
        );

        const assigned = [...plan.core.typeIds, ...plan.leaves.flatMap((partition) => partition.typeIds)];
        expect(assigned.sort()).toEqual(["ApiError", "Call", "Message", "RootType"]);
        expect(new Set(assigned).size).toBe(assigned.length);
    });
});
