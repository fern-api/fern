import { MODEL_FILE_MANIFEST_PATH } from "@fern-api/rust-model";
import { mkdir, mkdtemp, readFile, writeFile } from "fs/promises";
import { tmpdir } from "os";
import path from "path";
import { describe, expect, it } from "vitest";
import { CORE_PARTITION_KEY, TypeCratePartitionPlan } from "../planTypeCratePartitions.js";
import { splitTypesCrates } from "../splitTypesCrates.js";

/**
 * Stand up the single types crate as it looks after `patchTypesCrate`, so the
 * split runs against the same input the generator hands it.
 */
async function writeGeneratedTypesCrate({
    typesOutputDir,
    modules
}: {
    typesOutputDir: string;
    modules: { filename: string; moduleName: string; typeName: string; typeId: string }[];
}): Promise<void> {
    const typesDir = path.join(typesOutputDir, "src", "types");
    await mkdir(typesDir, { recursive: true });
    await mkdir(path.join(typesOutputDir, MODEL_FILE_MANIFEST_PATH, ".."), { recursive: true });

    for (const { filename, typeName } of modules) {
        await writeFile(path.join(typesDir, filename), `pub use crate::prelude::*;\npub struct ${typeName} {}\n`);
    }
    await writeFile(path.join(typesOutputDir, "src", "error.rs"), "pub enum BuildError {}\n");
    await writeFile(path.join(typesOutputDir, "src", "lib.rs"), "//! Generated models by Fern\n");
    await writeFile(
        path.join(typesOutputDir, MODEL_FILE_MANIFEST_PATH),
        JSON.stringify({
            modules: modules.map(({ filename, moduleName, typeName, typeId }) => ({
                filename,
                moduleName,
                typeName,
                owner: { kind: "type", typeId }
            }))
        })
    );
}

describe("splitTypesCrates", () => {
    it("emits a core crate the leaf crates depend on for shared types", async () => {
        const outputDir = await mkdtemp(path.join(tmpdir(), "split-types-"));
        const typesOutputDir = path.join(outputDir, "acme-types");
        await writeGeneratedTypesCrate({
            typesOutputDir,
            modules: [
                { filename: "shared.rs", moduleName: "shared", typeName: "Shared", typeId: "type_:Shared" },
                { filename: "widget.rs", moduleName: "widget", typeName: "Widget", typeId: "type_widgets:Widget" }
            ]
        });

        const plan: TypeCratePartitionPlan = {
            core: { key: CORE_PARTITION_KEY, typeIds: ["type_:Shared"], endpointIds: [] },
            leaves: [{ key: "widgets", typeIds: ["type_widgets:Widget"], endpointIds: [] }]
        };

        const result = await splitTypesCrates({
            typesOutputDir,
            typesCrateName: "acme-types",
            plan,
            needsReqwest: false
        });

        expect(result).toEqual({
            facadeCrateName: "acme-types",
            partitionCrates: [
                { crateName: "acme-types-core", relativeDir: "acme-types/crates/acme-types-core" },
                { crateName: "acme-types-widgets", relativeDir: "acme-types/crates/acme-types-widgets" }
            ]
        });

        // The leaf owns only its own type, and reaches the shared one through a
        // path dependency plus a prelude re-export — bare references in the
        // generated code resolve through the prelude.
        const leafDir = path.join(typesOutputDir, "crates", "acme-types-widgets");
        expect(await readFile(path.join(leafDir, "src", "types", "widget.rs"), "utf-8")).toContain("Widget");
        expect(await readFile(path.join(leafDir, "src", "types", "mod.rs"), "utf-8")).toBe(
            "//! Request and response types generated by Fern\n\npub mod widget;\n\npub use widget::Widget;\n"
        );
        expect(await readFile(path.join(leafDir, "src", "prelude.rs"), "utf-8")).toContain(
            "pub use acme_types_core::types::*;"
        );
        expect(await readFile(path.join(leafDir, "Cargo.toml"), "utf-8")).toContain(
            '[dependencies.acme_types_core]\npath = "../acme-types-core"'
        );

        // `BuildError` and the serde helpers are declared once, in core, and
        // borrowed by the leaf. A per-crate copy would make one API's builder
        // error a different type from another's.
        expect(await readFile(path.join(leafDir, "src", "error.rs"), "utf-8")).toContain(
            "pub use acme_types_core::error::*;"
        );
        const leafCoreMod = await readFile(path.join(leafDir, "src", "core", "mod.rs"), "utf-8");
        // Modules, not their items: generated types reach in by path, e.g.
        // `#[serde(with = "crate::core::flexible_datetime::offset::option")]`.
        expect(leafCoreMod).toContain("pub use acme_types_core::core::flexible_datetime;");
        expect(leafCoreMod).toContain("pub use acme_types_core::core::number_serializers;");
        // The leaf borrows them rather than carrying its own copy.
        await expect(readFile(path.join(leafDir, "src", "core", "flexible_datetime.rs"), "utf-8")).rejects.toThrow();

        // Core holds the real definitions.
        const coreDir = path.join(typesOutputDir, "crates", "acme-types-core");
        expect(await readFile(path.join(coreDir, "src", "error.rs"), "utf-8")).toContain("BuildError");
        expect(await readFile(path.join(coreDir, "src", "core", "flexible_datetime.rs"), "utf-8")).not.toBe("");

        // Core must not depend on a leaf: cargo forbids dependency cycles.
        const coreCargoToml = await readFile(path.join(coreDir, "Cargo.toml"), "utf-8");
        expect(coreCargoToml).not.toContain("acme-types-widgets");
        expect(await readFile(path.join(coreDir, "src", "prelude.rs"), "utf-8")).not.toContain("acme_types");

        // The facade keeps the original crate name resolving, and holds no
        // generated code of its own so it stays cheap to compile.
        const facadeLib = await readFile(path.join(typesOutputDir, "src", "lib.rs"), "utf-8");
        expect(facadeLib).toContain("pub use acme_types_core::types::*;");
        expect(facadeLib).toContain("pub use acme_types_widgets::types::*;");
        // Re-exporting the crate roots instead would make `core`, `prelude` and
        // `error` ambiguous at the facade — a warning on every consumer build,
        // and an error under `-D warnings`.
        expect(facadeLib).not.toMatch(/pub use acme_types_(core|widgets)::\*;/);
        // Those three come from core alone, so the facade can name them and keep
        // the un-split crate's module surface intact.
        expect(facadeLib).toContain("pub use acme_types_core::error;");
        expect(facadeLib).toContain("pub use acme_types_core::core;");
        expect(facadeLib).toContain("pub use acme_types_core::prelude;");
        const facadeCargoToml = await readFile(path.join(typesOutputDir, "Cargo.toml"), "utf-8");
        expect(facadeCargoToml).not.toContain("serde");
    });

    it("assigns each generated module to exactly one crate", async () => {
        const outputDir = await mkdtemp(path.join(tmpdir(), "split-types-"));
        const typesOutputDir = path.join(outputDir, "acme-types");
        await writeGeneratedTypesCrate({
            typesOutputDir,
            modules: [
                { filename: "a.rs", moduleName: "a", typeName: "A", typeId: "type_v1:A" },
                { filename: "b.rs", moduleName: "b", typeName: "B", typeId: "type_v2:B" }
            ]
        });

        const { partitionCrates } = await splitTypesCrates({
            typesOutputDir,
            typesCrateName: "acme-types",
            plan: {
                core: { key: CORE_PARTITION_KEY, typeIds: [], endpointIds: [] },
                leaves: [
                    { key: "v1", typeIds: ["type_v1:A"], endpointIds: [] },
                    { key: "v2", typeIds: ["type_v2:B"], endpointIds: [] }
                ]
            },
            needsReqwest: false
        });

        // Core is emitted even with nothing shared to put in it: it is where
        // `BuildError` and the serde helpers live, so the leaves depend on it
        // regardless. It holds no types here.
        expect(partitionCrates.map(({ crateName }) => crateName)).toEqual([
            "acme-types-core",
            "acme-types-v1",
            "acme-types-v2"
        ]);
        // Nested inside the facade, so enabling the flag adds no top-level
        // entry at all — the tree looks as it did with a single types crate.
        expect(partitionCrates.map(({ relativeDir }) => relativeDir)).toEqual([
            "acme-types/crates/acme-types-core",
            "acme-types/crates/acme-types-v1",
            "acme-types/crates/acme-types-v2"
        ]);
        // With no shared types, the leaf preludes must not glob core's empty
        // `types` module — that is an `unused_imports` warning per leaf, and a
        // namespaced multi-spec workspace has one leaf per spec.
        expect(
            await readFile(path.join(typesOutputDir, "crates", "acme-types-v1", "src", "prelude.rs"), "utf-8")
        ).not.toContain("acme_types_core::types::*");
        // The dependency itself stays: the leaf still borrows `BuildError` and
        // the serde helpers from core.
        expect(
            await readFile(path.join(typesOutputDir, "crates", "acme-types-v1", "src", "error.rs"), "utf-8")
        ).toContain("acme_types_core::error::*");
        // Same for core's own lib.rs and the facade: no `types` module to glob.
        const emptyCoreLib = await readFile(
            path.join(typesOutputDir, "crates", "acme-types-core", "src", "lib.rs"),
            "utf-8"
        );
        expect(emptyCoreLib).not.toContain("pub mod types;");
        const facade = await readFile(path.join(typesOutputDir, "src", "lib.rs"), "utf-8");
        expect(facade).not.toContain("acme_types_core::types::*");
        expect(facade).toContain("pub use acme_types_v1::types::*;");
        // The shared modules still come from core.
        expect(facade).toContain("pub use acme_types_core::error;");
        expect(
            await readFile(path.join(typesOutputDir, "crates", "acme-types-core", "src", "types", "mod.rs"), "utf-8")
        ).not.toContain("pub mod ");
        expect(
            await readFile(path.join(typesOutputDir, "crates", "acme-types-v1", "src", "types", "mod.rs"), "utf-8")
        ).toContain("pub use a::A;");
        expect(
            await readFile(path.join(typesOutputDir, "crates", "acme-types-v2", "src", "types", "mod.rs"), "utf-8")
        ).toContain("pub use b::B;");
        expect(
            await readFile(path.join(typesOutputDir, "crates", "acme-types-v1", "src", "types", "mod.rs"), "utf-8")
        ).not.toContain("pub use b::B;");
    });
});
