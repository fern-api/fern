import { CaseConverter } from "@fern-api/base-generator";
import { FernIr } from "@fern-fern/ir-sdk";
import { SdkGeneratorContext } from "../SdkGeneratorContext.js";

/** The error the generated client raises for an error example. */
export interface WireTestExpectedError {
    /** Status code declared on the error in the IR, served by the example's WireMock mapping. */
    statusCode: number;
    /** Fully qualified Ruby class raised for the status code, e.g. `Seed::Errors::NotFoundError`. */
    errorClassReference: string;
    /** Snake-cased IR error name, used in test names. */
    errorName: string;
    /** The example's error body, when it has one. */
    body: unknown;
}

export interface WireTestExample {
    example: FernIr.ExampleEndpointCall;
    /** ID of the matching example in the dynamic IR, used to generate the call snippet. */
    dynamicExampleId: string | undefined;
    /** Value of the `X-Test-Id` header the test sends; also selects the example's WireMock mapping. */
    testId: string;
    /** Set for error examples. */
    expectedError?: WireTestExpectedError;
}

/**
 * Selects the examples to cover with wire tests, mirroring the TypeScript and Java generators: every
 * user-specified example, or the first autogenerated success example when there are none, plus the
 * autogenerated error examples (one per error) unless a user example already covers an error or
 * `wireTestsFallbackToAutoGeneratedErrorExamples` is false.
 */
export class WireTestExampleSelector {
    private readonly context: SdkGeneratorContext;
    private readonly case: CaseConverter;
    private readonly examplesByEndpointId = new Map<string, WireTestExample[]>();
    // Keyed by the IR example object itself, since examples have no stable ID of their own.
    private readonly testIdsByExample = new Map<unknown, string>();
    private readonly endpointsByTestId = new Map<string, { endpoint: FernIr.HttpEndpoint; example: WireTestExample }>();

    constructor(context: SdkGeneratorContext) {
        this.context = context;
        this.case = context.caseConverter;
        for (const service of Object.values(context.ir.services)) {
            for (const endpoint of service.endpoints) {
                const examples = this.selectExamples(service, endpoint);
                this.examplesByEndpointId.set(endpoint.id, examples);
                for (const example of examples) {
                    this.testIdsByExample.set(example.example, example.testId);
                    this.endpointsByTestId.set(example.testId, { endpoint, example });
                }
            }
        }
    }

    public getExamples(endpoint: FernIr.HttpEndpoint): WireTestExample[] {
        return this.examplesByEndpointId.get(endpoint.id) ?? [];
    }

    /** `getExampleTestId` for `WireMock.convertToWireMock`: the test ID of each selected example. */
    public getExampleTestId(example: unknown): string | undefined {
        return this.testIdsByExample.get(example);
    }

    public getByTestId(testId: string): { endpoint: FernIr.HttpEndpoint; example: WireTestExample } | undefined {
        return this.endpointsByTestId.get(testId);
    }

    /**
     * The endpoint's declared success status code. Falls back to 200 for undeclared or non-2xx codes,
     * and for bodiless status codes (204/205) on endpoints that return a body.
     */
    public getSuccessStatusCode(endpoint: FernIr.HttpEndpoint): number {
        const statusCode = endpoint.response?.statusCode;
        if (statusCode == null || statusCode < 200 || statusCode >= 300) {
            return 200;
        }
        if ((statusCode === 204 || statusCode === 205) && endpoint.response?.body != null) {
            return 200;
        }
        return statusCode;
    }

    private selectExamples(service: FernIr.HttpService, endpoint: FernIr.HttpEndpoint): WireTestExample[] {
        const userExamples = endpoint.userSpecifiedExamples.flatMap((example) =>
            example.example != null ? [{ example: example.example, dynamicExampleId: example.example.id }] : []
        );
        const autogeneratedExamples = endpoint.autogeneratedExamples.flatMap((example) =>
            example.example != null ? [{ example: example.example, dynamicExampleId: example.example.id }] : []
        );
        const isError = ({ example }: { example: FernIr.ExampleEndpointCall }) => example.response.type === "error";
        const includeAutogeneratedErrors =
            this.context.customConfig.wireTestsFallbackToAutoGeneratedErrorExamples !== false;

        const selected = [...userExamples];
        if (userExamples.length === 0) {
            const firstSuccessExample = autogeneratedExamples.find((example) => !isError(example));
            if (firstSuccessExample != null) {
                selected.push(firstSuccessExample);
            }
        }
        if (includeAutogeneratedErrors && !userExamples.some(isError)) {
            const seenErrorIds = new Set<string>();
            for (const autogeneratedExample of autogeneratedExamples) {
                const response = autogeneratedExample.example.response;
                if (response.type !== "error" || seenErrorIds.has(response.error.errorId)) {
                    continue;
                }
                seenErrorIds.add(response.error.errorId);
                selected.push(autogeneratedExample);
            }
        }

        const examples: WireTestExample[] = [];
        for (const { example, dynamicExampleId } of selected) {
            let expectedError: WireTestExpectedError | undefined;
            if (example.response.type === "error") {
                expectedError = this.getExpectedError(example.response);
                if (expectedError == null) {
                    continue;
                }
            }
            examples.push({
                example,
                dynamicExampleId,
                testId: this.buildTestId(service, endpoint, examples.length),
                expectedError
            });
        }
        return examples;
    }

    /**
     * The generated client raises `Errors::ResponseError.subclass_for_code(code)` with the raw response body
     * for every non-2xx response, regardless of the error discrimination strategy or which declared error
     * shares the status code, so the expected class only depends on the error's declared status code.
     */
    private getExpectedError(response: FernIr.ExampleResponse.Error): WireTestExpectedError | undefined {
        const errorDeclaration = this.context.ir.errors[response.error.errorId];
        if (errorDeclaration == null || errorDeclaration.statusCode < 400) {
            return undefined;
        }
        const statusCode = errorDeclaration.statusCode;
        return {
            statusCode,
            errorClassReference: `${this.context.getRootModuleName()}::Errors::${getResponseErrorClassName(statusCode)}`,
            errorName: this.case.snakeSafe(errorDeclaration.name.name),
            body: response.body?.jsonExample ?? undefined
        };
    }

    /** `<service path>.<endpoint>.<index>`; the first example keeps index 0. */
    private buildTestId(service: FernIr.HttpService, endpoint: FernIr.HttpEndpoint, exampleIndex: number): string {
        const servicePathParts = service.name.fernFilepath.allParts.map((part) => this.case.snakeSafe(part));
        const segments: string[] = [];
        if (servicePathParts.length > 0) {
            segments.push(servicePathParts.join("."));
        }
        segments.push(this.case.snakeSafe(endpoint.name));
        segments.push(String(exampleIndex));
        return segments.join(".");
    }
}

/** Mirrors `Errors::ResponseError.subclass_for_code` in the generated SDK (errors/response_error.Template.rb). */
function getResponseErrorClassName(statusCode: number): string {
    if (statusCode >= 300 && statusCode <= 399) {
        return "RedirectError";
    }
    switch (statusCode) {
        case 401:
            return "UnauthorizedError";
        case 403:
            return "ForbiddenError";
        case 404:
            return "NotFoundError";
        case 503:
            return "ServiceUnavailableError";
    }
    if (statusCode >= 400 && statusCode <= 499) {
        return "ClientError";
    }
    if (statusCode >= 500 && statusCode <= 599) {
        return "ServerError";
    }
    return "ResponseError";
}
