import { getOriginalName, getWireValue } from "@fern-api/base-generator";
import { FernIr } from "@fern-fern/ir-sdk";
import { SdkGeneratorContext } from "../../SdkGeneratorContext.js";

/**
 * Extracts test data directly from the static IR for wire test validation.
 * This class is responsible for extracting request and response data from examples,
 * separate from the code snippet generation. It is used to generate test data for wire tests.
 */
export class WireTestDataExtractor {
    constructor(private readonly context: SdkGeneratorContext) {}

    /**
     * Returns one test example per example call to test, mirroring the TypeScript generator:
     * all user-specified examples, plus autogenerated error examples when no user example covers
     * an error. Endpoints without user examples get the first autogenerated success example
     * plus the autogenerated error examples.
     */
    public getTestExamples(endpoint: FernIr.HttpEndpoint): WireTestExample[] {
        const userExamples = endpoint.userSpecifiedExamples.flatMap((example, index) =>
            example.example != null
                ? [{ example: example.example, dynamicExampleId: example.example.id ?? `${endpoint.id}-user-${index}` }]
                : []
        );
        const autogeneratedExamples = endpoint.autogeneratedExamples.flatMap((example, index) =>
            example.example != null
                ? [{ example: example.example, dynamicExampleId: example.example.id ?? `${endpoint.id}-auto-${index}` }]
                : []
        );
        const includeAutogeneratedErrors =
            this.context.customConfig["wire-tests-fallback-to-autogenerated-error-examples"] !== false;
        const isError = ({ example }: { example: FernIr.ExampleEndpointCall }) => example.response.type === "error";

        const selected = [...userExamples];
        if (userExamples.length === 0) {
            const firstSuccessExample = autogeneratedExamples.find((example) => !isError(example));
            if (firstSuccessExample != null) {
                selected.push(firstSuccessExample);
            }
        }
        if (includeAutogeneratedErrors && !userExamples.some(isError)) {
            const seenErrorIds = new Set<string>();
            for (const autogeneratedExample of autogeneratedExamples) {
                const response = autogeneratedExample.example.response;
                if (response.type !== "error" || seenErrorIds.has(response.error.errorId)) {
                    continue;
                }
                seenErrorIds.add(response.error.errorId);
                selected.push(autogeneratedExample);
            }
        }

        const examples: WireTestExample[] = [];
        for (const { example, dynamicExampleId } of selected) {
            const extracted = this.extractTestExample(example, endpoint, dynamicExampleId);
            if (extracted) {
                examples.push(extracted);
            }
        }
        return examples;
    }

    private extractTestExample(
        example: FernIr.ExampleEndpointCall,
        endpoint: FernIr.HttpEndpoint,
        dynamicExampleId: string
    ): WireTestExample | undefined {
        let expectedError: WireTestExpectedError | undefined;
        if (example.response.type === "error") {
            expectedError = this.getExpectedError(endpoint, example.response.error.errorId);
            if (expectedError == null) {
                return undefined;
            }
        }

        const requestBody = this.extractRequestBody(example.request, endpoint);

        return {
            id: example.id || `${endpoint.id}-example`,
            dynamicExampleId,
            name: example.name != null ? getOriginalName(example.name) : undefined,
            methodNameSuffix:
                example.name != null
                    ? this.context.caseConverter.pascalSafe(example.name).replace(/[^A-Za-z0-9_]/g, "")
                    : undefined,
            request: {
                body: requestBody,
                headers: this.extractHeaders(example),
                queryParams: this.extractQueryParams(example),
                pathParams: this.extractPathParams(example)
            },
            response: {
                statusCode: expectedError?.statusCode ?? this.getSuccessStatusCode(endpoint),
                body: this.extractResponseBody(example.response)
            },
            expectedError
        };
    }

    /**
     * Resolves the exception the generated client throws for an error example. With status-code
     * discrimination the client maps each status code to the first declared error (by status code)
     * and throws the base API exception for undeclared ones; examples for errors shadowed by another
     * error with the same status code are skipped. With property discrimination the client always
     * throws the base API exception.
     */
    private getExpectedError(endpoint: FernIr.HttpEndpoint, errorId: string): WireTestExpectedError | undefined {
        const errorDeclaration = this.context.ir.errors[errorId];
        if (errorDeclaration == null || errorDeclaration.statusCode < 400) {
            return undefined;
        }
        const statusCode = errorDeclaration.statusCode;
        const baseException = this.context.getApiExceptionClassReference();
        const base: WireTestExpectedError = {
            statusCode,
            className: baseException.name,
            packageName: baseException.packageName
        };

        if (this.context.ir.errorDiscriminationStrategy.type !== "statusCode") {
            return base;
        }

        const dispatchedErrorId = this.getErrorIdsByStatusCode(endpoint).get(statusCode);
        if (dispatchedErrorId == null) {
            return base;
        }
        if (dispatchedErrorId !== errorId) {
            return undefined;
        }
        const errorClass = this.context.getErrorClassReference(errorDeclaration);
        return { statusCode, className: errorClass.name, packageName: errorClass.packageName };
    }

    private getErrorIdsByStatusCode(endpoint: FernIr.HttpEndpoint): Map<number, string> {
        const errorDeclarations = endpoint.errors
            .map((responseError) => this.context.ir.errors[responseError.error.errorId])
            .filter((errorDeclaration): errorDeclaration is FernIr.ErrorDeclaration => errorDeclaration != null)
            .sort((a, b) => a.statusCode - b.statusCode);
        const errorIdsByStatusCode = new Map<number, string>();
        for (const errorDeclaration of errorDeclarations) {
            if (!errorIdsByStatusCode.has(errorDeclaration.statusCode)) {
                errorIdsByStatusCode.set(errorDeclaration.statusCode, errorDeclaration.name.errorId);
            }
        }
        return errorIdsByStatusCode;
    }

    /**
     * The endpoint's declared success status code. Falls back to 200 for undeclared or non-2xx codes,
     * and for bodiless status codes (204/205) on endpoints that return a body.
     */
    private getSuccessStatusCode(endpoint: FernIr.HttpEndpoint): number {
        const statusCode = endpoint.response?.statusCode;
        if (statusCode == null || statusCode < 200 || statusCode >= 300) {
            return 200;
        }
        if ((statusCode === 204 || statusCode === 205) && endpoint.response?.body != null) {
            return 200;
        }
        return statusCode;
    }

    private extractRequestBody(
        request: FernIr.ExampleRequestBody | undefined,
        endpoint: FernIr.HttpEndpoint
    ): unknown | undefined {
        if (!request) {
            return undefined;
        }

        let rawBody: unknown | undefined;

        if ("jsonExample" in request && request.jsonExample !== undefined) {
            rawBody = request.jsonExample;

            // Check if this is an empty object for an optional request body
            if (this.isEmptyObjectForOptionalRequest(rawBody, endpoint)) {
                return undefined;
            }
        } else {
            // Fallback for inlined request bodies that may not have a direct jsonExample
            rawBody = request._visit({
                inlinedRequestBody: (value) => {
                    const result: Record<string, unknown> = {};
                    value.properties.forEach((p) => {
                        result[getWireValue(p.name)] = this.createRawJsonExample(p.value);
                    });
                    return result;
                },
                reference: (value) => {
                    return this.createRawJsonExample(value);
                },
                _other: () => {
                    return undefined;
                }
            });
        }

        return this.pruneUnionBaseProperties(rawBody, endpoint);
    }

    /**
     * Checks if the body is an empty object ({}) for an optional request body type.
     * Empty objects for optional request bodies should be treated as undefined to skip validation.
     */
    private isEmptyObjectForOptionalRequest(body: unknown, endpoint: FernIr.HttpEndpoint): boolean {
        if (typeof body !== "object" || body === null || Array.isArray(body)) {
            return false;
        }

        const bodyKeys = Object.keys(body);
        if (bodyKeys.length !== 0) {
            return false;
        }

        const requestBody = endpoint.requestBody;
        if (!requestBody || requestBody.type !== "reference") {
            return false;
        }

        const typeRef = requestBody.requestBodyType;
        if (typeRef.type !== "container") {
            return false;
        }

        return typeRef.container.type === "optional";
    }

    /**
     * Prunes base properties from union types in the request body.
     * The Java generator does not support base properties on unions, so we need to
     * remove them from expected JSON to match the actual SDK output.
     */
    private pruneUnionBaseProperties(body: unknown, endpoint: FernIr.HttpEndpoint): unknown {
        if (!body || typeof body !== "object") {
            return body;
        }

        const requestBody = endpoint.requestBody;
        if (!requestBody) {
            return body;
        }

        if (requestBody.type === "reference") {
            const typeReference = requestBody.requestBodyType;

            if (typeReference.type === "named") {
                const typeId = typeReference.typeId;
                const typeDecl = this.context.ir.types[typeId];

                if (typeDecl && typeDecl.shape.type === "union") {
                    return this.pruneBasePropertiesFromUnion(body, typeDecl);
                }
            } else if (typeReference.type === "container" && typeReference.container.type === "list") {
                const listItemType = typeReference.container.list;

                if (listItemType.type === "named") {
                    const typeId = listItemType.typeId;
                    const typeDecl = this.context.ir.types[typeId];

                    if (typeDecl && typeDecl.shape.type === "union") {
                        return this.pruneBasePropertiesFromUnion(body, typeDecl);
                    }
                }
            }
        }

        return body;
    }

    /**
     * Removes base properties from a union type's JSON representation.
     * Also handles arrays of unions (e.g., list<BigUnion>).
     */
    private pruneBasePropertiesFromUnion(body: unknown, typeDecl: FernIr.TypeDeclaration): unknown {
        if (!body) {
            return body;
        }

        if (Array.isArray(body)) {
            return body.map((item) => this.pruneBasePropertiesFromUnion(item, typeDecl));
        }

        if (typeof body !== "object" || body === null) {
            return body;
        }

        const unionShape = typeDecl.shape;
        if (unionShape.type !== "union") {
            return body;
        }

        const basePropertyWireNames = new Set<string>();
        unionShape.baseProperties.forEach((prop) => {
            basePropertyWireNames.add(getWireValue(prop.name));
        });

        const prunedBody: Record<string, unknown> = {};
        for (const [key, value] of Object.entries(body as Record<string, unknown>)) {
            if (!basePropertyWireNames.has(key)) {
                prunedBody[key] = value;
            }
        }

        return prunedBody;
    }

    private extractResponseBody(response: FernIr.ExampleResponse | undefined): unknown | undefined {
        if (!response) {
            return undefined;
        }

        return response._visit({
            ok: (value) => {
                return value._visit({
                    body: (body) => {
                        if (!body) {
                            return undefined;
                        }
                        return this.createRawJsonExample(body);
                    },
                    stream: () => undefined,
                    sse: () => undefined,
                    _other: () => undefined
                });
            },
            error: (value) => {
                if (!value.body) {
                    return undefined;
                }
                return this.createRawJsonExample(value.body);
            },
            _other: () => undefined
        });
    }

    private extractHeaders(example: FernIr.ExampleEndpointCall): Record<string, string> {
        const headers: Record<string, string> = {};

        [...(example.serviceHeaders ?? []), ...(example.endpointHeaders ?? [])].forEach((header) => {
            headers[getWireValue(header.name)] = String(header.value.jsonExample);
        });

        return headers;
    }

    private extractQueryParams(example: FernIr.ExampleEndpointCall): Record<string, string> {
        const params: Record<string, string> = {};

        (example.queryParameters ?? []).forEach((param) => {
            params[getWireValue(param.name)] = String(param.value.jsonExample);
        });

        return params;
    }

    private extractPathParams(example: FernIr.ExampleEndpointCall): Record<string, string> {
        const params: Record<string, string> = {};

        [
            ...(example.rootPathParameters ?? []),
            ...(example.servicePathParameters ?? []),
            ...(example.endpointPathParameters ?? [])
        ].forEach((param) => {
            params[getOriginalName(param.name)] = String(param.value.jsonExample);
        });

        return params;
    }

    private createRawJsonExample(typeRef: FernIr.ExampleTypeReference): unknown {
        return typeRef.jsonExample;
    }
}

export interface WireTestExpectedError {
    statusCode: number;
    className: string;
    packageName: string;
}

export interface WireTestExample {
    id: string;
    /** ID of the matching example in the dynamic IR, used to generate the call snippet. */
    dynamicExampleId: string;
    name?: string;
    methodNameSuffix?: string;
    request: {
        body?: unknown;
        headers: Record<string, string>;
        queryParams: Record<string, string>;
        pathParams: Record<string, string>;
    };
    response: {
        statusCode: number;
        body?: unknown;
    };
    /** Set for error examples: the exception the generated client is expected to throw. */
    expectedError?: WireTestExpectedError;
}
