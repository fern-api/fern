import { constructCasingsGenerator } from "@fern-api/casings-generator";
import * as FernIr from "@fern-api/ir-sdk";
import { applyAuthToGraphqlEndpoints } from "../applyAuthToGraphqlEndpoints.js";

const casingsGenerator = constructCasingsGenerator({
    generationLanguage: undefined,
    keywords: undefined,
    smartCasing: false
});

function makeHttpPath(): FernIr.HttpPath {
    return { head: "", parts: [] };
}

function makeEndpoint(id: string, transport: FernIr.Transport | undefined, auth = false): FernIr.HttpEndpoint {
    return {
        id,
        name: id,
        displayName: undefined,
        subtitle: undefined,
        method: "POST",
        headers: [],
        responseHeaders: undefined,
        baseUrl: undefined,
        v2BaseUrls: undefined,
        basePath: undefined,
        path: makeHttpPath(),
        fullPath: makeHttpPath(),
        pathParameters: [],
        allPathParameters: [],
        queryParameters: [],
        requestBody: undefined,
        v2RequestBodies: undefined,
        sdkRequest: undefined,
        response: undefined,
        v2Responses: undefined,
        errors: [],
        auth,
        security: undefined,
        idempotent: false,
        pagination: undefined,
        userSpecifiedExamples: [],
        autogeneratedExamples: [],
        v2Examples: undefined,
        transport,
        source: undefined,
        audiences: undefined,
        retries: undefined,
        apiPlayground: undefined,
        availability: undefined,
        docs: undefined
    };
}

function makeGraphqlTransport(operationType: FernIr.GraphqlOperationType): FernIr.Transport {
    return FernIr.Transport.graphql({
        query: "",
        operationType,
        operationName: "op",
        variableDefinitions: undefined,
        arguments: undefined
    });
}

function makeService(endpoints: FernIr.HttpEndpoint[]): FernIr.HttpService {
    return {
        availability: undefined,
        name: {
            fernFilepath: { allParts: [], packagePath: [], file: undefined }
        },
        displayName: undefined,
        basePath: makeHttpPath(),
        endpoints,
        headers: [],
        pathParameters: [],
        encoding: undefined,
        transport: undefined,
        audiences: undefined
    };
}

const bearerScheme: FernIr.AuthScheme = FernIr.AuthScheme.bearer({
    token: casingsGenerator.generateName("token"),
    tokenEnvVar: undefined,
    tokenPlaceholder: undefined,
    key: "bearer",
    docs: undefined
});

function makeIr(schemes: FernIr.AuthScheme[], service: FernIr.HttpService): FernIr.IntermediateRepresentation {
    return {
        fdrApiDefinitionId: undefined,
        apiVersion: undefined,
        specVersion: undefined,
        apiName: "test-api",
        apiDisplayName: undefined,
        apiDocs: undefined,
        auth: { requirement: "ALL", schemes, docs: undefined },
        headers: [],
        idempotencyHeaders: [],
        types: {},
        graphqlFieldArguments: undefined,
        services: { service },
        webhookGroups: {},
        websocketChannels: undefined,
        errors: {},
        subpackages: {},
        rootPackage: {
            fernFilepath: { allParts: [], packagePath: [], file: undefined },
            service: undefined,
            types: [],
            errors: [],
            subpackages: [],
            webhooks: undefined,
            websocket: undefined,
            hasEndpointsInTree: false,
            hasWebSocketInTree: undefined,
            navigationConfig: undefined,
            docs: undefined
        },
        constants: {
            errorInstanceIdKey: {
                wireValue: "errorInstanceId",
                name: casingsGenerator.generateName("errorInstanceId")
            }
        },
        environments: undefined,
        basePath: undefined,
        pathParameters: [],
        errorDiscriminationStrategy: FernIr.ErrorDiscriminationStrategy.statusCode(),
        sdkConfig: {
            isAuthMandatory: false,
            hasStreamingEndpoints: false,
            hasPaginatedEndpoints: false,
            hasFileDownloadEndpoints: false,
            platformHeaders: {
                language: "X-Fern-Language",
                sdkName: "X-Fern-SDK-Name",
                sdkVersion: "X-Fern-SDK-Version",
                userAgent: undefined
            }
        },
        variables: [],
        serviceTypeReferenceInfo: {
            typesReferencedOnlyByService: {},
            sharedTypes: []
        },
        readmeConfig: undefined,
        sourceConfig: undefined,
        publishConfig: undefined,
        dynamic: undefined,
        selfHosted: undefined,
        audiences: undefined,
        generationMetadata: undefined,
        apiPlayground: undefined,
        casingsConfig: undefined
    };
}

describe("applyAuthToGraphqlEndpoints", () => {
    it("authes graphql query/mutation endpoints when the IR has auth schemes", () => {
        const query = makeEndpoint("q", makeGraphqlTransport("QUERY"));
        const mutation = makeEndpoint("m", makeGraphqlTransport("MUTATION"));
        const result = applyAuthToGraphqlEndpoints(makeIr([bearerScheme], makeService([query, mutation])));
        const endpoints = result.services.service?.endpoints ?? [];
        expect(endpoints.map((e) => e.auth)).toEqual([true, true]);
    });

    it("authes graphql subscriptions too (auth resolves lazily in the WS connect)", () => {
        const subscription = makeEndpoint("s", makeGraphqlTransport("SUBSCRIPTION"));
        const result = applyAuthToGraphqlEndpoints(makeIr([bearerScheme], makeService([subscription])));
        expect(result.services.service?.endpoints[0]?.auth).toBe(true);
    });

    it("is a no-op when the IR has no auth schemes", () => {
        const query = makeEndpoint("q", makeGraphqlTransport("QUERY"));
        const result = applyAuthToGraphqlEndpoints(makeIr([], makeService([query])));
        expect(result.services.service?.endpoints[0]?.auth).toBe(false);
    });

    it("does not touch non-graphql endpoints", () => {
        const rest = makeEndpoint("r", undefined);
        const result = applyAuthToGraphqlEndpoints(makeIr([bearerScheme], makeService([rest])));
        expect(result.services.service?.endpoints[0]?.auth).toBe(false);
    });
});
