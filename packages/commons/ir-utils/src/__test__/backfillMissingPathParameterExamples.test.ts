import * as FernIr from "@fern-api/ir-sdk";

import { backfillMissingPathParameterExamples } from "../examples/backfillMissingPathParameterExamples.js";
import { getOriginalName } from "../utils/namesUtils.js";
import { casingsGenerator, EMPTY_FERN_FILEPATH, makeMinimalIr } from "./utils/makeMinimalIr.js";

const STRING_TYPE = FernIr.TypeReference.primitive({
    v1: "STRING",
    v2: FernIr.PrimitiveTypeV2.string({ default: undefined, validation: undefined })
});

const DATETIME_TYPE = FernIr.TypeReference.primitive({
    v1: "DATE_TIME",
    v2: FernIr.PrimitiveTypeV2.dateTime({ default: undefined })
});

const ENUM_TYPE_ID = "type_:Color";

function makePathParameter({
    name,
    valueType = STRING_TYPE,
    location,
    clientDefault
}: {
    name: string;
    valueType?: FernIr.TypeReference;
    location: FernIr.PathParameterLocation;
    clientDefault?: FernIr.Literal;
}): FernIr.PathParameter {
    return {
        name: casingsGenerator.generateName(name),
        valueType,
        location,
        variable: undefined,
        clientDefault,
        v2Examples: undefined,
        explode: undefined,
        docs: undefined
    };
}

function makeEnumTypeDeclaration(): FernIr.TypeDeclaration {
    return {
        name: {
            typeId: ENUM_TYPE_ID,
            fernFilepath: EMPTY_FERN_FILEPATH,
            name: casingsGenerator.generateName("Color"),
            displayName: undefined
        },
        shape: FernIr.Type.enum({
            default: undefined,
            forwardCompatible: undefined,
            values: ["red", "blue"].map((value) => ({
                name: casingsGenerator.generateNameAndWireValue({ name: value, wireValue: value }),
                docs: undefined,
                availability: undefined,
                casing: undefined
            }))
        }),
        autogeneratedExamples: [],
        userProvidedExamples: [],
        v2Examples: undefined,
        referencedTypes: new Set(),
        encoding: undefined,
        source: undefined,
        inline: undefined,
        docs: undefined,
        availability: undefined
    };
}

function makeExample({
    endpointPathParameters = [],
    servicePathParameters = [],
    rootPathParameters = [],
    url
}: {
    endpointPathParameters?: FernIr.ExamplePathParameter[];
    servicePathParameters?: FernIr.ExamplePathParameter[];
    rootPathParameters?: FernIr.ExamplePathParameter[];
    url: string;
}): FernIr.ExampleEndpointCall {
    return {
        id: "example-id",
        name: casingsGenerator.generateName("Example name"),
        url,
        rootPathParameters,
        servicePathParameters,
        endpointPathParameters,
        serviceHeaders: [],
        endpointHeaders: [],
        queryParameters: [],
        request: undefined,
        response: FernIr.ExampleResponse.ok(FernIr.ExampleEndpointSuccessResponse.body(undefined)),
        docs: undefined
    };
}

function makeStringExamplePathParameter(name: string, value: string): FernIr.ExamplePathParameter {
    return {
        name: casingsGenerator.generateName(name),
        value: {
            jsonExample: value,
            shape: FernIr.ExampleTypeReferenceShape.primitive(FernIr.ExamplePrimitive.string({ original: value }))
        }
    };
}

function makeIr({
    rootPathParameters = [],
    servicePathParameters = [],
    endpointPathParameters = [],
    examples,
    autogeneratedExamples = [],
    types = {}
}: {
    rootPathParameters?: FernIr.PathParameter[];
    servicePathParameters?: FernIr.PathParameter[];
    endpointPathParameters?: FernIr.PathParameter[];
    examples: FernIr.ExampleEndpointCall[];
    autogeneratedExamples?: FernIr.ExampleEndpointCall[];
    types?: Record<FernIr.TypeId, FernIr.TypeDeclaration>;
}): FernIr.IntermediateRepresentation {
    const path: FernIr.HttpPath = {
        head: "/objects/",
        parts: endpointPathParameters.map((pathParameter, index) => ({
            pathParameter: getOriginalName(pathParameter.name),
            tail: index === endpointPathParameters.length - 1 ? "" : "/"
        }))
    };
    const endpoint: FernIr.HttpEndpoint = {
        id: "endpoint_service.upload",
        name: casingsGenerator.generateName("upload"),
        displayName: undefined,
        subtitle: undefined,
        method: FernIr.HttpMethod.Post,
        headers: [],
        responseHeaders: undefined,
        baseUrl: undefined,
        v2BaseUrls: undefined,
        basePath: undefined,
        path,
        fullPath: path,
        pathParameters: endpointPathParameters,
        allPathParameters: [...rootPathParameters, ...servicePathParameters, ...endpointPathParameters],
        queryParameters: [],
        requestBody: undefined,
        v2RequestBodies: undefined,
        sdkRequest: undefined,
        response: undefined,
        v2Responses: undefined,
        errors: [],
        auth: false,
        security: undefined,
        idempotent: false,
        pagination: undefined,
        userSpecifiedExamples: examples.map((example) => ({ example, codeSamples: undefined })),
        autogeneratedExamples: autogeneratedExamples.map((example) => ({ example })),
        v2Examples: undefined,
        transport: undefined,
        source: undefined,
        audiences: undefined,
        retries: undefined,
        globalParameters: undefined,
        apiPlayground: undefined,
        availability: undefined,
        docs: undefined
    };
    const service: FernIr.HttpService = {
        availability: undefined,
        name: { fernFilepath: EMPTY_FERN_FILEPATH },
        displayName: undefined,
        basePath: { head: "", parts: [] },
        endpoints: [endpoint],
        headers: [],
        pathParameters: servicePathParameters,
        encoding: undefined,
        transport: undefined,
        audiences: undefined
    };
    return makeMinimalIr({
        pathParameters: rootPathParameters,
        services: { service_service: service },
        types
    });
}

function getEndpoint(ir: FernIr.IntermediateRepresentation): FernIr.HttpEndpoint {
    const endpoint = Object.values(ir.services)[0]?.endpoints[0];
    if (endpoint == null) {
        throw new Error("expected an endpoint");
    }
    return endpoint;
}

function getUserExample(ir: FernIr.IntermediateRepresentation): FernIr.ExampleEndpointCall {
    const example = getEndpoint(ir).userSpecifiedExamples[0]?.example;
    if (example == null) {
        throw new Error("expected a user-specified example");
    }
    return example;
}

describe("backfillMissingPathParameterExamples", () => {
    it("backfills a path parameter the example does not supply", () => {
        const ir = makeIr({
            endpointPathParameters: [makePathParameter({ name: "objectPath", location: "ENDPOINT" })],
            examples: [makeExample({ url: "/objects/undefined" })]
        });

        backfillMissingPathParameterExamples({ ir });

        const example = getUserExample(ir);
        expect(example.endpointPathParameters).toHaveLength(1);
        expect(example.endpointPathParameters[0]?.value.jsonExample).toBe("objectPath");
        expect(example.url).toBe("/objects/objectPath");
        expect(example.url).not.toContain("undefined");
    });

    it("leaves a supplied path parameter untouched", () => {
        const supplied = makeStringExamplePathParameter("objectPath", "my/object.txt");
        const ir = makeIr({
            endpointPathParameters: [makePathParameter({ name: "objectPath", location: "ENDPOINT" })],
            examples: [makeExample({ url: "/objects/my/object.txt", endpointPathParameters: [supplied] })]
        });

        backfillMissingPathParameterExamples({ ir });

        const example = getUserExample(ir);
        expect(example.endpointPathParameters).toEqual([supplied]);
        expect(example.url).toBe("/objects/my/object.txt");
    });

    it("leaves a path parameter with a client default out of the example, but uses it in the url", () => {
        const ir = makeIr({
            endpointPathParameters: [
                makePathParameter({
                    name: "tenantId",
                    location: "ENDPOINT",
                    clientDefault: FernIr.Literal.string("acme")
                })
            ],
            examples: [makeExample({ url: "/objects/undefined" })]
        });

        backfillMissingPathParameterExamples({ ir });

        const example = getUserExample(ir);
        expect(example.endpointPathParameters).toEqual([]);
        expect(example.url).toBe("/objects/acme");
    });

    it("interpolates the client default into the url of a backfilled example", () => {
        const ir = makeIr({
            endpointPathParameters: [
                makePathParameter({
                    name: "tenantId",
                    location: "ENDPOINT",
                    clientDefault: FernIr.Literal.string("acme")
                }),
                makePathParameter({ name: "objectPath", location: "ENDPOINT" })
            ],
            examples: [makeExample({ url: "/objects/undefined/undefined" })]
        });

        backfillMissingPathParameterExamples({ ir });

        const example = getUserExample(ir);
        expect(example.endpointPathParameters.map((pathParameter) => getOriginalName(pathParameter.name))).toEqual([
            "objectPath"
        ]);
        expect(example.url).toBe("/objects/acme/objectPath");
    });

    it("backfills an enum path parameter", () => {
        const ir = makeIr({
            endpointPathParameters: [
                makePathParameter({
                    name: "color",
                    location: "ENDPOINT",
                    valueType: FernIr.TypeReference.named({
                        typeId: ENUM_TYPE_ID,
                        fernFilepath: EMPTY_FERN_FILEPATH,
                        name: casingsGenerator.generateName("Color"),
                        default: undefined,
                        inline: undefined,
                        displayName: undefined
                    })
                })
            ],
            examples: [makeExample({ url: "/objects/undefined" })],
            types: { [ENUM_TYPE_ID]: makeEnumTypeDeclaration() }
        });

        backfillMissingPathParameterExamples({ ir });

        const example = getUserExample(ir);
        expect(example.endpointPathParameters[0]?.value.jsonExample).toBe("red");
        expect(example.url).toBe("/objects/red");
    });

    it("backfills a datetime path parameter", () => {
        const ir = makeIr({
            endpointPathParameters: [
                makePathParameter({ name: "asOf", location: "ENDPOINT", valueType: DATETIME_TYPE })
            ],
            examples: [makeExample({ url: "/objects/undefined" })]
        });

        backfillMissingPathParameterExamples({ ir });

        const example = getUserExample(ir);
        expect(typeof example.endpointPathParameters[0]?.value.jsonExample).toBe("string");
        expect(example.url).not.toContain("undefined");
    });

    it("backfills into the root, service and endpoint buckets separately", () => {
        const ir = makeIr({
            rootPathParameters: [makePathParameter({ name: "rootId", location: "ROOT" })],
            servicePathParameters: [makePathParameter({ name: "serviceId", location: "SERVICE" })],
            endpointPathParameters: [makePathParameter({ name: "endpointId", location: "ENDPOINT" })],
            examples: [makeExample({ url: "/objects/undefined" })]
        });

        backfillMissingPathParameterExamples({ ir });

        const example = getUserExample(ir);
        expect(example.rootPathParameters.map((p) => getOriginalName(p.name))).toEqual(["rootId"]);
        expect(example.servicePathParameters.map((p) => getOriginalName(p.name))).toEqual(["serviceId"]);
        expect(example.endpointPathParameters.map((p) => getOriginalName(p.name))).toEqual(["endpointId"]);
    });

    it("is a no-op for an endpoint with no path parameters", () => {
        const ir = makeIr({ examples: [makeExample({ url: "/objects/" })] });
        const before = getUserExample(ir);

        backfillMissingPathParameterExamples({ ir });

        const after = getUserExample(ir);
        expect(after.url).toBe("/objects/");
        expect(after.rootPathParameters).toHaveLength(0);
        expect(after.servicePathParameters).toHaveLength(0);
        expect(after.endpointPathParameters).toHaveLength(0);
        expect(after).toBe(before);
    });

    it("preserves the example id and name", () => {
        const ir = makeIr({
            endpointPathParameters: [makePathParameter({ name: "objectPath", location: "ENDPOINT" })],
            examples: [makeExample({ url: "/objects/undefined" })]
        });

        backfillMissingPathParameterExamples({ ir });

        const example = getUserExample(ir);
        expect(example.id).toBe("example-id");
        expect(example.name).toEqual(casingsGenerator.generateName("Example name"));
    });

    it("does not touch autogenerated examples", () => {
        const ir = makeIr({
            endpointPathParameters: [makePathParameter({ name: "objectPath", location: "ENDPOINT" })],
            examples: [],
            autogeneratedExamples: [makeExample({ url: "/objects/undefined" })]
        });

        backfillMissingPathParameterExamples({ ir });

        const autogenerated = getEndpoint(ir).autogeneratedExamples[0]?.example;
        expect(autogenerated?.endpointPathParameters).toHaveLength(0);
        expect(autogenerated?.url).toBe("/objects/undefined");
    });
});
