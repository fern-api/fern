import { AbsoluteFilePath, join, RelativeFilePath } from "@fern-api/fs-utils";
import { getOriginalName, getWireValue } from "@fern-api/ir-utils";
import { OSSWorkspace } from "@fern-api/lazy-fern-workspace";
import { createMockTaskContext } from "@fern-api/task-context";
import { loadAPIWorkspace } from "@fern-api/workspace-loader";

const FIXTURES_DIR = join(AbsoluteFilePath.of(__dirname), RelativeFilePath.of("fixtures"));

async function getIRForFixture(fixtureName: string) {
    const fixturePath = join(FIXTURES_DIR, RelativeFilePath.of(fixtureName), RelativeFilePath.of("fern"));
    const context = createMockTaskContext();
    const workspace = await loadAPIWorkspace({
        absolutePathToWorkspace: fixturePath,
        context,
        cliVersion: "0.0.0",
        workspaceName: fixtureName
    });
    if (!workspace.didSucceed) {
        throw new Error(`Failed to load OpenAPI fixture ${fixtureName}\n${JSON.stringify(workspace.failures)}`);
    }
    if (!(workspace.workspace instanceof OSSWorkspace)) {
        throw new Error(`Expected OSSWorkspace for fixture ${fixtureName}`);
    }
    return workspace.workspace.getIntermediateRepresentation({
        context,
        audiences: { type: "all" },
        enableUniqueErrorsPerEndpoint: false,
        generateV1Examples: true,
        logWarnings: false
    });
}

describe("parameter examples declared inside the schema", () => {
    it("should use the referenced object schema's example for a JSON-encoded header", async () => {
        const ir = await getIRForFixture("parameter-content");

        const endpoint = Object.values(ir.services)
            .flatMap((service) => service.endpoints)
            .find((endpoint) => getOriginalName(endpoint.name) === "getAccountPhoto");
        expect(endpoint).toBeDefined();

        const header = endpoint?.headers.find((header) => getWireValue(header.name) === "Api-Arg");
        expect(header).toBeDefined();

        const expectedExample = {
            circle_crop: false,
            dbx_account_id: "dbid:plant-fern-123",
            expect_account_photo: true,
            size: "128x128"
        };
        expect(Object.values(header?.v2Examples?.userSpecifiedExamples ?? {})).toEqual([expectedExample]);
        expect(header?.v2Examples?.autogeneratedExamples).toEqual({});

        const endpointExamples = Object.values(endpoint?.v2Examples?.userSpecifiedExamples ?? {}).concat(
            Object.values(endpoint?.v2Examples?.autogeneratedExamples ?? {})
        );
        expect(endpointExamples.length).toBeGreaterThan(0);
        for (const example of endpointExamples) {
            expect(example.request?.headers?.["Api-Arg"]).toEqual(expectedExample);
        }
    });
});
