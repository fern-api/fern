import { access, readFile } from "node:fs/promises";
import { join } from "node:path";
import {
    GENERATORS_CONFIGURATION_FILENAME,
    GENERATORS_CONFIGURATION_FILENAME_ALTERNATIVE,
    LEGACY_GENERATORS_CONFIGURATION_FILENAME
} from "@fern-api/configuration-loader";
import YAML from "yaml";

import type { RubiconDiagnostic } from "./types.js";

/** First line of every generators.yml rubicon writes; it marks the file as safe to regenerate. */
export const RUBICON_HEADER = "# Generated by fern sdk rubicon";

/** Where migrate's legacy file goes when rubicon takes the generators slot. */
export const PARKED_LEGACY_FILENAME = "generators.legacy.pre-rubicon.yml";

export interface Rename {
    from: string;
    to: string;
}

export interface GeneratorsSlot {
    generatorsPath: string;
    /** The previous rubicon output, parsed, for the D12 carry-over. */
    previous: Record<string, unknown> | undefined;
    renames: Rename[];
    removals: string[];
    rollback: string[];
}

/**
 * Decides whether rubicon may write generators.yml into `folder` (RUBICON-PLAN.md, D5). The Fern CLI
 * allows one active generators file per folder, and refuses generators.yml next to
 * generators.legacy.yml, the file `fern sdk migrate` leaves behind.
 */
export async function planGeneratorsSlot({
    folder,
    force
}: {
    folder: string;
    force: boolean;
}): Promise<{ slot: GeneratorsSlot | undefined; diagnostics: RubiconDiagnostic[] }> {
    const generatorsPath = join(folder, GENERATORS_CONFIGURATION_FILENAME);
    const alternativePath = join(folder, GENERATORS_CONFIGURATION_FILENAME_ALTERNATIVE);
    const legacyPath = join(folder, LEGACY_GENERATORS_CONFIGURATION_FILENAME);
    const parkedPath = join(folder, PARKED_LEGACY_FILENAME);
    const [generators, alternative, legacy] = await Promise.all([
        readOptional(generatorsPath),
        readOptional(alternativePath),
        readOptional(legacyPath)
    ]);
    const empty: GeneratorsSlot = { generatorsPath, previous: undefined, renames: [], removals: [], rollback: [] };

    if ((generators != null || alternative != null) && legacy != null) {
        return stop(
            generators != null ? GENERATORS_CONFIGURATION_FILENAME : GENERATORS_CONFIGURATION_FILENAME_ALTERNATIVE,
            "RUBICON_GENERATORS_CONFLICT",
            `${folder} holds both a generators file and ${LEGACY_GENERATORS_CONFIGURATION_FILENAME}; the Fern CLI already refuses this folder.`,
            "Keep only one of them, then run rubicon again."
        );
    }

    if (generators != null) {
        if (generators.startsWith(RUBICON_HEADER)) {
            return { slot: { ...empty, previous: parseRecord(generators) }, diagnostics: [] };
        }
        return force
            ? { slot: empty, diagnostics: [] }
            : stop(
                  GENERATORS_CONFIGURATION_FILENAME,
                  "RUBICON_GENERATORS_EXISTS",
                  `${generatorsPath} exists and was not written by rubicon.`,
                  "Pass --force to replace it, or move it aside."
              );
    }

    if (alternative != null) {
        return force
            ? { slot: { ...empty, removals: [alternativePath] }, diagnostics: [] }
            : stop(
                  GENERATORS_CONFIGURATION_FILENAME_ALTERNATIVE,
                  "RUBICON_GENERATORS_EXISTS",
                  `${alternativePath} exists and was not written by rubicon.`,
                  "Pass --force to replace it with generators.yml, or move it aside."
              );
    }

    if (legacy != null) {
        const activeGroups = Object.keys(groupsOf(parseRecord(legacy)));
        if (activeGroups.length > 0) {
            return stop(
                LEGACY_GENERATORS_CONFIGURATION_FILENAME,
                "RUBICON_LEGACY_GROUPS_ACTIVE",
                `${legacyPath} still runs these groups: ${activeGroups.join(", ")}. Setting it aside would switch them off.`,
                "Migrate those groups with `fern sdk migrate --group <name>`, or remove them, then run rubicon again."
            );
        }
        if (await exists(parkedPath)) {
            return stop(
                PARKED_LEGACY_FILENAME,
                "RUBICON_RENAME_CONFLICT",
                `Cannot rename ${legacyPath}: ${parkedPath} already exists.`,
                `Remove or rename ${parkedPath}, then run rubicon again.`
            );
        }
        return {
            slot: {
                ...empty,
                renames: [{ from: legacyPath, to: parkedPath }],
                rollback: [`Delete ${generatorsPath}.`, `Rename ${parkedPath} back to ${legacyPath}.`]
            },
            diagnostics: []
        };
    }

    return { slot: empty, diagnostics: [] };
}

function stop(
    path: string,
    code: string,
    message: string,
    action: string
): { slot: undefined; diagnostics: RubiconDiagnostic[] } {
    return { slot: undefined, diagnostics: [{ severity: "error", path, code, message, action }] };
}

function groupsOf(document: Record<string, unknown> | undefined): Record<string, unknown> {
    const groups = document?.groups;
    return isRecord(groups) ? groups : {};
}

function parseRecord(contents: string): Record<string, unknown> | undefined {
    const parsed: unknown = YAML.parse(contents);
    return isRecord(parsed) ? parsed : undefined;
}

async function readOptional(path: string): Promise<string | undefined> {
    try {
        return await readFile(path, "utf8");
    } catch (error) {
        if (isMissing(error)) {
            return undefined;
        }
        throw error;
    }
}

async function exists(path: string): Promise<boolean> {
    try {
        await access(path);
        return true;
    } catch (error) {
        if (isMissing(error)) {
            return false;
        }
        throw error;
    }
}

function isMissing(error: unknown): boolean {
    return typeof error === "object" && error != null && "code" in error && error.code === "ENOENT";
}

function isRecord(value: unknown): value is Record<string, unknown> {
    return value !== null && typeof value === "object" && !Array.isArray(value);
}
