import { assertNever } from "@fern-api/core-utils";
import { RawSchemas } from "@fern-api/fern-definition-schema";
import { ObjectProperty, ObjectPropertyAccess, Type, XmlPropertyEncoding, XmlPropertyKind } from "@fern-api/ir-sdk";

import { FernFileContext } from "../../FernFileContext.js";
import { parseTypeName } from "../../utils/parseTypeName.js";
import { convertDeclaration } from "../convertDeclaration.js";

export function convertObjectTypeDeclaration({
    object,
    file,
    withinXmlElement = false
}: {
    object: RawSchemas.ObjectSchema;
    file: FernFileContext;
    withinXmlElement?: boolean;
}): Type {
    return Type.object({
        extends: getExtensionsAsList(object.extends).map((extended) => parseTypeName({ typeName: extended, file })),
        properties: getObjectPropertiesFromRawObjectSchema(object, file, withinXmlElement),
        extraProperties: object["extra-properties"] ?? false,
        extendedProperties: undefined,
        // Populated by the computeUnionBasePropertyDedupe post-build pass; undefined here.
        deferredUnionBaseProperties: undefined
    });
}

export function getObjectPropertiesFromRawObjectSchema(
    object: RawSchemas.ObjectSchema,
    file: FernFileContext,
    withinXmlElement = false
): ObjectProperty[] {
    if (object.properties == null) {
        return [];
    }
    return Object.entries(object.properties).map(([propertyKey, propertyDefinition]) => ({
        ...convertDeclaration(propertyDefinition),
        name: file.casingsGenerator.generateNameAndWireValue({
            wireValue: propertyKey,
            name: getPropertyName({ propertyKey, property: propertyDefinition }).name
        }),
        valueType: file.parseTypeReference(propertyDefinition),
        propertyAccess: getPropertyAccess({ property: propertyDefinition }),
        defaultValue: typeof propertyDefinition !== "string" ? propertyDefinition.default : undefined,
        xml: getXmlPropertyEncoding({ property: propertyDefinition, withinXmlElement }),
        v2Examples: {
            userSpecifiedExamples: {},
            autogeneratedExamples: {}
        }
    }));
}

function getXmlPropertyEncoding({
    property,
    withinXmlElement
}: {
    property: RawSchemas.ObjectPropertySchema;
    withinXmlElement: boolean;
}): XmlPropertyEncoding | undefined {
    const xml = typeof property === "string" ? undefined : property.encoding?.xml;
    if (xml == null) {
        return withinXmlElement
            ? { kind: XmlPropertyKind.Element, name: undefined, wrapped: undefined, listSeparator: undefined }
            : undefined;
    }
    return {
        kind: xml.text ? XmlPropertyKind.Text : xml.attribute ? XmlPropertyKind.Attribute : XmlPropertyKind.Element,
        name: xml.name,
        wrapped: xml.wrapped,
        listSeparator: xml.separator
    };
}

export function getExtensionsAsList(extensions: string | string[] | undefined): string[] {
    if (extensions == null) {
        return [];
    }
    if (typeof extensions === "string") {
        return [extensions];
    }
    return extensions;
}

export function getPropertyName({
    propertyKey,
    property
}: {
    propertyKey: string;
    property: RawSchemas.ObjectPropertySchema;
}): { name: string; wasExplicitlySet: boolean } {
    if (typeof property !== "string" && property.name != null) {
        return {
            name: property.name,
            wasExplicitlySet: true
        };
    }

    return {
        name: propertyKey,
        wasExplicitlySet: false
    };
}

export function getPropertyAccess({
    property
}: {
    property: RawSchemas.ObjectPropertySchema;
}): ObjectPropertyAccess | undefined {
    if (typeof property === "string") {
        return undefined;
    }
    const propertyAccess = property["access"];
    if (propertyAccess != null) {
        switch (propertyAccess) {
            case "read-only":
                return ObjectPropertyAccess.ReadOnly;
            case "write-only":
                return ObjectPropertyAccess.WriteOnly;
            default:
                assertNever(propertyAccess);
        }
    }
    return undefined;
}
